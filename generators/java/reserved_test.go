var update = flag.Bool("update", false, "rewrite tests/conformance/java/reserved.{yaml,json} from the reserved-name list")

// reservedNames is every name on the Java list, sorted.
func reservedNames() []string {
	var names []string
	for _, set := range []map[string]bool{javaKeywords, javaStatics, javaQualifiers} {
		for n := range set {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	return names
}

// reservedYAML is a schema that uses every reserved name as a field of a message,
// of a nested struct, and as an option of a union -- plus the union's own slot
// name `which`, `v`, the parameter name of every union setter, and the one path
// clash a decoder frame name can hit: inner.inner2 beside a field inner_inner2.
func reservedYAML(names []string) string {
	var b strings.Builder
	b.WriteString("# Generated by TestReservedSchemaFile from generators/java/reserved.go;\n")
	b.WriteString("# do not edit. Regenerate: go test ./generators/java -run TestReservedSchemaFile -update\n")
	b.WriteString("# The collision test: every reserved name as a field must compile warning-free and round-trip.\n")
	var fields strings.Builder
	var opts []string
	for i, n := range names {
		fmt.Fprintf(&fields, "      %q: { id: %d, type: u8 }\n", n, i)
		opts = append(opts, fmt.Sprintf("%q: { id: %d, type: u8 }", n, i))
	}
	k := len(names)
	opts = append(opts, fmt.Sprintf("which: { id: %d, type: u8 }", k), fmt.Sprintf("v: { id: %d, type: u8 }", k+1))
	fmt.Fprintf(&b, `version: 1
$defs:
  struct:
    Inner2:
      x: { id: 0, type: u8 }
    Inner:
%s      inner2: { id: %d, type: struct, fields: { $ref: '#/$defs/struct/Inner2' } }
messages:
  m:
    payload:
%s      inner:        { id: %d, type: struct, fields: { $ref: '#/$defs/struct/Inner' } }
      inner_inner2: { id: %d, type: struct, fields: { $ref: '#/$defs/struct/Inner2' } }
      u:            { id: %d, type: union, oneof: { %s } }
`, fields.String(), k, fields.String(), k, k+1, k+2, strings.Join(opts, ", "))
	return b.String()
}

// reservedJSON is the harness input for m: every reserved field and nested one
// at a non-default value, and the union holding option `v` -- the one a setter
// without `this.` would assign to its own parameter.
func reservedJSON(names []string) string {
	top := map[string]any{}
	inner := map[string]any{"inner2": map[string]any{"x": 5}}
	for i, n := range names {
		top[n] = i + 1
		inner[n] = i + 2
	}
	top["inner"] = inner
	top["inner_inner2"] = map[string]any{"x": 6}
	top["u"] = map[string]any{"v": 9}
	b, _ := json.MarshalIndent(top, "", "  ")
	return string(b) + "\n"
}

// TestReservedSchemaFile keeps the checked-in collision schema and its input in
// step with the list: the conformance suite compiles that file warning-free and
// round-trips it (tests/conformance/java/run.sh), so a name added to reserved.go
// is covered once the file is regenerated -- and this test fails until it is.
func TestReservedSchemaFile(t *testing.T) {
	names := reservedNames()
	for path, want := range map[string]string{
		"../../tests/conformance/java/reserved.yaml": reservedYAML(names),
		"../../tests/conformance/java/reserved.json": reservedJSON(names),
	} {
		if *update {
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s is out of step with the reserved-name list; regenerate with -update", path)
		}
	}
}

// TestReservedNamesAreMangled: every name on the list is a field with a trailing
// underscore, in the message and the nested struct; a union setter assigns its
// slot through `this.`.
func TestReservedNamesAreMangled(t *testing.T) {
	names := reservedNames()
	files := genJavaFromYAML(t, reservedYAML(names), map[string]any{})
	var all strings.Builder
	for _, c := range files {
		all.WriteString(c)
	}
	for _, n := range names {
		if got := len(regexp.MustCompile(`(?m)^    public long `+regexp.QuoteMeta(n)+`_;$`).FindAllString(all.String(), -1)); got != 2 {
			t.Errorf("field %q is the field %s_ in %d of the 2 classes", n, n, got)
		}
	}
	if !strings.Contains(all.String(), "public void setV(long v) { which = V_ID; this.v = v; }") {
		t.Error("the setter of option `v` does not assign through this.v")
	}
}

// TestFieldNameCollision: two fields that give one Java field (`int` is mangled
// to `int_`) are a generation error naming both, not a duplicate variable.
func TestFieldNameCollision(t *testing.T) {
	src := "version: 1\nmessages:\n  m:\n    payload:\n      int: { id: 0, type: u8 }\n      int_: { id: 1, type: u8 }\n"
	doc, err := parser.Parse([]byte(src), "c.yaml")
	if err != nil {
		t.Fatal(err)
	}
	s, err := model.Build(doc)
	if err != nil {
		t.Fatal(err)
	}
	if err := analysis.Analyze(s); err != nil {
		t.Fatal(err)
	}
	if _, err := (&Backend{}).Generate(s, map[string]any{}); err == nil || !strings.Contains(err.Error(), "both generate the field") {
		t.Errorf("want a collision error, got %v", err)
	}
}

// publicClassBody is the body of a Java file's public top-level class -- the
// region where that class's fields are in scope (its nested classes included,
// a second top-level class in the same file not). Comments and string literals
// are blanked first so their braces and dots do not count.
func publicClassBody(src string) string {
	src = regexp.MustCompile(`(?s)/\*.*?\*/|//[^\n]*|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'`).ReplaceAllString(src, `""`)
	loc := regexp.MustCompile(`(?m)^public (?:final )?class \w+[^{]*\{`).FindStringIndex(src)
	if loc == nil {
		return ""
	}
	depth := 1
	for i := loc[1]; i < len(src); i++ {
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return src[loc[1]:i]
			}
		}
	}
	return src[loc[1]:]
}

// TestJavaNamesInScope is the drift guard for javaStatics and javaQualifiers:
// over the whole corpus, realworld set and example, every static field a public
// generated class declares and every name its body uses as an expression
// qualifier must be on the list (union option ids and `_`-prefixed names aside,
// which no schema field can spell or which checkUnionNames owns). A backend that
// starts writing `Math.max(...)` or declares another static fails here until the
// name is reserved -- instead of shipping a class a field named `Math` breaks.
// Lower-case qualifiers other than package roots are locals and parameters,
// which shadow a field anyway.
func TestJavaNamesInScope(t *testing.T) {
	defs, _ := filepath.Glob("../../tests/matrix/corpus/defs/*.yaml")
	rw, _ := filepath.Glob("../../examples/messages/realworld/*.yaml")
	defs = append(append(defs, rw...), "../../examples/messages/example.yaml")
	staticRe := regexp.MustCompile(`\bstatic final [\w<>\[\], ]+? (\w+)\s*[=;]`)
	qualRe := regexp.MustCompile(`(?:^|[^\w.])([A-Za-z_]\w*)\.[A-Za-z_]`)
	optID := regexp.MustCompile(`^[A-Z0-9_]+_ID$`)
	for _, def := range defs {
		doc, err := parser.Load(def) // Load, not Parse: cross_file.yaml refers to ../shared
		if err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		if _, err := doc.Resolve(); err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		s, err := model.Build(doc)
		if err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		if err := analysis.Analyze(s); err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		files, err := (&Backend{}).Generate(s, map[string]any{"emit": "project"})
		if err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		for _, f := range files {
			// Main.java is the harness: its own class, where no message field is in scope.
			if !strings.HasSuffix(f.Path, ".java") || !strings.Contains(f.Path, "src/main/java/message/") || strings.HasSuffix(f.Path, "/Main.java") {
				continue
			}
			body := publicClassBody(string(f.Content))
			for _, m := range staticRe.FindAllStringSubmatch(body, -1) {
				n := m[1]
				if strings.HasPrefix(n, "_") || optID.MatchString(n) || javaStatics[n] {
					continue
				}
				t.Errorf("%s (%s): static field %s is not on javaStatics", f.Path, filepath.Base(def), n)
			}
			for _, m := range qualRe.FindAllStringSubmatch(body, -1) {
				n := m[1]
				if n == "this" || !(n[0] >= 'A' && n[0] <= 'Z' || n == "java" || n == "javax" || n == "org") {
					continue
				}
				if !javaQualifiers[n] {
					t.Errorf("%s (%s): qualifier %s is not on javaQualifiers", f.Path, filepath.Base(def), n)
				}
			}
		}
	}
}

// TestFrameNamesAreDistinct: decoder frames are named by the schema path joined
// with `_` and looked up by name, so the path inner.inner2 and a field
// inner_inner2 must be two frames -- sharing one, the decoder stored the field
// inner_inner2 into inner.inner2 without an error.
func TestFrameNamesAreDistinct(t *testing.T) {
	src := "version: 1\n$defs:\n  struct:\n    B: { x: { id: 0, type: u8 } }\n    A: { b: { id: 0, type: struct, fields: { $ref: '#/$defs/struct/B' } } }\n" +
		"messages:\n  m:\n    payload:\n      a: { id: 0, type: struct, fields: { $ref: '#/$defs/struct/A' } }\n      a_b: { id: 1, type: struct, fields: { $ref: '#/$defs/struct/B' } }\n"
	doc, err := parser.Parse([]byte(src), "f.yaml")
	if err != nil {
		t.Fatal(err)
	}
	s, err := model.Build(doc)
	if err != nil {
		t.Fatal(err)
	}
	if err := analysis.Analyze(s); err != nil {
		t.Fatal(err)
	}
	g := &gen{schema: s}
	seen := map[string]bool{}
	for _, fr := range g.frames(s.Messages[0]) {
		if seen[fr.loc] {
			t.Errorf("two decoder frames are both named %s", fr.loc)
		}
		seen[fr.loc] = true
	}
	if !seen["Root_a_b"] || !seen["Root_a__b"] {
		t.Errorf("want frames Root_a_b and Root_a__b, got %v", seen)
	}
}
