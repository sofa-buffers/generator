// Package java is the Java throughput backend (PLAN §6.4): classes with
// marshal over OStream and a flat-visitor decode (Visitor) against corelib-java.
// The Visitor is flat (sequenceBegin/end, no child visitors), so decode is a
// (location, id) state machine with a location stack — same as Rust/C#. Java has
// no unsigned ints, so all integers map to long (u64 handled via
// Long.toUnsignedString / parseUnsignedLong in the JSON harness).
package java

import (
	"fmt"
	"strings"

	"github.com/sofa-buffers/generator/internal/generator"
	"github.com/sofa-buffers/generator/internal/ir"
)

func init() { generator.Register(&Backend{}) }

// Backend implements generator.Backend for Java.
type Backend struct{}

func (*Backend) Lang() string { return "java" }

func (*Backend) Generate(s *ir.Schema, cfg map[string]any) ([]generator.File, error) {
	g := &gen{schema: s, pkg: cfgString(cfg, "package", "message"), banner: cfgString(cfg, "tool_banner", "sofabgen"), license: generator.LicenseID(cfg), limits: resolveLimits(s, cfg), size: generator.NewSizePolicy(cfg)}
	dir := "src/main/java/" + strings.ReplaceAll(g.pkg, ".", "/") + "/"
	var files []generator.File
	files = append(files, generator.File{Path: dir + "Sbuf.java", Content: g.sbufSupport()})
	for _, m := range s.Messages {
		files = append(files, generator.File{Path: dir + exported(m.Name) + ".java", Content: g.messageFile(m)})
	}
	if cfgString(cfg, "emit", "sources") == "project" {
		files = append(files, g.projectFiles(s, cfg, dir)...)
	}
	if g.sizeErr != nil {
		return nil, g.sizeErr
	}
	return files, nil
}

type gen struct {
	schema  *ir.Schema
	pkg     string
	banner  string
	license string // SPDX id, "" to omit the header line
	limits  limitSet
	// size is the max_message_size policy; sizeErr carries a violation out of
	// the emit path, which has no error channel of its own.
	size    generator.SizePolicy
	sizeErr error
	// tmpN names the narrowed-wrapper-array locals (`_t0`, `_t1`, ...) a marshal
	// body declares. It is reset per emitted method so the names stay short and
	// stable, and it counts per method rather than per nesting depth because two
	// array FIELDS of one class share a scope and would otherwise collide.
	tmpN int
}

// messageSize resolves a message's worst-case encoded size via the shared walk
// (ir.MaxWireSize), falling back to the configured max_message_size ceiling when
// a field is unbounded. The emit path has no error channel, so a violation of an
// explicitly configured ceiling is recorded here and surfaced by Generate.
func (g *gen) messageSize(name string, fields []*ir.Field) generator.MessageSize {
	ms, err := g.size.Resolve(name, fields)
	if err != nil && g.sizeErr == nil {
		g.sizeErr = err
	}
	return ms
}

// limitSet is the receiver-side decode-limit configuration (generator#102). An
// entry is active only when its key is configured AND the schema actually has
// an unbounded field of that kind — otherwise the option would be inert and no
// limit plumbing is emitted. Unlike backends whose corelib enforces the limits
// globally per decode (Go, Python, TypeScript), the Java visitor guards each
// unbounded field individually, so the configured value is emitted as-is —
// schema-bounded fields never see it (they keep their generator#100 guard).
type limitSet struct {
	arrayCount, stringLen, blobLen int64
	arrayHas, stringHas, blobHas   bool
}

// resolveLimits reads the max_dyn_* config keys and gates them on the schema's
// bounds (see limitSet).
func resolveLimits(s *ir.Schema, cfg map[string]any) limitSet {
	var all []*ir.Field
	for _, m := range s.Messages {
		all = append(all, m.Fields...)
	}
	b := ir.Bounds(all)
	var l limitSet
	if v, ok := cfgLimit(cfg, "max_dyn_array_count"); ok && b.HasDynArray {
		l.arrayCount, l.arrayHas = v, true
	}
	if v, ok := cfgLimit(cfg, "max_dyn_string_len"); ok && b.HasDynString {
		l.stringLen, l.stringHas = v, true
	}
	if v, ok := cfgLimit(cfg, "max_dyn_blob_len"); ok && b.HasDynBlob {
		l.blobLen, l.blobHas = v, true
	}
	return l
}

// header writes the @generated banner and, when a license is set, an SPDX line.
func (g *gen) header(f *jfile) {
	f.line("// Code generated by %s; DO NOT EDIT.", g.banner)
	if g.license != "" {
		f.line("// SPDX-License-Identifier: %s", g.license)
	}
}

type jfile struct{ b strings.Builder }

func (f *jfile) line(format string, args ...any) {
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}
func (f *jfile) blank()        { f.b.WriteByte('\n') }
func (f *jfile) bytes() []byte { return []byte(f.b.String()) }

// javadoc writes a Javadoc doc comment for text at the given indent, or nothing
// when text is empty. Single-line text becomes `/** text */`; multi-line text is
// expanded across lines. Any `*/` in the text is neutralised to `* /` so it can
// never close the comment early; UTF-8 passes through byte-for-byte.
func (f *jfile) javadoc(indent, text string) {
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "*/", "* /")
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	if len(lines) == 1 {
		f.line("%s/** %s */", indent, lines[0])
		return
	}
	f.line("%s/**", indent)
	for _, ln := range lines {
		if ln == "" {
			f.line("%s *", indent)
		} else {
			f.line("%s * %s", indent, ln)
		}
	}
	f.line("%s */", indent)
}

// fieldDoc is the Javadoc body for a field: its description, with a unit suffix
// appended (or used alone), plus a Javadoc @deprecated tag on a trailing line
// when the field is deprecated. Empty when the field carries none of these.
func fieldDoc(fld *ir.Field) string {
	d := fld.Description
	if fld.Unit != "" {
		if d == "" {
			d = "(unit: " + fld.Unit + ")"
		} else {
			d += " (unit: " + fld.Unit + ")"
		}
	}
	if fld.Deprecated {
		const tag = "@deprecated This field is deprecated and may be removed in a future version."
		if d == "" {
			d = tag
		} else {
			d += "\n\n" + tag
		}
	}
	return d
}

// messageFile emits <Message>.java: the public message class plus its reachable
// named-type classes (package-private) and the decode visitor.
func (g *gen) messageFile(m *ir.Message) []byte {
	f := &jfile{}
	g.header(f)
	f.line("package %s;", g.pkg)
	f.line("import org.sofabuffers.sofab.*;")
	f.line("import java.io.IOException;")
	f.line("import java.util.*;")
	f.blank()

	order := g.reachable(m)
	for _, key := range order {
		nt := g.schema.Named[key]
		if nt.Category == ir.CatStruct || nt.Category == ir.CatUnion {
			g.emitClass(f, g.typeName(key), nt.Fields, nt.Summary, false, false)
		}
	}
	g.emitClass(f, exported(m.Name), m.Fields, m.Summary, true, true)
	return f.bytes()
}

func (g *gen) emitClass(f *jfile, name string, fields []*ir.Field, summary string, isMessage, isPublic bool) {
	vis := ""
	if isPublic {
		vis = "public "
	}
	f.javadoc("", summary)
	f.line("%sclass %s {", vis, name)
	for _, fld := range fields {
		f.javadoc("    ", fieldDoc(fld))
		if fld.Deprecated {
			f.line("    @Deprecated")
		}
		f.line("    public %s %s%s;", g.javaType(fld), javaIdent(fld.Name), g.javaInit(fld))
	}
	// Hoist each native array's omit-compare default into a static: marshal only
	// ever reads it (Arrays.equals / List.equals), so one shared instance suffices
	// and encode stops allocating a fresh `new T[n]` literal on every call (issue
	// #146 -- a `count: N` field's default is N elements, so for a large N or many
	// array fields that per-encode garbage dominates). The mutable per-object
	// initializer above stays a fresh allocation; this static is read-only. Mirrors
	// the C# backend's `_arrdef_*` statics.
	for _, fld := range fields {
		if def, ok := g.javaArrayCompareDefault(fld); ok {
			f.line("    private static final %s %s = %s;", g.javaType(fld), javaArrDefName(fld), def)
		}
	}
	// A `count: N` array's value is N elements long whether or not the field ever
	// reaches the wire (MESSAGE_SPEC §5.1: the length "is N for every target").
	// A NATIVE fixed-count array has always been materialized at construction --
	// `new long[3]` / `new ArrayList<>(List.of(false, false))` above -- but a
	// WRAPPER one (string/blob/struct/union/nested elements) was left as the empty
	// List, which made the two kinds disagree about the same schema and made the
	// field disagree with itself: an ABSENT count:3 string array decoded at length
	// 0 while one element on the wire, or an explicitly-empty wrapper, decoded at
	// 3 (sequenceEnd can only refill a sequence that was actually opened).
	//
	// The N default elements cannot be a shared static the way the native
	// omit-compare defaults above can: the List is the mutable field value, and a
	// struct/union element must be a distinct instance per array slot. A filler
	// factory keeps both the field initializer and reset() to one call and stays
	// compact for a large N.
	//
	// Elements are the element default, exactly what the collectors gap-fill with:
	// a declared per-element default is not materialized anywhere today.
	for _, fld := range fields {
		if !fixedSeqArray(fld) {
			continue
		}
		t := g.javaType(fld)
		f.line("    private static %s %s(%s l) {", t, javaSeqDefName(fld), t)
		f.line("        for (int i = 0; i < %d; i++) l.add(%s);", fld.Count, g.javaSeqElemDefault(fld))
		f.line("        return l;")
		f.line("    }")
	}
	f.blank()

	// marshal
	g.tmpN = 0
	f.line("    public void marshal(OStream os) throws IOException {")
	for _, fld := range fields {
		g.emitMarshal(f, fld)
	}
	f.line("    }")

	g.emitIsDefault(f, fields)

	g.emitReset(f, fields)

	if isMessage {
		ms := g.messageSize(name, fields)
		if !ms.Bounded {
			f.line("    // Configured ceiling (max_message_size): an unbounded field means this")
			f.line("    // size is imposed, not derived from the schema.")
			f.line("    public static final int MAX_SIZE_LIMIT = %d;", ms.Size)
			f.line("    public static final int MAX_SIZE = MAX_SIZE_LIMIT;")
		} else {
			f.line("    public static final int MAX_SIZE = %d;", ms.Size)
		}
		f.line("    // Per-thread scratch buffer: encode() marshals into it and returns an")
		f.line("    // exact-size copy, so the worst-case buffer is not re-allocated (and")
		f.line("    // zeroed) on every call. Do not call encode() reentrantly from a")
		f.line("    // marshal() override on the same thread.")
		f.line("    private static final ThreadLocal<byte[]> ENC_BUF =")
		f.line("        ThreadLocal.withInitial(() -> new byte[MAX_SIZE]);")
		f.line("    public byte[] encode() {")
		f.line("        try {")
		f.line("            byte[] buf = ENC_BUF.get();")
		f.line("            OStream os = new OStream(buf);")
		f.line("            marshal(os);")
		f.line("            return Arrays.copyOf(buf, os.bytesUsed());")
		f.line("        } catch (IOException e) { throw new RuntimeException(e); }")
		f.line("    }")
		// Best-effort decode: kept for back-compat. feed() suspends without
		// throwing on a truncated message, so this cannot tell COMPLETE from
		// INCOMPLETE — prefer tryDecode when that verdict matters
		// (generator#105).
		f.line("    public static %s decode(byte[] data) {", name)
		f.line("        %s m = new %s();", name, name)
		f.line("        try { new IStream().feed(data, new %sVisitor(m)); }", name)
		f.line("        catch (Exception e) { throw new RuntimeException(e); }")
		f.line("        return m;")
		f.line("    }")
		// Status-surfacing one-shot decode (MESSAGE_SPEC §7): fills the
		// caller-provided instance with the fields decoded so far and returns
		// the corelib's terminal DecodeStatus — COMPLETE at a clean field
		// boundary, INCOMPLETE when the bytes end inside a field or an open
		// sequence. Malformed input throws SofabException (INVALID) from feed;
		// the caller owns end-of-input and decides whether a trailing
		// INCOMPLETE is a truncation error.
		// `out` is caller-supplied and may carry a previous decode. Absence is the
		// encoding of an all-default field (MESSAGE_SPEC §2), and an absent field
		// fires no callback at all, so the destination is re-armed HERE — the last
		// point at which absence is still observable.
		f.line("    public static DecodeStatus tryDecode(byte[] data, %s out) throws SofabException {", name)
		f.line("        out.reset();")
		f.line("        IStream is = new IStream();")
		f.line("        is.feed(data, new %sVisitor(out));", name)
		f.line("        return is.status();")
		f.line("    }")
	}
	f.line("}")
	f.blank()

	if isMessage {
		g.emitVisitor(f, name, fields)
	}
}

// emitIsDefault writes `isDefault()`: the object's all-default predicate, and the
// exact negation of what marshal writes -- the object is default iff marshal would
// emit no child at all, evaluated per field and recursively, never as a byte image
// (MESSAGE_SPEC §2).
//
// Every generated struct/union carries it so a `count: N` wrapper array can find M
// -- one past its last non-default element -- BEFORE opening the element loop
// (§3/§5.1). The lazy framing already encodes the same test implicitly for a
// sequence-typed FIELD ("the frame survives iff a child was written"), but an
// array ELEMENT has to be judged before its frame is opened, which the implicit
// form cannot answer in time.
//
// Keep this in lockstep with emitMarshal: every arm below is written as the
// negation of that field's write guard, and the wrapper-array arm shares
// elemTrimExpr with the marshal loop verbatim. A predicate that narrows a field
// the writer does not narrow (or the reverse) either omits a field that is on the
// wire or keeps one that is not.
//
// Package-private on purpose: it is an encoder-internal predicate, reached only as
// the `X::isDefault` method reference the generated marshal hands to
// Sbuf.trimTailObjs, never part of the public message API.
func (g *gen) emitIsDefault(f *jfile, fields []*ir.Field) {
	f.line("    /** True when every field still equals its declared default, compared per field and recursively -- i.e. marshal would write nothing at all. */")
	f.line("    boolean isDefault() {")
	for _, fld := range fields {
		f.line("        if (%s) return false;", g.fieldWritesExpr(fld))
	}
	f.line("        return true;")
	f.line("    }")
}

// fieldWritesExpr is the boolean expression "marshal would put this field on the
// wire", i.e. literally emitMarshal's write guard for the same field. isDefault is
// built from it rather than from a hand-written "equals its default" twin so that
// the two cannot state different truth tables: the object is default exactly when
// no arm below fires.
func (g *gen) fieldWritesExpr(fld *ir.Field) string {
	acc := "this." + javaIdent(fld.Name)
	switch fld.Kind {
	case ir.KindBlob:
		// emitMarshal's two blob guards, verbatim.
		if def := g.javaDefaultValue(fld); def == "new byte[0]" || def == "Sbuf.EMPTY_BYTES" {
			return fmt.Sprintf("%s == null || %s.length != 0", acc, acc)
		}
		return fmt.Sprintf("!java.util.Arrays.equals(%s, %s)", acc, g.javaDefaultValue(fld))
	case ir.KindStruct, ir.KindUnion:
		// Lazily framed, so the frame survives iff the nested marshal wrote a child
		// -- exactly "the nested object is not default". A null field marshals as a
		// fresh instance, whose fields are their declared defaults by construction,
		// so a null is never written.
		return fmt.Sprintf("%s != null && !%s.isDefault()", acc, acc)
	case ir.KindArray:
		return g.arrayWritesExpr(fld, acc)
	}
	// Scalar/string/enum/bitfield leaf: the writer's own omit condition.
	return g.javaOmitCond(fld)
}

// arrayWritesExpr mirrors emitMarshalArray arm for arm: a native array is a leaf
// field compared whole against its materialized default, and a wrapper array puts
// something on the wire iff at least one element survives the SAME narrowing the
// marshal loop runs over.
func (g *gen) arrayWritesExpr(fld *ir.Field, acc string) string {
	if primitiveArrayElem(fld.Elem) {
		if _, ok := g.javaPrimArrayLiteral(fld); ok {
			return fmt.Sprintf("!java.util.Arrays.equals(%s, %s)", acc, javaArrDefName(fld))
		}
		return fmt.Sprintf("%s != null && %s.length != 0", acc, acc)
	}
	if nativeArrayElem(fld.Elem) { // boolean array (boxed List<Boolean>)
		if _, ok := g.javaNativeArrayLiteral(fld); ok {
			return fmt.Sprintf("!%s.equals(%s)", javaArrDefName(fld), acc)
		}
		return fmt.Sprintf("%s != null && !%s.isEmpty()", acc, acc)
	}
	// Wrapper array: a child is written iff some element differs from the element
	// default. fld.HasCount must be threaded through UNCHANGED -- narrowing here
	// but not in the marshal loop (or the reverse) is exactly the drift this
	// shared expression exists to prevent: it would call a dynamic [{}] "default"
	// while the writer still frames its one empty element, omitting a field that
	// is on the wire.
	return fmt.Sprintf("!%s.isEmpty()", g.elemTrimExpr(acc, fld.Elem, fld.ElemRef, fld.ElemItems, fld.HasCount))
}

// emitReset writes `reset()`: every field back to its declared default, in place.
//
// It exists because MESSAGE_SPEC §2 made ABSENCE the encoding of an all-default
// sequence. The visitor's §7.4 clear (a wrapper array is replaced whole by a later
// occurrence) hangs off sequenceBegin/arrayBegin — a callback an omitted field
// never fires. Decoding into a REUSED destination therefore left the previous
// decode's elements standing, so the decoded array held data that was not in the
// message. Absence is only observable before the feed starts, so the reset has to
// happen there: tryDecode(data, out) calls out.reset() first, and the §7.4 clear
// stays exactly as it is for the re-opened-wrapper case it actually covers.
//
// "In place" is the point of a reuse API: a List is cleared (keeping its capacity)
// and a nested object is reset recursively rather than re-allocated, and a
// primitive array is refilled from the shared default when its length already
// matches. It is public so a caller who drives the Visitor directly — feeding
// chunks itself, with no tryDecode to hook — can re-arm a destination the same way
// (corelib-cpp exposes IStreamImpl::reset() for the same reason).
func (g *gen) emitReset(f *jfile, fields []*ir.Field) {
	f.line("    /** Restores every field to its declared default, in place; call before reusing an instance as a decode destination. */")
	f.line("    public void reset() {")
	for _, fld := range fields {
		g.emitResetField(f, fld)
	}
	f.line("    }")
}

func (g *gen) emitResetField(f *jfile, fld *ir.Field) {
	acc := "this." + javaIdent(fld.Name)
	switch fld.Kind {
	case ir.KindStruct, ir.KindUnion:
		// Recurse rather than re-allocate; a null field is materialized once.
		f.line("        if (%s == null) %s = new %s(); else %s.reset();", acc, acc, g.typeName(fld.Ref.Key), acc)
	case ir.KindArray:
		if primitiveArrayElem(fld.Elem) {
			// A materialized default (always the case for `count: N`) is copied back
			// over the existing storage when the length already matches — a fixed
			// array's length never changes, so the reuse path allocates nothing. A
			// dynamic array with no default is the shared zero-length constant, which
			// is exactly its field initializer.
			if _, ok := g.javaPrimArrayLiteral(fld); ok {
				d := javaArrDefName(fld)
				f.line("        if (%s != null && %s.length == %s.length) System.arraycopy(%s, 0, %s, 0, %s.length);", acc, acc, d, d, acc, d)
				f.line("        else %s = %s.clone();", acc, d)
				return
			}
			f.line("        %s = %s;", acc, emptyPrimConst(fld.Elem))
			return
		}
		// List-backed: the boolean array (which may carry a materialized default) and
		// every wrapper sequence (whose declared per-element default is not
		// materialized, so the element defaults ARE its default — the same rule the
		// dropping closer relies on).
		f.line("        %s = Sbuf.resetList(%s);", acc, acc)
		if nativeArrayElem(fld.Elem) {
			if _, ok := g.javaNativeArrayLiteral(fld); ok {
				f.line("        %s.addAll(%s);", acc, javaArrDefName(fld))
			}
		}
		// reset() re-arms a destination the caller supplies, so it has to land on the
		// same value `new <Msg>()` does: a fixed-count wrapper array is N element
		// defaults, not the empty list (§5.1).
		if fixedSeqArray(fld) {
			f.line("        %s(%s);", javaSeqDefName(fld), acc)
		}
	default:
		// Scalar/string/blob leaf: assign the same literal the field initializer uses.
		f.line("        %s = %s;", acc, g.javaDefaultValue(fld))
	}
}

// emptyPrimConst is the shared zero-length primitive-array constant backing a
// dynamic (count-less, default-less) array field — the same value javaInit gives it.
func emptyPrimConst(elem ir.Kind) string {
	switch primArrayBase(elem) {
	case "float":
		return "Sbuf.EMPTY_FLOATS"
	case "double":
		return "Sbuf.EMPTY_DOUBLES"
	default:
		return "Sbuf.EMPTY_LONGS"
	}
}

func (g *gen) emitMarshal(f *jfile, fld *ir.Field) {
	acc := "this." + javaIdent(fld.Name)
	var write string
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		write = fmt.Sprintf("os.writeUnsigned(%d, %s);", fld.ID, acc)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		write = fmt.Sprintf("os.writeSigned(%d, %s);", fld.ID, acc)
	case ir.KindBool:
		write = fmt.Sprintf("os.writeBoolean(%d, %s);", fld.ID, acc)
	case ir.KindFP32:
		write = fmt.Sprintf("os.writeFp32(%d, %s);", fld.ID, acc)
	case ir.KindFP64:
		write = fmt.Sprintf("os.writeFp64(%d, %s);", fld.ID, acc)
	case ir.KindString:
		write = fmt.Sprintf("os.writeString(%d, %s == null ? \"\" : %s);", fld.ID, acc, acc)
	case ir.KindBlob:
		// A blob is a leaf: omit when equal to its default (empty when none).
		// With an empty default the content compare degenerates to a length
		// check, sparing an Arrays.equals against a fresh byte[0] per call.
		if def := g.javaDefaultValue(fld); def == "new byte[0]" || def == "Sbuf.EMPTY_BYTES" {
			f.line("        if (%s == null || %s.length != 0) { os.writeBlob(%d, %s == null ? new byte[0] : %s); }", acc, acc, fld.ID, acc, acc)
			return
		}
		f.line("        if (!Arrays.equals(%s, %s)) { os.writeBlob(%d, %s == null ? new byte[0] : %s); }", acc, g.javaDefaultValue(fld), fld.ID, acc, acc)
		return
	case ir.KindStruct, ir.KindUnion:
		// MESSAGE_SPEC S2: the != default test is per field and a sequence-typed
		// field is no exception, so the frame is opened LAZILY -- the corelib holds
		// the header back until a child field actually appears. The nested marshal
		// omits every child that equals its default, so "no child was written" IS
		// "the object equals its declared default", evaluated per field and
		// recursively, with no byte image ever compared. An all-default nested
		// object is therefore dropped, not emitted as an empty wrapper.
		f.line("        os.writeSequenceBeginLazy(%d); (%s == null ? new %s() : %s).marshal(os); os.writeSequenceEnd();", fld.ID, acc, g.typeName(fld.Ref.Key), acc)
		return
	case ir.KindArray:
		g.emitMarshalArray(f, fld, acc)
		return
	}
	// Scalar/string/enum/bitfield leaf: always omit when equal to the default;
	// sparse encoding is canonical (MESSAGE_SPEC S2) and the decoder reconstructs
	// the omitted field from its default.
	f.line("        if (%s) { %s }", g.javaOmitCond(fld), write)
}

func (g *gen) emitMarshalArray(f *jfile, fld *ir.Field, acc string) {
	// A native scalar array is a leaf field: omit it when equal to its default
	// (materialized at construction), else when empty. A composite/dynamic-element
	// array is a wrapper sequence: opened lazily, closed with the dropping end at
	// field level, so an all-default one is omitted (MESSAGE_SPEC §2).
	if primitiveArrayElem(fld.Elem) {
		// Primitive array (long[]/float[]/double[]): omit when equal to its default
		// (Arrays.equals), else when empty; write straight to the OStream primitive
		// overload with no Sbuf box/unbox temporary.
		if _, ok := g.javaPrimArrayLiteral(fld); ok {
			f.line("        if (!java.util.Arrays.equals(%s, %s)) {", acc, javaArrDefName(fld))
		} else {
			f.line("        if (%s != null && %s.length != 0) {", acc, acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, true, fld.HasCount)
		f.line("        }")
		return
	}
	if nativeArrayElem(fld.Elem) { // boolean array (boxed List<Boolean>)
		if _, ok := g.javaNativeArrayLiteral(fld); ok {
			f.line("        if (!%s.equals(%s)) {", javaArrDefName(fld), acc)
		} else {
			f.line("        if (%s != null && !%s.isEmpty()) {", acc, acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, fld.HasCount)
		f.line("        }")
		return
	}
	// The field-level wrapper frame is dropped when no element is written, and
	// absence then reconstructs the field's default. That is correct because a
	// wrapper array's declared `default` is not materialized today (the generated
	// field initializer is the empty collection), so absent and explicitly-empty
	// denote the same value. If that gap is ever closed, this call needs a guard --
	// `if (value != default) { ... os.writeSequenceEndKeep(); }` -- so that a value
	// differing from a non-empty default still reaches the wire as the empty
	// wrapper, the only encoding of "explicitly empty" (MESSAGE_SPEC S2, S3).
	g.marshalArray(f, "        ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, fld.HasCount)
}

// javaArrDefName is the static field holding a native array field's omit-compare
// default (issue #146).
func javaArrDefName(fld *ir.Field) string { return "_arrdef_" + fld.Name }

// javaArrayCompareDefault is the literal a native array field's value is compared
// against for whole-field omission, and ("", false) when the field has no
// materialized default (a dynamic array with no schema default, or a
// wrapper-sequence array, which is never whole-omitted). It is exactly the field
// initializer, so an untouched field always compares equal and is omitted.
func (g *gen) javaArrayCompareDefault(fld *ir.Field) (string, bool) {
	if fld.Kind != ir.KindArray {
		return "", false
	}
	if primitiveArrayElem(fld.Elem) {
		return g.javaPrimArrayLiteral(fld)
	}
	if nativeArrayElem(fld.Elem) {
		return g.javaNativeArrayLiteral(fld)
	}
	return "", false
}

// trimExpr wraps a native array expression in the trailing-default-run trim a
// fixed-count array's canonical encoding requires (MESSAGE_SPEC §3). Only a
// declared `count: N` array is fixed-length; a dynamic (count-less) array has no
// N to refill from, so a trailing default element is significant and stays.
// Elements compare by BIT PATTERN, not by ==, so a trailing -0.0 (which == 0.0
// in Java) survives the round-trip instead of being silently trimmed to +0.0.
func trimExpr(val string, elem ir.Kind, fixed bool) string {
	if !fixed {
		return val
	}
	switch elem {
	case ir.KindFP32:
		return "Sbuf.trimTailF32(" + val + ")"
	case ir.KindFP64:
		return "Sbuf.trimTailF64(" + val + ")"
	default: // long-backed: integers, enum, bitfield, and the bool 0/1 image
		return "Sbuf.trimTail(" + val + ")"
	}
}

// elemTrimExpr narrows a wrapper array to the M its canonical wire carries: one
// past the last element differing from the element default (MESSAGE_SPEC §3/§5.1,
// which says "even for sequence-form elements"). Only a declared `count: N` array
// is fixed-length and may be narrowed -- a DYNAMIC array has no N to refill from,
// so a trailing default element is significant and stays on the wire (a leaf one
// via lastElemGuard, a sequence-form one via its keeping closer). Interior
// all-default elements are never dropped by this: element presence carries the
// length, so only the trailing run goes.
//
// Both the marshal loop and isDefault run off this one expression, so the writer
// and the predicate cannot disagree about which elements reach the wire.
func (g *gen) elemTrimExpr(val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, fixed bool) string {
	switch elem {
	case ir.KindString:
		// Dynamic: identity, save for the null the trim used to absorb. The local
		// it binds is also what lastElemGuard measures the last index against.
		if !fixed {
			return "Sbuf.orEmpty(" + val + ")"
		}
		return "Sbuf.trimTailStrings(" + val + ")"
	case ir.KindBlob:
		if !fixed {
			return "Sbuf.orEmpty(" + val + ")"
		}
		return "Sbuf.trimTailBlobs(" + val + ")"
	case ir.KindStruct, ir.KindUnion:
		if !fixed {
			return val
		}
		return fmt.Sprintf("Sbuf.trimTailObjs(%s, %s::isDefault)", val, g.typeName(ref.Key))
	case ir.KindArray:
		if !fixed {
			return val
		}
		return "Sbuf.trimTailRows(" + val + ")"
	}
	return val
}

// lastElemGuard is the "|| this is the last element" disjunct that keeps a
// DYNAMIC wrapper array's final LEAF element on the wire whatever its value
// (MESSAGE_SPEC §2, "the last element of a dynamic array is always present").
// Such an array recovers its length as highest-present-id + 1 (§5.1), so the
// element at the highest index is the only one whose PRESENCE carries the
// length: dropping it would encode ["a", ""] exactly like ["a"] and decode one
// element short. Sequence-form elements never needed this -- they are framed
// unconditionally, by the keeping closer -- so this closes the gap on the leaf
// side and holds both element kinds to one standard. A fixed-count array needs
// none of it: its length is N whatever the wire carries, which is why it elides
// the entire trailing default run instead (§3/§5.1), so the guard is omitted
// there and the trailing run collapses as before.
func lastElemGuard(iv, lv string, fixed bool) string {
	if fixed {
		return ""
	}
	return fmt.Sprintf(" || %s == %s.size() - 1", iv, lv)
}

// elemLoopList declares the narrowed local the marshal element loop runs over and
// returns its name, or val itself when this element kind and shape is never
// narrowed. The local exists for two reasons: Java re-evaluates a for-condition on
// every iteration (Go's `range` evaluates its operand once), and the loop must
// index the very list the narrowing produced.
func (g *gen) elemLoopList(f *jfile, ind, val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, fixed bool) string {
	te := g.elemTrimExpr(val, elem, ref, items, fixed)
	if te == val {
		return val
	}
	name := fmt.Sprintf("_t%d", g.tmpN)
	g.tmpN++
	f.line("%sList<%s> %s = %s;", ind, g.javaArrayElemType(elem, ref, items), name, te)
	return name
}

// marshalArray writes the array val as field idExpr. Numeric/enum/boolean/
// bitfield elements use the native array wire type (enum->signed, bool/bitfield->
// unsigned); string/blob/struct/union/array elements lower to a wrapper sequence
// whose child ids are the 0-based index (per MESSAGE_SPEC). Recurses for nested
// arrays, depth-suffixing loop vars to avoid collisions.
// prim is true only for a direct primitive array field (`val` is a
// long[]/float[]/double[]); it writes straight to the OStream overload. When
// false, `val` is a boxed List and is unboxed via a Sbuf.to*Array temporary —
// the case for boolean arrays and for a nested array's inner rows (which stay
// List<...>).
// fixed is true only for a top-level `count: N` array FIELD: its trailing run of
// default elements is elided on the wire and rebuilt by the decoder from the
// schema count (MESSAGE_SPEC §3). Nested rows of an array-of-array are not
// fixed-length in that sense, so the recursion below passes false.
func (g *gen) marshalArray(f *jfile, ind, idExpr, val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, depth int, prim, fixed bool) {
	iv := fmt.Sprintf("_i%d", depth)
	longs := "Sbuf.toLongArray(" + val + ")"
	floats := "Sbuf.toFloatArray(" + val + ")"
	doubles := "Sbuf.toDoubleArray(" + val + ")"
	if prim {
		longs, floats, doubles = val, val, val
	}
	// MESSAGE_SPEC S2: every sequence is opened lazily; the CLOSER decides whether a
	// contentless one survives, and it is picked here statically from the position
	// in the schema, never from the value. A wrapper array at depth 0 is a
	// sequence-typed FIELD, so it closes with the dropping end -- an all-default
	// array is omitted and absence reconstructs it. A nested row (depth > 0) is an
	// array ELEMENT, and element presence is what carries a dynamic array's length
	// (S5.1), so it closes with the keeping end: dropping an all-default row would
	// change the decoded length, not merely the bytes.
	seqEnd := "writeSequenceEnd"
	if depth > 0 {
		seqEnd = "writeSequenceEndKeep"
	}
	switch elem {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		f.line("%sos.writeArrayUnsigned(%s, %s);", ind, idExpr, trimExpr(longs, elem, fixed))
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		f.line("%sos.writeArraySigned(%s, %s);", ind, idExpr, trimExpr(longs, elem, fixed))
	case ir.KindBool:
		// Trimming the 0/1 image is equivalent to trimming the booleans (false <-> 0).
		f.line("%sos.writeArrayUnsigned(%s, %s);", ind, idExpr, trimExpr("Sbuf.boolToLongArray("+val+")", ir.KindU8, fixed))
	case ir.KindFP32:
		f.line("%sos.writeArrayFp32(%s, %s);", ind, idExpr, trimExpr(floats, elem, fixed))
	case ir.KindFP64:
		f.line("%sos.writeArrayFp64(%s, %s);", ind, idExpr, trimExpr(doubles, elem, fixed))
	case ir.KindString:
		// A string element is a leaf: omit it when equal to the element default
		// (empty), leaving an id gap the decoder restores (MESSAGE_SPEC S2) --
		// except at the one position whose presence carries the length, see
		// lastElemGuard. A null element IS the element default, so it is
		// normalized to "" first: at the last index of a dynamic array it is
		// written rather than skipped.
		ev := fmt.Sprintf("_e%d", depth)
		lv := g.elemLoopList(f, ind, val, elem, ref, items, fixed)
		f.line("%sos.writeSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%sfor (int %s = 0; %s < %s.size(); %s++) { String %s = %s.get(%s); if (%s == null) %s = \"\"; if (!%s.isEmpty()%s) os.writeString(%s, %s); }", ind, iv, iv, lv, iv, ev, lv, iv, ev, ev, ev, lastElemGuard(iv, lv, fixed), iv, ev)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindBlob:
		// A blob element is a leaf: omit it when equal to the element default
		// (empty), leaving an id gap the decoder restores (MESSAGE_SPEC S2) --
		// except at the one position whose presence carries the length, see
		// lastElemGuard. A null element IS the element default, so it is
		// normalized to the empty blob first: at the last index of a dynamic
		// array it is written rather than skipped.
		ev := fmt.Sprintf("_e%d", depth)
		lv := g.elemLoopList(f, ind, val, elem, ref, items, fixed)
		f.line("%sos.writeSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%sfor (int %s = 0; %s < %s.size(); %s++) { byte[] %s = %s.get(%s); if (%s == null) %s = Sbuf.EMPTY_BYTES; if (%s.length != 0%s) os.writeBlob(%s, %s); }", ind, iv, iv, lv, iv, ev, lv, iv, ev, ev, ev, lastElemGuard(iv, lv, fixed), iv, ev)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindStruct, ir.KindUnion:
		// An INTERIOR element frame closes with the KEEPING end: a struct/union
		// element is present even when all-default, and its id counts toward the
		// array's length (highest present id + 1, MESSAGE_SPEC S5.1), so dropping
		// it would leave an id gap and SHORTEN the decoded array. The TRAILING
		// all-default run is already gone -- the loop runs to M, not to size()
		// (S3/S5.1) -- and M == 0 writes no child at all, so the lazily-opened
		// wrapper is dropped by the field-level closer and the field is omitted (S2).
		lv := g.elemLoopList(f, ind, val, elem, ref, items, fixed)
		f.line("%sos.writeSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%sfor (int %s = 0; %s < %s.size(); %s++) { os.writeSequenceBeginLazy(%s); (%s.get(%s) == null ? new %s() : %s.get(%s)).marshal(os); os.writeSequenceEndKeep(); }", ind, iv, iv, lv, iv, iv, lv, iv, g.typeName(ref.Key), lv, iv)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindArray:
		lv := g.elemLoopList(f, ind, val, elem, ref, items, fixed)
		f.line("%sos.writeSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%sfor (int %s = 0; %s < %s.size(); %s++) {", ind, iv, iv, lv, iv)
		g.marshalArray(f, ind+"    ", iv, fmt.Sprintf("%s.get(%s)", lv, iv), items.Elem, items.ElemRef, items.ElemItems, depth+1, false, false)
		f.line("%s}", ind)
		f.line("%sos.%s();", ind, seqEnd)
	}
}
