// Package python is the Python throughput backend (PLAN §6.4): it emits
// dataclasses with _marshal (Encoder) and a pull-parser _unmarshal
// (Decoder.next/skip + typed readers) against corelib-py, plus JSON helpers for
// the conformance harness.
package python

import (
	"fmt"
	"strings"

	"github.com/sofa-buffers/generator/internal/generator"
	"github.com/sofa-buffers/generator/internal/ir"
)

func init() { generator.Register(&Backend{}) }

// Backend implements generator.Backend for Python.
type Backend struct{}

func (*Backend) Lang() string { return "python" }

// Generate emits a single module (all enums/bitfields/dataclasses + messages).
// In project mode it adds a harness and pyproject.toml.
func (*Backend) Generate(s *ir.Schema, cfg map[string]any) ([]generator.File, error) {
	g := &gen{
		schema:  s,
		banner:  cfgString(cfg, "tool_banner", "sofabgen"),
		license: generator.LicenseID(cfg),
		limits:  resolveLimits(s, cfg),
		size:    generator.NewSizePolicy(cfg),
	}
	module := g.module(s)
	files := []generator.File{{Path: "message.py", Content: module}}
	if cfgString(cfg, "emit", "sources") == "project" {
		files = append(files, g.projectFiles(s, cfg)...)
	}
	if g.sizeErr != nil {
		return nil, g.sizeErr
	}
	return files, nil
}

type gen struct {
	schema  *ir.Schema
	banner  string
	license string // SPDX id, "" to omit the header line
	limits  limitSet
	// size is the max_message_size policy; sizeErr carries a violation out of
	// the emit path, which has no error channel of its own.
	size    generator.SizePolicy
	sizeErr error
}

// messageSize resolves a class's worst-case encoded size via the shared walk
// (ir.MaxWireSize), falling back to the configured max_message_size ceiling when
// a field is unbounded. The emit path has no error channel, so a violation of an
// explicitly configured ceiling is recorded here and surfaced by Generate.
func (g *gen) messageSize(name string, fields []*ir.Field) generator.MessageSize {
	ms, err := g.size.Resolve(name, fields)
	if err != nil && g.sizeErr == nil {
		g.sizeErr = err
	}
	return ms
}

// limitSet is the receiver-side decode-limit configuration (generator#102),
// resolved against the schema. An entry is active only when its key is
// configured AND the schema actually has an unbounded field of that kind --
// otherwise the option would be inert and no plumbing is emitted.
//
// The configured value is emitted AS CONFIGURED. It used to be raised to the
// largest schema bound of its kind, because corelib-py applies its caps per
// Decoder and would otherwise reject a schema-bounded field larger than the cap
// -- which §6.2.1 forbids, since there the schema bound governs. That raise kept
// such messages decodable by loosening the cap for the UNBOUNDED fields too,
// which is exactly the protection §6.2.1 wants kept tight. Generated code now
// declares each bounded field with d.schema_bounded() instead, so the cap binds
// only what the schema left open and can stay at the number the deployment
// chose (generator#325).
type limitSet struct {
	arrayCount, stringLen, blobLen int64
	arrayHas, stringHas, blobHas   bool
}

func (l limitSet) any() bool { return l.arrayHas || l.stringHas || l.blobHas }

// resolveLimits reads the max_dyn_* config keys and resolves them against the
// schema's bounds (see limitSet).
func resolveLimits(s *ir.Schema, cfg map[string]any) limitSet {
	var all []*ir.Field
	for _, m := range s.Messages {
		all = append(all, m.Fields...)
	}
	b := ir.Bounds(all)
	var l limitSet
	if v, ok := cfgLimit(cfg, "max_dyn_array_count"); ok && b.HasDynArray {
		l.arrayCount, l.arrayHas = v, true
	}
	if v, ok := cfgLimit(cfg, "max_dyn_string_len"); ok && b.HasDynString {
		l.stringLen, l.stringHas = v, true
	}
	if v, ok := cfgLimit(cfg, "max_dyn_blob_len"); ok && b.HasDynBlob {
		l.blobLen, l.blobHas = v, true
	}
	return l
}

type pyfile struct{ b strings.Builder }

func (f *pyfile) line(format string, args ...any) {
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}
func (f *pyfile) blank()        { f.b.WriteByte('\n') }
func (f *pyfile) bytes() []byte { return []byte(f.b.String()) }

func (g *gen) module(s *ir.Schema) []byte {
	f := &pyfile{}
	f.line("# Code generated by %s; DO NOT EDIT.", g.banner)
	if g.license != "" {
		f.line("# SPDX-License-Identifier: %s", g.license)
	}
	f.line("from __future__ import annotations")
	f.line("import io")
	f.line("from dataclasses import dataclass, field")
	f.line("from enum import IntEnum")
	// SofaDecodeError is raised by the over-count scalar-array guard
	// (generator#100) and the over-index wrapper-array guard (generator#142), so
	// import it only when a fixed-count array of either kind exists — an
	// unconditional import would be unused for other schemas.
	names := []string{"Encoder", "Decoder"}
	if schemaHasCountedNativeArray(s) || schemaHasCountedWrapperArray(s) || schemaHasMaxlenStringBlob(s) {
		names = append(names, "SofaDecodeError")
	}
	names = append(names, "WireType")
	// FixlenSubtype is referenced only by the §7.3 guard of a fixlen-framed field;
	// importing it unconditionally would leave it unused for schemas without one.
	if schemaHasFixlenField(s) {
		names = append(names, "FixlenSubtype")
	}
	f.line("from sofab import %s", strings.Join(names, ", "))
	f.blank()

	if g.limits.any() {
		f.line("# Receiver-side decode limits, baked from the sofabgen config")
		f.line("# (max_dyn_array_count / max_dyn_string_len / max_dyn_blob_len). They govern")
		f.line("# only fields the schema left unbounded; each cap is raised to the largest")
		f.line("# schema bound of its kind, so a schema-bounded field stays governed by its")
		f.line("# own bound alone. Exceeding a cap raises sofab.SofaLimitError at the count/")
		f.line("# length header, before any allocation.")
		if g.limits.arrayHas {
			f.line("MAX_DYN_ARRAY_COUNT = %d", g.limits.arrayCount)
		}
		if g.limits.stringHas {
			f.line("MAX_DYN_STRING_LEN = %d", g.limits.stringLen)
		}
		if g.limits.blobHas {
			f.line("MAX_DYN_BLOB_LEN = %d", g.limits.blobLen)
		}
		f.blank()
	}

	// enums + bitfield constants first
	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		switch nt.Category {
		case ir.CatEnum:
			g.emitEnum(f, nt)
		case ir.CatBitfield:
			g.emitBitfieldConsts(f, nt)
		}
	}
	// struct/union dataclasses, then messages
	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		if nt.Category == ir.CatStruct || nt.Category == ir.CatUnion {
			g.emitDataclass(f, g.typeName(key), nt.Summary, nt.Fields)
		}
	}
	for _, m := range s.Messages {
		g.emitDataclass(f, exported(m.Name), m.Summary, m.Fields)
	}
	return f.bytes()
}

// schemaHasCountedNativeArray reports whether any field (recursively through
// nested-array element items) is a native scalar array with a schema `count` —
// the arrays whose decode emits the over-count SofaDecodeError guard
// (generator#100). The recursion is what keeps this in lockstep with the
// emitter: a nested native ROW carries its own capacity and is bounded at its
// own count header, so a schema whose ONLY counted native array is such a row
// (a count-less outer array of counted u32 rows) still needs the import — a
// top-level-only scan would leave the raise NameError at decode time.
func schemaHasCountedNativeArray(s *ir.Schema) bool {
	var arrHas func(elem ir.Kind, items *ir.ArrayElem, hasCount bool) bool
	arrHas = func(elem ir.Kind, items *ir.ArrayElem, hasCount bool) bool {
		if hasCount && isNativeArrayElem(elem) {
			return true
		}
		if elem == ir.KindArray && items != nil {
			return arrHas(items.Elem, items.ElemItems, items.HasCount)
		}
		return false
	}
	return schemaHasField(s, func(fld *ir.Field) bool {
		return fld.Kind == ir.KindArray && arrHas(fld.Elem, fld.ElemItems, fld.HasCount)
	})
}

// schemaHasCountedWrapperArray reports whether any field (recursively through
// nested-array element items) is a fixed-count wrapper-sequence array —
// string/blob/struct/union/nested-array elements with a schema `count` — the
// fields whose decode emits the over-index SofaDecodeError guard (generator#142).
func schemaHasCountedWrapperArray(s *ir.Schema) bool {
	var arrHas func(elem ir.Kind, items *ir.ArrayElem, hasCount bool) bool
	arrHas = func(elem ir.Kind, items *ir.ArrayElem, hasCount bool) bool {
		if hasCount && !isNativeArrayElem(elem) {
			return true
		}
		if elem == ir.KindArray && items != nil {
			return arrHas(items.Elem, items.ElemItems, items.HasCount)
		}
		return false
	}
	return schemaHasField(s, func(fld *ir.Field) bool {
		return fld.Kind == ir.KindArray && arrHas(fld.Elem, fld.ElemItems, fld.HasCount)
	})
}

// schemaHasMaxlenStringBlob reports whether any field (recursively through
// nested-array element items) is a bounded (maxlen) string/blob — a scalar
// string/blob carrying a schema `maxlen`, or a string/blob array element
// carrying an element maxlen — the fields whose decode emits the over-length
// SofaDecodeError guard (MESSAGE_SPEC §7.1). Kept in lockstep with the import
// condition: a schema that rejects only on a bounded string/blob still needs
// SofaDecodeError imported.
func schemaHasMaxlenStringBlob(s *ir.Schema) bool {
	var arrHas func(elem ir.Kind, items *ir.ArrayElem, elemMaxHas bool) bool
	arrHas = func(elem ir.Kind, items *ir.ArrayElem, elemMaxHas bool) bool {
		if elemMaxHas && (elem == ir.KindString || elem == ir.KindBlob) {
			return true
		}
		if elem == ir.KindArray && items != nil {
			return arrHas(items.Elem, items.ElemItems, items.ElemMaxHas)
		}
		return false
	}
	return schemaHasField(s, func(fld *ir.Field) bool {
		if (fld.Kind == ir.KindString || fld.Kind == ir.KindBlob) && fld.HasMaxlen {
			return true
		}
		return fld.Kind == ir.KindArray && arrHas(fld.Elem, fld.ElemItems, fld.ElemMaxHas)
	})
}

// schemaHasFixlenField reports whether any §7.3 guard the module emits needs to
// compare a fixlen subtype — i.e. whether the generated module references
// FixlenSubtype at all. fp32/fp64/string/blob and their native arrays all share
// one wire type (FIXLEN / ARRAY_FIXLEN), so only the subtype separates them;
// every other kind is settled by the wire type alone and needs no import.
//
// Guards are emitted at TWO levels and both must be counted (generator#246): the
// field-level pyWireGuard, and pyElemWireGuard for every wrapper-sequence
// ELEMENT down the array element chain — so an `array<string>` (element guard
// names FixlenSubtype.STRING) or an `array<array<fp32>>` (the nested row's guard
// names FixlenSubtype.FP32) needs the import even though no *field* is fixlen.
func schemaHasFixlenField(s *ir.Schema) bool {
	return schemaHasField(s, fieldHasFixlenGuard)
}

// fieldHasFixlenGuard reports whether any guard emitted for fld — pyWireGuard on
// the field itself, plus one pyElemWireGuard per level of the array element chain
// — names a FixlenSubtype member. A fixlen kind anywhere in that chain does it:
// as a native array element the containing array's guard carries the subtype
// (ARRAY_FIXLEN is ambiguous), and as a wrapper element the element's own guard
// does (FIXLEN is). A struct/union element carries no subtype; its own fields are
// reached separately through the named types (schemaHasField).
func fieldHasFixlenGuard(fld *ir.Field) bool {
	if pyFixlenSubtype(fld.Kind) != "" {
		return true
	}
	if fld.Kind != ir.KindArray {
		return false
	}
	for elem, items := fld.Elem, fld.ElemItems; ; elem, items = items.Elem, items.ElemItems {
		if pyFixlenSubtype(elem) != "" {
			return true
		}
		if elem != ir.KindArray || items == nil {
			return false
		}
	}
}

// pyFixlenSubtype returns the FixlenSubtype member a fixlen kind must carry, or
// "" for a kind that is not fixlen-framed.
func pyFixlenSubtype(k ir.Kind) string {
	switch k {
	case ir.KindFP32:
		return "FixlenSubtype.FP32"
	case ir.KindFP64:
		return "FixlenSubtype.FP64"
	case ir.KindString:
		return "FixlenSubtype.STRING"
	case ir.KindBlob:
		return "FixlenSubtype.BLOB"
	}
	return ""
}

// pyExpectedWire returns the WireType member a field's header must carry for its
// schema-typed reader to be the right one, mirroring the encode side
// (emitMarshal / marshalArray): unsigned integers, bool and bitfield ->
// UNSIGNED; signed integers and enum -> SIGNED; fp32/fp64, string and blob ->
// FIXLEN; nested messages and composite (wrapper) arrays -> SEQUENCE_START;
// native scalar arrays -> the matching ARRAY_* wire type.
func pyExpectedWire(fld *ir.Field) string {
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBool, ir.KindBitfield:
		return "WireType.UNSIGNED"
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		return "WireType.SIGNED"
	case ir.KindFP32, ir.KindFP64, ir.KindString, ir.KindBlob:
		return "WireType.FIXLEN"
	case ir.KindStruct, ir.KindUnion:
		return "WireType.SEQUENCE_START"
	case ir.KindArray:
		if !isNativeArrayElem(fld.Elem) {
			return "WireType.SEQUENCE_START"
		}
		switch fld.Elem {
		case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
			return "WireType.ARRAY_SIGNED"
		case ir.KindFP32, ir.KindFP64:
			return "WireType.ARRAY_FIXLEN"
		default: // u8/u16/u32/u64, bool, bitfield
			return "WireType.ARRAY_UNSIGNED"
		}
	}
	return "WireType.SEQUENCE_START" // unreachable: keeps the switch total
}

// pyWireGuard renders the §7.3 condition a field header must satisfy before its
// schema-typed reader may run: the wire type the declared type maps to, plus the
// fixlen subtype where the wire type alone is ambiguous (fp32/fp64/string/blob,
// and the fp32/fp64 native arrays, which share FIXLEN / ARRAY_FIXLEN).
func pyWireGuard(fld *ir.Field) string {
	cond := "fld.type != " + pyExpectedWire(fld)
	sub := pyFixlenSubtype(fld.Kind)
	if fld.Kind == ir.KindArray && isNativeArrayElem(fld.Elem) {
		sub = pyFixlenSubtype(fld.Elem)
	}
	if sub != "" {
		cond += " or fld.subtype != " + sub
	}
	return cond
}

// pyElemWireGuard is pyWireGuard for a wrapper-sequence ELEMENT: §5.1 makes each
// element a normal field, so §7.3 applies — an element whose wire type/subtype
// contradicts the declared element type is skipped like an unknown id (issue
// #189), not fed to the schema-typed reader. Named by the element's header
// variable `ef` (`_ef<depth>`) rather than the field's `fld`, and mapped through
// a synthetic field so it stays in lockstep with the field-level guard.
func pyElemWireGuard(ef string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem) string {
	x := &ir.Field{Kind: elem, Ref: ref}
	if elem == ir.KindArray {
		x.Elem = items.Elem
		x.ElemRef = items.ElemRef
	}
	cond := ef + ".type != " + pyExpectedWire(x)
	sub := pyFixlenSubtype(elem)
	if elem == ir.KindArray && isNativeArrayElem(items.Elem) {
		sub = pyFixlenSubtype(items.Elem)
	}
	if sub != "" {
		cond += " or " + ef + ".subtype != " + sub
	}
	return cond
}

// schemaHasField reports whether any message or named-type field satisfies pred.
func schemaHasField(s *ir.Schema, pred func(*ir.Field) bool) bool {
	any := func(fields []*ir.Field) bool {
		for _, fld := range fields {
			if pred(fld) {
				return true
			}
		}
		return false
	}
	for _, key := range s.NamedOrder {
		if any(s.Named[key].Fields) {
			return true
		}
	}
	for _, m := range s.Messages {
		if any(m.Fields) {
			return true
		}
	}
	return false
}

func (g *gen) emitEnum(f *pyfile, nt *ir.NamedType) {
	f.line("class %s(IntEnum):", g.typeName(nt.Key))
	for _, c := range nt.Consts {
		// Sphinx attribute comment(s) carrying the constant's description, above
		// the member so pydoc/Sphinx attaches it to the enum value.
		if c.Description != "" {
			for _, dl := range strings.Split(c.Description, "\n") {
				f.line("    #: %s", dl)
			}
		}
		f.line("    %s = %d", strings.ToUpper(c.Name), c.Value)
	}
	f.blank()
}

func (g *gen) emitBitfieldConsts(f *pyfile, nt *ir.NamedType) {
	f.line("class %s(IntEnum):", g.typeName(nt.Key))
	for _, fl := range nt.Flags {
		// Sphinx attribute comment(s): the flag description, with the schema
		// default appended as "(default: true/false)" when the flag has one.
		for _, dl := range bitfieldFlagDocLines(fl) {
			f.line("    #: %s", dl)
		}
		f.line("    %s = 1 << %d", strings.ToUpper(fl.Name), fl.Pos)
	}
	f.blank()
}

// bitfieldFlagDocLines builds the Sphinx attribute-comment text (without the
// leading "#: ") for a bitfield flag: its Description, plus a trailing
// "(default: true)" / "(default: false)" note appended to the last line when
// the flag declares a default. Returns nil when there is nothing to document.
func bitfieldFlagDocLines(fl *ir.BitfieldFlag) []string {
	var lines []string
	if fl.Description != "" {
		lines = strings.Split(fl.Description, "\n")
	}
	if fl.HasDefault {
		note := "(default: false)"
		if fl.Default {
			note = "(default: true)"
		}
		if len(lines) == 0 {
			lines = []string{note}
		} else {
			lines[len(lines)-1] = lines[len(lines)-1] + " " + note
		}
	}
	return lines
}

// emitClassDoc writes a triple-quoted class docstring as the first statement of
// the class body when the summary is non-empty. A single-line summary becomes
// """<summary>"""; a multi-line summary opens with """ on the first line and
// closes with """ on its own line. UTF-8 passes through byte-for-byte.
func emitClassDoc(f *pyfile, summary string) {
	if summary == "" {
		return
	}
	lines := strings.Split(summary, "\n")
	if len(lines) == 1 {
		f.line(`    """%s"""`, lines[0])
		return
	}
	f.line(`    """%s`, lines[0])
	for _, ln := range lines[1:] {
		f.line("    %s", ln)
	}
	f.line(`    """`)
}

// pyFieldDocLines builds the Sphinx attribute-comment text (without the leading
// "#: ") from a field's Description and Unit. A multi-line description yields one
// line per source line; a non-empty Unit is appended as " (unit: <Unit>)" to the
// last line. A deprecated field gets a trailing ".. deprecated::" directive so
// Sphinx renders the deprecation and pydoc surfaces the note. Returns nil when
// there is nothing to document.
func pyFieldDocLines(fld *ir.Field) []string {
	var lines []string
	if fld.Description != "" {
		lines = strings.Split(fld.Description, "\n")
	}
	if fld.Unit != "" {
		if len(lines) == 0 {
			lines = []string{fmt.Sprintf("(unit: %s)", fld.Unit)}
		} else {
			lines[len(lines)-1] = fmt.Sprintf("%s (unit: %s)", lines[len(lines)-1], fld.Unit)
		}
	}
	if note := generator.BoundNote(fld, generator.StorageDynamic); note != "" {
		lines = append(lines, note)
	}
	if fld.Deprecated {
		lines = append(lines,
			".. deprecated::",
			"   Deprecated and retained only for backward compatibility; do not use in new code.")
	}
	return lines
}

func (g *gen) emitDataclass(f *pyfile, name, summary string, fields []*ir.Field) {
	f.line("@dataclass")
	f.line("class %s:", name)
	// Class docstring (pydoc/Sphinx) as the first statement in the body, when the
	// summary is non-empty. It also satisfies the body for a field-less class.
	emitClassDoc(f, summary)
	if len(fields) == 0 && summary == "" {
		f.line("    pass")
	}
	for _, fld := range fields {
		// Sphinx attribute comment(s) immediately before the declaration.
		for _, dl := range pyFieldDocLines(fld) {
			f.line("    #: %s", dl)
		}
		f.line("    %s: %s = %s", pyIdent(fld.Name), g.pyAnnot(fld), g.pyDefault(fld))
	}
	f.blank()

	// Worst-case encoded size. It is what sizes the buffer encode() hands the
	// encoder: the corelib is given storage and never grows or reallocates it
	// (CORELIB_PLAN §5.1), so the number has to come from the schema, here.
	//
	// Deliberately unannotated: an annotated class attribute in a @dataclass
	// becomes a FIELD, which would put MAX_SIZE on the wire and in __init__.
	ms := g.messageSize(name, fields)
	if ms.Bounded {
		f.line("    # Worst-case encoded size, derived from the schema: no value of this")
		f.line("    # class can encode to more, which is why encode() can size one exact")
		f.line("    # buffer from it.")
		f.line("    MAX_SIZE = %d", ms.Size)
	} else {
		f.line("    # Configured ceiling (max_message_size), NOT a size this class cannot")
		f.line("    # exceed: a field of it is unbounded, so the schema supplies no worst")
		f.line("    # case and encode() must not size a buffer from this number.")
		f.line("    MAX_SIZE_LIMIT = %d", ms.Size)
		f.line("    MAX_SIZE = MAX_SIZE_LIMIT")
	}
	f.blank()

	g.emitIsDefault(f, fields)

	// _marshal
	f.line("    def serialize(self, e: Encoder) -> None:")
	if len(fields) == 0 {
		f.line("        pass")
	}
	for _, fld := range fields {
		g.emitMarshal(f, fld)
	}
	f.blank()

	// _unmarshal (pull-parser)
	f.line("    def deserialize(self, d: Decoder) -> None:")
	f.line("        while True:")
	f.line("            fld = d.next()")
	f.line("            if fld is None or fld.type == WireType.SEQUENCE_END:")
	f.line("                return")
	for i, fld := range fields {
		kw := "elif"
		if i == 0 {
			kw = "if"
		}
		f.line("            %s fld.id == %d:", kw, fld.ID)
		// Frame each field by its header wire type before reading (MESSAGE_SPEC
		// §7.3). The schema-typed readers assume they are only called for their
		// matching wire type — corelib-py raises SofaStateError from _take_scalar /
		// _take_fixlen when they are not, which is the right answer to a *caller*
		// error but the wrong outcome here: a field whose header contradicts the
		// schema must be skipped like an unknown id, not fail the whole decode.
		// The wire type is already in hand (fld.type is read above), so the guard
		// costs one comparison and keeps the decoder synced.
		f.line("                if %s:", pyWireGuard(fld))
		f.line("                    d.skip()")
		f.line("                    continue")
		g.emitUnmarshal(f, fld)
	}
	if len(fields) > 0 {
		f.line("            else:")
		f.line("                d.skip()")
	} else {
		f.line("            d.skip()")
	}
	f.blank()

	// JSON helpers + encode/decode
	g.emitJSON(f, name, fields, ms)
}

// emitIsDefault emits the object's all-default predicate. It is the exact
// negation of what _marshal writes: the object is default iff _marshal would
// emit no child at all, evaluated per field and recursively (MESSAGE_SPEC §2).
// Keep this in lockstep with emitMarshal -- both are generated from
// fieldIsDefaultExpr's per-field expressions for exactly that reason. A predicate
// that disagrees with the writer omits a field that is on the wire, or keeps one
// that is not.
func (g *gen) emitIsDefault(f *pyfile, fields []*ir.Field) {
	f.line("    def _is_default(self) -> bool:")
	if len(fields) == 0 {
		f.line("        return True")
		f.blank()
		return
	}
	for _, fld := range fields {
		f.line("        if not (%s):", g.fieldIsDefaultExpr(fld))
		f.line("            return False")
	}
	f.line("        return True")
	f.blank()
}

// fieldIsDefaultExpr is the boolean expression "this field equals its default",
// i.e. the negation of emitMarshal's write guard for the same field.
func (g *gen) fieldIsDefaultExpr(fld *ir.Field) string {
	acc := "self." + pyIdent(fld.Name)
	switch fld.Kind {
	case ir.KindBlob:
		// emitMarshal compares bytes(acc) so a bytearray/memoryview value still
		// matches the literal default.
		return fmt.Sprintf("bytes(%s) == %s", acc, g.pyDefault(fld))
	case ir.KindStruct, ir.KindUnion:
		// Lazily framed: the frame survives iff the nested _marshal wrote a child,
		// which is exactly "the nested object is not default".
		return fmt.Sprintf("%s._is_default()", acc)
	case ir.KindArray:
		return g.arrayIsDefaultExpr(fld, acc)
	}
	return fmt.Sprintf("%s == %s", acc, g.pyDefault(fld))
}

// arrayIsDefaultExpr mirrors emitMarshalArray. An array's declared `count: N` is
// a CAPACITY, never a length (MESSAGE_SPEC §3), so it takes no part in this test:
// the value is compared against the declared default exactly as written, with no
// padding to N on either side, and against the empty collection when none is
// declared. A count:N array is therefore default only when it is EMPTY -- an
// all-zero N-element value is a length-N array, which differs from the empty one
// and stays on the wire.
func (g *gen) arrayIsDefaultExpr(fld *ir.Field, acc string) string {
	if isNativeArrayElem(fld.Elem) {
		if lit, ok := g.pyNativeArrayDefault(fld); ok {
			return fmt.Sprintf("%s == %s", acc, lit)
		}
		return fmt.Sprintf("len(%s) == 0", acc)
	}
	// Wrapper array: the writer emits a child for every element it holds, because
	// the LAST element is written whatever its value (§2) -- so "no child is
	// written" is exactly "the array is empty", and the two cannot drift apart.
	return fmt.Sprintf("len(%s) == 0", acc)
}

func (g *gen) emitMarshal(f *pyfile, fld *ir.Field) {
	acc := "self." + pyIdent(fld.Name)
	var write string
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		write = fmt.Sprintf("e.write_unsigned(%d, int(%s))", fld.ID, acc)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		write = fmt.Sprintf("e.write_signed(%d, int(%s))", fld.ID, acc)
	case ir.KindBool:
		write = fmt.Sprintf("e.write_bool(%d, %s)", fld.ID, acc)
	case ir.KindFP32:
		write = fmt.Sprintf("e.write_float32(%d, %s)", fld.ID, acc)
	case ir.KindFP64:
		write = fmt.Sprintf("e.write_float64(%d, %s)", fld.ID, acc)
	case ir.KindString:
		write = fmt.Sprintf("e.write_string(%d, %s)", fld.ID, acc)
	case ir.KindBlob:
		// blob is a leaf: omit when equal to its default (empty if none).
		f.line("        if bytes(%s) != %s:", acc, g.pyDefault(fld))
		f.line("            e.write_bytes(%d, bytes(%s))", fld.ID, acc)
		return
	case ir.KindStruct, ir.KindUnion:
		// MESSAGE_SPEC S2: the != default test is per field and a sequence is no
		// exception, so the frame is opened LAZILY -- the corelib holds the header
		// back until a child field appears. The nested marshal omits each child that
		// equals its default, so "no child was written" IS "the object equals its
		// declared default", evaluated per field and recursively. An all-default
		// nested object is therefore dropped, not emitted as an empty wrapper.
		f.line("        e.write_sequence_begin_lazy(%d)", fld.ID)
		f.line("        %s.serialize(e)", acc)
		f.line("        e.write_sequence_end()")
		return
	case ir.KindArray:
		g.emitMarshalArray(f, fld, acc)
		return
	}
	// Scalar/string/enum/bitfield leaf: always omit when equal to the default;
	// sparse encoding is canonical (MESSAGE_SPEC S2) and the decoder reconstructs
	// the omitted field from its default.
	f.line("        if %s != %s:", acc, g.pyDefault(fld))
	f.line("            %s", write)
}

func (g *gen) emitMarshalArray(f *pyfile, fld *ir.Field, acc string) {
	// A native scalar array is a leaf field: omit it when equal to its default
	// (materialized in the dataclass), else when empty. A composite/dynamic-element
	// array is a wrapper sequence, opened lazily and closed by the dropping end
	// (see marshalArray) -- an empty one vanishes instead of being framed empty.
	//
	// A declared `count: N` takes no part in either test. `count` is a CAPACITY,
	// never a length (§3): it never reaches the wire, so the value is compared
	// against the declared default exactly as written -- neither side padded to N
	// -- and against the empty collection when no default is declared.
	if isNativeArrayElem(fld.Elem) {
		if lit, ok := g.pyNativeArrayDefault(fld); ok {
			f.line("        if %s != %s:", acc, lit)
		} else {
			f.line("        if len(%s) != 0:", acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, "")
		return
	}
	// The field-level wrapper frame is dropped when no element is written, and
	// absence then reconstructs the field's default. That is correct because a
	// wrapper array's declared `default` is not materialized today -- the dataclass
	// default is the empty list -- so absent and explicitly-empty denote the same
	// value. If that gap is ever closed, this call needs a guard --
	// `if value != default: ... e.write_sequence_end_keep()` -- so that a value
	// differing from a non-empty default still reaches the wire as the empty
	// wrapper, the only encoding of "explicitly empty" (MESSAGE_SPEC §2, §3).
	g.marshalArray(f, "        ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, "")
}

// lastElemExpr is the "this element is the array's last" test, at loop position
// iv over the value val.
//
// It is the whole of the positional half of MESSAGE_SPEC §2's element rule. A
// wrapper array carries no length field: its decoded length is *highest present
// id + 1* (§5.1), so the element at the highest index is the only one whose
// PRESENCE carries the length, and nothing that carries the length may be elided.
// Everything before it may be: an interior element equal to the element default
// is indistinguishable from an absent one, because the decoder restores an absent
// id from that same default. Hence: interior sparse, last always written.
//
// A declared `count: N` changes nothing here. N is a capacity, not a length (§3),
// so it can never restore an elided tail -- the same test applies with or without
// one.
func lastElemExpr(iv, val string) string {
	return fmt.Sprintf("%s == len(%s) - 1", iv, val)
}

// emitSeqEnd closes the wrapper sequence opened at ind, choosing between the two
// closers the corelib offers. Every sequence is opened LAZILY (the corelib holds
// the header back until a child is written), so the closer alone decides whether
// a contentless one survives: write_sequence_end drops it, write_sequence_end_keep
// forces the empty frame out.
//
// keepIf is the condition under which an empty frame must survive:
//   - "" -- never. A sequence-typed FIELD (a struct/union field, an array
//     wrapper): an all-default one is omitted and absence reconstructs it (§2).
//   - a lastElemExpr -- a sequence-form array ELEMENT, kept only at the array's
//     last index. In the interior it is dropped and leaves an id GAP, which is
//     what makes an all-default element sparse like any other default value.
//     Note this is decided from the position in the VALUE, at run time; the
//     schema cannot answer it.
func emitSeqEnd(f *pyfile, ind, keepIf string) {
	if keepIf == "" {
		f.line("%se.write_sequence_end()", ind)
		return
	}
	f.line("%sif %s:", ind, keepIf)
	f.line("%s    e.write_sequence_end_keep()", ind)
	f.line("%selse:", ind)
	f.line("%s    e.write_sequence_end()", ind)
}

// marshalArray writes the array `val` as field `idExpr`. Numeric/enum/boolean/
// bitfield elements use the native array wire type (enum->signed, bool/bitfield->
// unsigned); string/blob/struct/union/array elements lower to a wrapper sequence
// whose child ids are the 0-based index (per MESSAGE_SPEC). Recurses for nested
// arrays.
//
// Every element the value holds is written -- no trailing run is elided, of
// either element kind, because the wire count IS the array's length (§3) and the
// highest wrapper id IS its last index (§5.1). What the interior may drop is a
// value that is indistinguishable from absence, and only that.
//
// keepIf is the closer this call's own wrapper takes (see emitSeqEnd); the native
// element kinds open no sequence and ignore it.
func (g *gen) marshalArray(f *pyfile, ind, idExpr, val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, depth int, keepIf string) {
	iv := fmt.Sprintf("_i%d", depth)
	ev := fmt.Sprintf("_e%d", depth)
	switch elem {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64:
		f.line("%se.write_unsigned_array(%s, %s)", ind, idExpr, val)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64:
		f.line("%se.write_signed_array(%s, %s)", ind, idExpr, val)
	case ir.KindEnum:
		f.line("%se.write_signed_array(%s, [int(_v) for _v in %s])", ind, idExpr, val)
	case ir.KindBool:
		f.line("%se.write_unsigned_array(%s, [1 if _v else 0 for _v in %s])", ind, idExpr, val)
	case ir.KindBitfield:
		f.line("%se.write_unsigned_array(%s, [int(_v) for _v in %s])", ind, idExpr, val)
	case ir.KindFP32:
		f.line("%se.write_float32_array(%s, %s)", ind, idExpr, val)
	case ir.KindFP64:
		f.line("%se.write_float64_array(%s, %s)", ind, idExpr, val)
	case ir.KindString:
		// A string element is a leaf: in the array's INTERIOR it is omitted when it
		// equals the element default (empty), leaving an id gap the decoder restores
		// from that same default -- the ordinary sparse-field rule of MESSAGE_SPEC
		// §2, applied to an element. At the LAST index it is written whatever its
		// value: see lastElemExpr.
		f.line("%se.write_sequence_begin_lazy(%s)", ind, idExpr)
		f.line("%sfor %s, %s in enumerate(%s):", ind, iv, ev, val)
		f.line(`%s    if %s != "" or %s:`, ind, ev, lastElemExpr(iv, val))
		f.line("%s        e.write_string(%s, %s)", ind, iv, ev)
		emitSeqEnd(f, ind, keepIf)
	case ir.KindBlob:
		// A blob element is a leaf, exactly like the string element above.
		f.line("%se.write_sequence_begin_lazy(%s)", ind, idExpr)
		f.line("%sfor %s, %s in enumerate(%s):", ind, iv, ev, val)
		f.line("%s    if len(%s) != 0 or %s:", ind, ev, lastElemExpr(iv, val))
		f.line("%s        e.write_bytes(%s, bytes(%s))", ind, iv, ev)
		emitSeqEnd(f, ind, keepIf)
	case ir.KindStruct, ir.KindUnion:
		// A sequence-form element obeys the SAME rule as the leaf elements above --
		// one rule for both kinds -- and the lazily-held frame is where it is
		// applied. The nested _marshal writes no child exactly when the element
		// equals its declared default, so the CLOSER alone decides: the dropping one
		// in the interior, where an all-default element vanishes into an id gap; the
		// keeping one at the last index, where it survives as an empty frame because
		// that presence is what fixes the array's length.
		f.line("%se.write_sequence_begin_lazy(%s)", ind, idExpr)
		f.line("%sfor %s, %s in enumerate(%s):", ind, iv, ev, val)
		f.line("%s    e.write_sequence_begin_lazy(%s)", ind, iv)
		f.line("%s    %s.serialize(e)", ind, ev)
		emitSeqEnd(f, ind+"    ", lastElemExpr(iv, val))
		emitSeqEnd(f, ind, keepIf)
	case ir.KindArray:
		f.line("%se.write_sequence_begin_lazy(%s)", ind, idExpr)
		f.line("%sfor %s, %s in enumerate(%s):", ind, iv, ev, val)
		if isNativeArrayElem(items.Elem) {
			// A native row is a single count-prefixed value with no frame of its own,
			// so the rule lands on the WRITE rather than on a closer: an interior row
			// equal to the element default (the empty row) is not written at all, and
			// the last row always is.
			f.line("%s    if len(%s) != 0 or %s:", ind, ev, lastElemExpr(iv, val))
			g.marshalArray(f, ind+"        ", iv, ev, items.Elem, items.ElemRef, items.ElemItems, depth+1, "")
		} else {
			// A wrapper row has its own frame, so it takes the closer instead -- the
			// same interior/last choice, expressed the same way as for a struct
			// element above.
			g.marshalArray(f, ind+"    ", iv, ev, items.Elem, items.ElemRef, items.ElemItems, depth+1, lastElemExpr(iv, val))
		}
		emitSeqEnd(f, ind, keepIf)
	}
}

// emitWidthGuard writes the §7.1 declared-width rejection for the value just read
// into `acc` (documentation#32): a `u8`/`u16`/`u32`/`i8`/`i16`/`i32` destination
// carrying a value outside its declared range is malformed input. Python's int is
// unbounded, so nothing masks the value here — the whole defect on this backend
// was that an out-of-range value was simply KEPT — and the raise aborts the
// decode before the object is handed back. Nothing is emitted for u64/i64.
//
// Mirrors the blob arm's read-then-check order rather than reading into a temp:
// the guard reads better beside the store, and a raised decode never returns the
// object it was filling.
func emitWidthGuard(f *pyfile, ind, acc, name string, k ir.Kind) {
	lo, hi, ok := ir.NarrowRange(k)
	if !ok {
		return
	}
	cond := fmt.Sprintf("%s > %d", acc, hi)
	if lo < 0 {
		cond = fmt.Sprintf("%s < %d or %s > %d", acc, lo, acc, hi)
	}
	f.line("%sif %s:", ind, cond)
	f.line(`%s    raise SofaDecodeError("%s: value outside declared width %s")`, ind, name, k)
}

// elemBoundArgs renders the declared element width as the read call's argument
// list — `255` for an unsigned array, `-128, 127` for a signed one — or "" for
// u64/i64, whose range is the value domain the corelib already returns.
//
// The bound travels WITH the read for the same reason the schema count and a
// blob's maxlen already do: a scan over the returned list decides an array that
// arrives, and never runs for one that does not, so a message cut short after an
// out-of-width element reported INCOMPLETE where §5.2 requires INVALID
// (generator#267, Crucible F-0043 width_elem_trunc). corelib-py takes the bound
// on both engines: the native one checks at the element, the pure one at the
// truncation, which is the same verdict either way.
func elemBoundArgs(elem ir.Kind) string {
	lo, hi, ok := ir.NarrowRange(elem)
	if !ok {
		return ""
	}
	if lo < 0 {
		return fmt.Sprintf("%d, %d", lo, hi)
	}
	return fmt.Sprintf("%d", hi)
}

// emitArrayWidthGuard is the same §7.1 bound for a native array's ELEMENTS,
// applied to the assembled list.
//
// It stays alongside elemBoundArgs rather than being replaced by it. The two
// answer different questions: the reader's bound is what makes a TRUNCATED array
// INVALID, and this scan is what still bounds the elements if a consumer builds
// against a corelib whose readers ignore the arguments. It costs one pass over a
// list already in hand.
func emitArrayWidthGuard(f *pyfile, ind, target, loc string, elem ir.Kind) {
	lo, hi, ok := ir.NarrowRange(elem)
	if !ok {
		return
	}
	cond := fmt.Sprintf("_v > %d", hi)
	if lo < 0 {
		cond = fmt.Sprintf("_v < %d or _v > %d", lo, hi)
	}
	f.line("%sif any(%s for _v in %s):", ind, cond, target)
	f.line(`%s    raise SofaDecodeError("%s element: value outside declared width %s")`, ind, loc, elem)
}

func (g *gen) emitUnmarshal(f *pyfile, fld *ir.Field) {
	acc := "self." + pyIdent(fld.Name)
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		f.line("                %s = d.unsigned()", acc)
		if fld.Kind != ir.KindBitfield {
			emitWidthGuard(f, "                ", acc, fld.Name, fld.Kind)
		}
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		f.line("                %s = d.signed()", acc)
		if fld.Kind != ir.KindEnum {
			emitWidthGuard(f, "                ", acc, fld.Name, fld.Kind)
		}
	case ir.KindBool:
		f.line("                %s = d.bool()", acc)
	case ir.KindFP32:
		f.line("                %s = d.float32()", acc)
	case ir.KindFP64:
		f.line("                %s = d.float64()", acc)
	case ir.KindString:
		// A bounded string whose UTF-8 BYTE length exceeds its schema maxlen is
		// malformed input — reject, never truncate (MESSAGE_SPEC §7.1). Bound
		// against the exact wire byte length the decoder already parsed
		// (d.fixlen_len(), a non-consuming peek), checked before the string is
		// materialized — never re-encode the decoded str to measure it.
		if fld.HasMaxlen {
			f.line("                d.schema_bounded()")
			f.line("                if d.fixlen_len() > %d:", fld.Maxlen)
			f.line(`                    raise SofaDecodeError("%s: string byte length above schema maxlen %d")`, fld.Name, fld.Maxlen)
		}
		f.line("                %s = d.string()", acc)
	case ir.KindBlob:
		// A bounded blob whose byte length exceeds its schema maxlen is malformed
		// input — reject, never truncate (MESSAGE_SPEC §7.1). Bound against the
		// exact wire byte length the decoder already parsed (d.fixlen_len(), a
		// non-consuming peek) BEFORE the payload is read, exactly as the string arm
		// above does.
		//
		// The order is the whole point (generator#267 / Crucible F-0043): §5.2 makes
		// INVALID dominate INCOMPLETE, so a message truncated right after the length
		// word — where the violation is already fully established — must still be
		// INVALID. Reading first and measuring the decoded bytes afterwards never
		// reaches the check on such a message and reported INCOMPLETE instead.
		if fld.HasMaxlen {
			f.line("                d.schema_bounded()")
			f.line("                if d.fixlen_len() > %d:", fld.Maxlen)
			f.line(`                    raise SofaDecodeError("%s: blob byte length above schema maxlen %d")`, fld.Name, fld.Maxlen)
		}
		f.line("                %s = d.bytes()", acc)
	case ir.KindStruct, ir.KindUnion:
		f.line("                %s.deserialize(d)", acc)
	case ir.KindArray:
		g.emitUnmarshalArray(f, fld, acc)
	}
}

// capOf maps a schema fixed-count bound to a wrapper array's cap: N when the
// array declares a count, -1 (dynamic/unbounded) otherwise.
func capOf(hasCount bool, count int64) int64 {
	if hasCount {
		return count
	}
	return -1
}

func (g *gen) emitUnmarshalArray(f *pyfile, fld *ir.Field, acc string) {
	// The wire count M IS the array's length (MESSAGE_SPEC §3): the M elements that
	// arrived are the whole value, so they are taken as they come. A declared
	// `count: N` is a capacity and bounds M (emitCountGuard, inside); it never adds
	// elements, so there is nothing to fill in at [M, N).
	g.unmarshalArray(f, "                ", acc, fld.Name, fld.Elem, fld.ElemRef, fld.ElemItems, capOf(fld.HasCount, fld.Count), fld.ElemMaxHas, fld.ElemMax, 0)
}

// arrayFieldVar names the generated variable holding the Field header that
// delivered the array being read at `depth`: the message loop's `fld` for a
// top-level array field, and the enclosing wrapper loop's `_ef<depth-1>` for a
// nested row (the row's own header, read by that loop's d.next()).
func arrayFieldVar(depth int) string {
	if depth == 0 {
		return "fld"
	}
	return fmt.Sprintf("_ef%d", depth-1)
}

// emitCountGuard rejects a NATIVE array whose wire element count exceeds the
// schema `count` capacity N. Such a count is INVALID per MESSAGE_SPEC §3+§7 —
// reject the whole message, never keep-all (generator#100). Decide it at the
// count header: the wire element count is on the delivered Field (`.count`, read
// by d.next() before any element), so rejecting BEFORE read_*_array() — which
// would raise SofaIncompleteError on a truncated tail — makes INVALID dominate
// INCOMPLETE per §5.2 (generator#216 / F-0032). A check on len() after the read
// never fires when truncation cuts the array short of the announced count.
//
// This lives with the native READ rather than at the top-level field, because a
// nested native row (array<array<u32>>) is read through exactly the same branch
// and carries its own capacity: its count header is the row element's header in
// the enclosing wrapper loop, and bounding it there is the only place the row's
// `count` can be enforced at all. Count-less (dynamic) arrays have no bound;
// wrapper-element arrays have no count header and are bounded by element id
// instead (§5.1, the over-index guard below).
func emitCountGuard(f *pyfile, ind, loc string, cap int64, depth int) {
	if cap < 0 {
		return
	}
	f.line("%sd.schema_bounded()", ind)
	f.line("%sif %s.count > %d:", ind, arrayFieldVar(depth), cap)
	f.line(`%s    raise SofaDecodeError("%s: array count above schema capacity %d")`, ind, loc, cap)
}

// unmarshalArray reads an array into `target`, mirroring marshalArray: native
// array readers for numeric/enum/boolean/bitfield elements, a wrapper-sequence
// loop for string/blob/struct/union/array elements. Recurses for nested arrays.
//
// `loc` is the schema location named in a rejection message (the field name at
// the top level, suffixed per nesting level for a row).
func (g *gen) unmarshalArray(f *pyfile, ind, target, loc string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, cap int64, elemMaxHas bool, elemMax int64, depth int) {
	switch elem {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		emitCountGuard(f, ind, loc, cap, depth)
		if elem == ir.KindBitfield {
			f.line("%s%s = d.read_unsigned_array()", ind, target)
		} else {
			f.line("%s%s = d.read_unsigned_array(%s)", ind, target, elemBoundArgs(elem))
			emitArrayWidthGuard(f, ind, target, loc, elem)
		}
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		emitCountGuard(f, ind, loc, cap, depth)
		if elem == ir.KindEnum {
			f.line("%s%s = d.read_signed_array()", ind, target)
		} else {
			f.line("%s%s = d.read_signed_array(%s)", ind, target, elemBoundArgs(elem))
			emitArrayWidthGuard(f, ind, target, loc, elem)
		}
	case ir.KindBool:
		emitCountGuard(f, ind, loc, cap, depth)
		f.line("%s%s = [bool(_v) for _v in d.read_unsigned_array()]", ind, target)
	case ir.KindFP32:
		emitCountGuard(f, ind, loc, cap, depth)
		f.line("%s%s = d.read_float32_array()", ind, target)
	case ir.KindFP64:
		emitCountGuard(f, ind, loc, cap, depth)
		f.line("%s%s = d.read_float64_array()", ind, target)
	default: // string/blob/struct/union/array -> wrapper sequence
		ef := fmt.Sprintf("_ef%d", depth)
		ev := fmt.Sprintf("_e%d", depth)
		f.line("%s%s = []", ind, target)
		f.line("%swhile True:", ind)
		f.line("%s    %s = d.next()", ind, ef)
		f.line("%s    if %s is None or %s.type == WireType.SEQUENCE_END:", ind, ef, ef)
		f.line("%s        break", ind)
		// §7.3 (issue #189): an element whose wire type/subtype contradicts the
		// declared element type is skipped like an unknown id — before the
		// over-index check, so a mis-typed element is skipped, not rejected for its
		// id — never handed to the schema-typed reader (which would raise).
		f.line("%s    if %s:", ind, pyElemWireGuard(ef, elem, ref, items))
		f.line("%s        d.skip()", ind)
		f.line("%s        continue", ind)
		// Fixed-count wrapper array: an element id >= N is INVALID (MESSAGE_SPEC
		// §5.1/§7 — issue #142), rejected before the list grows, which also bounds
		// an over-index heap-amplification fill. A dynamic array keeps every index.
		if cap >= 0 {
			f.line("%s    d.schema_bounded()", ind)
			f.line("%s    if %s.id >= %d:", ind, ef, cap)
			f.line(`%s        raise SofaDecodeError("%s: array index above schema capacity %d")`, ind, target, cap)
		}
		switch elem {
		case ir.KindString:
			// A string element is keyed by index id: an INTERIOR element equal to the
			// element default is omitted on the wire, so place the value at its id and
			// fill any gap with the element default "" (MESSAGE_SPEC §2). The array's
			// LAST element is always present, so the decoded length -- highest present
			// id + 1 -- is exact.
			f.line("%s    while len(%s) <= %s.id:", ind, target, ef)
			f.line(`%s        %s.append("")`, ind, target)
			// A bounded string element whose UTF-8 BYTE length exceeds the element
			// maxlen is malformed — reject, never truncate (MESSAGE_SPEC §7.1). Bound
			// against the wire byte length (non-consuming peek) before the element is
			// materialized — never re-encode the decoded str to measure it.
			if elemMaxHas {
				f.line("%s    d.schema_bounded()", ind)
				f.line(`%s    if d.fixlen_len() > %d:`, ind, elemMax)
				f.line(`%s        raise SofaDecodeError("%s: string element byte length above schema maxlen %d")`, ind, target, elemMax)
			}
			f.line("%s    %s[%s.id] = d.string()", ind, target, ef)
		case ir.KindBlob:
			// A blob element is keyed by index id: a default (empty) element is
			// omitted on the wire, so place the value at its id and fill any gap
			// with the element default b"" (MESSAGE_SPEC S2).
			f.line("%s    while len(%s) <= %s.id:", ind, target, ef)
			f.line(`%s        %s.append(b"")`, ind, target)
			// Declared BEFORE the read: this arm measures the materialized bytes
			// rather than peeking the length word, so a receiver cap would reject
			// during d.bytes() -- one call before the schema bound below could
			// speak (§6.2.1: on a bounded field the schema governs).
			if elemMaxHas {
				f.line("%s    d.schema_bounded()", ind)
			}
			f.line("%s    %s[%s.id] = d.bytes()", ind, target, ef)
			// A bounded blob element whose byte length exceeds the element maxlen
			// is malformed — reject, never truncate (MESSAGE_SPEC §7.1).
			if elemMaxHas {
				f.line("%s    if len(%s[%s.id]) > %d:", ind, target, ef, elemMax)
				f.line(`%s        raise SofaDecodeError("%s: blob element byte length above schema maxlen %d")`, ind, target, elemMax)
			}
		case ir.KindStruct, ir.KindUnion:
			// A struct/union element is keyed by index id exactly like the string and
			// blob leaves above (MESSAGE_SPEC §5.1: the element id IS the array
			// index), so the element is PLACED at target[id] after gap-filling with
			// default elements -- never appended (generator#247). Appending would
			// shorten the array by the size of any interior id gap, and would decode a
			// REOPENED element id as a second element instead of merging into the
			// first; decoding INTO the element already at that index gives the §7.4
			// struct-merge for free. The over-index guard above still rejects an
			// element id >= N, which also bounds this gap-fill.
			f.line("%s    while len(%s) <= %s.id:", ind, target, ef)
			f.line("%s        %s.append(%s())", ind, target, g.typeName(ref.Key))
			f.line("%s    %s[%s.id].deserialize(d)", ind, target, ef)
		case ir.KindArray:
			// A ROW is keyed by its element id exactly like every other element kind
			// (§5.1), so it is PLACED at target[id] after gap-filling with empty rows
			// -- never appended. Appending was unreachable while every row was framed
			// unconditionally; under §2's sparse rule an interior row equal to the
			// element default (the empty row) is omitted, and an appending collector
			// would then shift every later row down by one. The over-index guard above
			// rejects a row id >= N, which also bounds this gap-fill.
			g.unmarshalArray(f, ind+"    ", ev, loc+" row", items.Elem, items.ElemRef, items.ElemItems, capOf(items.HasCount, items.Count), items.ElemMaxHas, items.ElemMax, depth+1)
			f.line("%s    while len(%s) <= %s.id:", ind, target, ef)
			f.line("%s        %s.append([])", ind, target)
			f.line("%s    %s[%s.id] = %s", ind, target, ef, ev)
		}
	}
}
