// projectFiles scaffolds a runnable TS project: an encode/decode JSON harness
// over the generated module, a package.json depending on @sofa-buffers/corelib,
// and a tsconfig (PLAN §9.1). Run with `npx tsx harness.ts`.
func (g *gen) projectFiles(s *ir.Schema, cfg map[string]any) []generator.File {
	return []generator.File{
		{Path: "harness.ts", Content: g.harness(s)},
		{Path: "package.json", Content: []byte(packageJSON)},
		{Path: "tsconfig.json", Content: []byte(tsconfig)},
		{Path: "README.md", Content: []byte(readme)},
	}
}

const packageJSON = `{
  "//": "@generated by sofabgen",
  "name": "sofabuffers-generated",
  "private": true,
  "type": "module",
  "dependencies": { "@sofa-buffers/corelib": "*" },
  "devDependencies": { "tsx": "^4", "typescript": "^5", "@types/node": "^20" }
}
`

const tsconfig = `{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "skipLibCheck": true,
    "noEmit": true
  }
}
`

const readme = "# Generated SofaBuffers TypeScript module\n\n" +
	"`@generated by sofabgen`. Encode/decode harness over `@sofa-buffers/corelib`.\n\n" +
	"```sh\nnpm install\n" +
	"echo '{...}' | npx tsx harness.ts encode <Message>   # JSON -> bytes\n" +
	"npx tsx harness.ts decode <Message> < bytes.bin       # bytes -> JSON\n" +
	"npx tsx harness.ts recode <Message> < bytes.bin       # bytes -> bytes (no JSON)\n```\n"

func (g *gen) harness(s *ir.Schema) []byte {
	f := &tsfile{}
	f.line("// Code generated by %s; DO NOT EDIT.", g.banner)
	f.line("import * as M from \"./message.js\";")
	f.blank()
	// decode() is typed with encode()/serialize() as well as toJSON(): the `recode`
	// mode below re-encodes a decoded object without going through JSON, which is the
	// only way to observe wire detail a JSON value cannot hold (an fp32 signaling
	// NaN's payload bits, say).
	f.line("const MESSAGES: Record<string, { fromJSON(d: Record<string, unknown>): { encode(): Uint8Array; serialize(os: import(%q).OStream): void; toJSON(): Record<string, unknown> }; decode(b: Uint8Array): { encode(): Uint8Array; serialize(os: import(%q).OStream): void; toJSON(): Record<string, unknown> } }> = {", corelibPkg, corelibPkg)
	for _, m := range s.Messages {
		f.line("  %q: M.%s,", m.Name, exported(m.Name))
	}
	f.line("};")
	f.blank()
	// The incremental Decoder classes are exported per message, beside the message
	// classes rather than on them, so they need a map of their own for the
	// `streamdecode` mode to reach one by message name.
	// `status` is in the structural type on purpose: it is the decoder's memory of
	// what the last `feed` returned, and the streamdecode mode below checks the two
	// agree. Typing it as `unknown` would let that check compare nothing.
	f.line("const DECODERS: Record<string, { new (): { feed(chunk: Uint8Array): import(%q).DecodeStatus; readonly status: import(%q).DecodeStatus; finish(): { toJSON(): Record<string, unknown> } } }> = {", corelibPkg, corelibPkg)
	for _, m := range s.Messages {
		f.line("  %q: M.%sDecoder,", m.Name, exported(m.Name))
	}
	f.line("};")
	f.blank()
	f.line("// benchMain - see tests/bench/README.md.")
	f.line("//")
	f.line("// V8 JIT-compiles the hot path at runtime, so there is no native symbol to")
	f.line("// --toggle-collect on. This is the `subtract` method instead: tests/bench runs")
	f.line("// the same workload at two rep counts and subtracts the totals,")
	f.line("//   Ir/op = ( Ir(R2) - Ir(R1) ) / ( R2 - R1 )")
	f.line("// which cancels node startup, module loading, JIT compilation and JSON parsing")
	f.line("// exactly. It only holds if the two runs differ in NOTHING but the rep count,")
	f.line("// hence `node --predictable` in the bench recipe. Same shape as")
	f.line("// corelib-ts/bench/run_callgrind.sh.")
	f.line("const BENCH_WARMUP = Number(process.env.SOFAB_BENCH_WARMUP ?? 5000);")
	f.blank()
	f.line("async function benchMain(w: string, reps: number, input: Buffer): Promise<number> {")
	for _, m := range s.Messages {
		mt := exported(m.Name)
		low := strings.ToLower(m.Name)
		f.line("  if (w === \"encode_%s\" || w === \"decode_%s\") {", low, low)
		f.line("    const obj = M.%s.fromJSON(JSON.parse(input.toString(\"utf8\")));", mt)
		// encode() allocates the output buffer here in generated code, as every caller
		// must (CORELIB_PLAN §5.1) — so the measured body includes that allocation and
		// the copy of the finished message. That is the real cost of encoding; the
		// former `os.bytes().length` folded a VIEW into a corelib-owned slab and paid
		// for neither.
		f.line("    const wire = obj.encode(); // setup: the decode input")
		f.line("    let sink = 0;")
		// A cheap integer scalar, not toJSON(): the fold runs inside the measured
		// loop, so anything heavier would be counted as decode cost.
		f.line("    const body = w === \"encode_%s\"", low)
		f.line("      ? () => { sink ^= obj.encode().length; }")
		f.line("      : () => { sink ^= %s; };", g.benchSinkExpr(mt, m))
		f.line("    // Fixed warmup, independent of `reps`, so it cancels in the subtraction")
		f.line("    // (corelib-java/.../Callgrind.java does the same). Without it V8 tiers up")
		f.line("    // DURING the measured loop and Ir stops being affine in reps -- the two")
		f.line("    // rep points then measure the JIT rather than the code.")
		f.line("    for (let i = 0; i < BENCH_WARMUP; i++) body();")
		f.line("    for (let i = 0; i < reps; i++) body();")
		f.line("    process.stderr.write(`sink=${sink} bytes=${wire.length}\\n`);")
		f.line("    process.stderr.write(`wire_hex=${Buffer.from(wire).toString(\"hex\")}\\n`);")
		f.line("    return 0;")
		f.line("  }")
		// The CHUNKED decode surface, which neither workload above touches: `decode`
		// is the whole-buffer pull cursor, and the two paths are different code
		// reaching the same fields (the differential test in
		// tests/conformance/typescript/run.sh exists for exactly that reason). A
		// change that only moves on the push path — corelib-ts's opt-in Long channel
		// is one — is invisible in `decode_*`.
		//
		// Fed WHOLE, one chunk: the point is the visitor's per-value cost, not the
		// resumption machinery, and a fixed chunking would measure the split as much
		// as the decode.
		f.line("  if (w === \"stream_%s\") {", low)
		f.line("    const obj = M.%s.fromJSON(JSON.parse(input.toString(\"utf8\")));", mt)
		f.line("    const wire = obj.encode(); // setup: the decode input")
		f.line("    let sink = 0;")
		f.line("    const body = () => { const _d = new M.%sDecoder(); _d.feed(wire); sink ^= %s; };", mt, g.benchSinkOn("_d.finish()", m))
		f.line("    for (let i = 0; i < BENCH_WARMUP; i++) body();")
		f.line("    for (let i = 0; i < reps; i++) body();")
		f.line("    process.stderr.write(`sink=${sink} bytes=${wire.length}\\n`);")
		f.line("    return 0;")
		f.line("  }")
	}
	f.line("  process.stderr.write(`unknown workload: ${w}\\n`);")
	f.line("  return 2;")
	f.line("}")
	f.blank()
	f.line("async function main(): Promise<number> {")
	f.line("  const mode = process.argv[2];")
	f.line("  const name = process.argv[3] ?? %q;", defaultMessage(s))
	f.line("  const chunks: Uint8Array[] = [];")
	f.line("  for await (const c of process.stdin) chunks.push(c as Uint8Array);")
	f.line("  const input = Buffer.concat(chunks);")
	f.line("  // `bench <workload> <reps>` takes a workload, not a message name.")
	f.line("  if (mode === \"bench\") {")
	f.line("    return await benchMain(name, Number(process.argv[4] ?? 1000), input);")
	f.line("  }")
	f.line("  const cls = MESSAGES[name];")
	f.line("  if (!cls) { process.stderr.write(\"unknown message\\n\"); return 2; }")
	f.line("  if (mode === \"encode\") {")
	f.line("    const obj = cls.fromJSON(JSON.parse(input.toString(\"utf8\")));")
	// encode() owns its output buffer (CORELIB_PLAN §5.1) and hands back an owned
	// copy, so there is no corelib-allocated slab to keep alive behind the write.
	f.line("    process.stdout.write(obj.encode());")
	f.line("  } else if (mode === \"decode\") {")
	f.line("    const obj = cls.decode(new Uint8Array(input));")
	f.line("    process.stdout.write(JSON.stringify(obj.toJSON()) + \"\\n\");")
	// The same bytes through the incremental decoder, fed ONE BYTE per feed. A
	// whole-buffer feed would exercise the Decoder's signature without ever making
	// it suspend and resume, which is the half that can actually be wrong;
	// drip-feeding turns every byte offset -- inside a skipped payload included --
	// into a boundary the parse state has to survive. The JSON printed here is
	// compared against `decode`'s by the conformance runner.
	f.line("  } else if (mode === \"streamdecode\") {")
	f.line("    const dec = new DECODERS[name]();")
	// An Incomplete status mid-stream is the normal verdict for a chunk that ended
	// mid-field: it says the BYTES ended there, not that the message is bad. Only
	// finish() decides on the message as a whole, and it throws when the stream
	// ended half-read.
	f.line("    const one = new Uint8Array(1);")
	f.line("    let obj;")
	f.line("    try {")
	// The stream publishes its outcome once, as feed's return value, and has no
	// accessor to ask again -- so the Decoder's `status` is the wrapper
	// remembering it. Nothing else in the suite reads that memory, and a stale one
	// would still let every vector pass, so check it here: it has to agree with
	// the feed that produced it, on every byte of every vector (generator#461).
	f.line("      for (const b of input) {")
	f.line("        one[0] = b;")
	f.line("        const fed = dec.feed(one);")
	f.line("        if (dec.status !== fed) {")
	f.line("          throw new Error(`status ${dec.status} disagrees with the feed that set it (${fed})`);")
	f.line("        }")
	f.line("      }")
	f.line("      obj = dec.finish();")
	f.line("    } catch (e) {")
	// The remembered status is printed, not just the throw. A refusal is
	// terminal and leaves through this catch, so the ONLY way the latch in the
	// generated feed -- the one arm of #461 that is new logic rather than a
	// rename -- becomes observable to a suite is by naming what it recorded.
	// Without it an inverted mapping, or a latch that sets nothing at all,
	// still exits 1 and every reject vector still passes.
	// tests/conformance/typescript/run.sh greps this for the malformed and the
	// over-cap fixtures it already builds.
	f.line("      process.stderr.write(")
	f.line("        `decode error: ${String(e)} [status=${dec.status}]\\n`);")
	f.line("      return 1;")
	f.line("    }")
	f.line("    process.stdout.write(JSON.stringify(obj.toJSON()) + \"\\n\");")
	f.line("  } else if (mode === \"recode\") {")
	// Bytes in, bytes out: decode and re-encode without a JSON detour. JSON cannot
	// carry every wire distinction a message can (a NaN renders as null, and no JSON
	// number has an fp32 NaN's payload bits), so a JSON round-trip cannot show that
	// re-encoding is bit-exact. This mode can.
	f.line("    const obj = cls.decode(new Uint8Array(input));")
	f.line("    process.stdout.write(obj.encode());")
	f.line("  } else if (mode === \"status\") {")
	// Surface the §7 decode outcome (COMPLETE / INVALID / INCOMPLETE / LIMIT_EXCEEDED)
	// so a conformance harness can assert the INVALID-vs-INCOMPLETE distinction that
	// a bare non-zero exit hides — e.g. a message that is BOTH over-bound and
	// truncated must be INVALID, not INCOMPLETE (generator#216 / §5.2). The corelib
	// throws a SofabError carrying a machine-readable .code.
	f.line("    try {")
	f.line("      cls.decode(new Uint8Array(input));")
	f.line("      process.stdout.write(\"COMPLETE\\n\");")
	f.line("    } catch (e) {")
	f.line("      const code = (e as { code?: string })?.code;")
	f.line("      if (code === \"INVALID_MSG\") process.stdout.write(\"INVALID\\n\");")
	f.line("      else if (code === \"INCOMPLETE\") process.stdout.write(\"INCOMPLETE\\n\");")
	f.line("      else if (code === \"LIMIT_EXCEEDED\") process.stdout.write(\"LIMIT_EXCEEDED\\n\");")
	f.line("      else throw e;")
	f.line("    }")
	f.line("  } else { process.stderr.write(\"unknown mode\\n\"); return 2; }")
	f.line("  return 0;")
	f.line("}")
	f.blank()
	f.line("main().then((c) => process.exit(c));")
	return f.bytes()
}

// benchSinkExpr is the fold of one decoded field into the bench sink, keeping the
// decode from being elided. `Number()` is right for a narrow int and for the
// bigint/number int64 modes, but a Long-backed 64-bit scalar is an OBJECT —
// Number(Long) is NaN, which folds to a sink of 0 and quietly stops proving
// anything. Its low half is the cheap read there, and just as unelidable.
func (g *gen) benchSinkExpr(mt string, m *ir.Message) string {
	return g.benchSinkOn(fmt.Sprintf("M.%s.decode(wire)", mt), m)
}

// benchSinkOn is that fold over an arbitrary decoded-object expression, so the
// pull and the chunked workloads share one definition of "cheap unelidable read".
func (g *gen) benchSinkOn(obj string, m *ir.Message) string {
	fld := benchSinkField(m)
	acc := obj + "." + fld
	for _, x := range m.Fields {
		if x.Name == fld && g.longScalars() && isBig(x.Kind) {
			return acc + ".low"
		}
	}
	return "Number(" + acc + ")"
}

// benchSinkField names one cheap integer scalar of m, folded in the bench loop so
// the decode cannot be elided. Prefers a narrow int: with `int64: bigint` a u64/i64
// field would fold through BigInt and add cost that is not decode cost.
func benchSinkField(m *ir.Message) string {
	for _, f := range m.Fields {
		switch f.Kind {
		case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindI8, ir.KindI16, ir.KindI32:
			return f.Name
		}
	}
	for _, f := range m.Fields {
		switch f.Kind {
		case ir.KindU64, ir.KindI64:
			return f.Name
		}
	}
	return m.Fields[0].Name
}

func defaultMessage(s *ir.Schema) string {
	if len(s.Messages) > 0 {
		return s.Messages[0].Name
	}
	return ""
}

