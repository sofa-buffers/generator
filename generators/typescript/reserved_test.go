var update = flag.Bool("update", false, "rewrite tests/conformance/typescript/reserved.{yaml,json} from the reserved-name list")

// reservedNames is every name on the list a schema field can spell, sorted.
// The union's underscored members bound derived slots, not field names.
func reservedNames() []string {
	var names []string
	for _, set := range []map[string]bool{tsClassBody, tsMembers, tsObjectMembers, unionReserved} {
		for n := range set {
			if !strings.HasPrefix(n, "_") {
				names = append(names, n)
			}
		}
	}
	sort.Strings(names)
	return names
}

// reservedYAML is a schema that uses every reserved name as a field of a message,
// of a nested struct, and as an option of a union. An fp32 field gives the
// message a raw-bytes companion too.
func reservedYAML(names []string) string {
	var b strings.Builder
	b.WriteString("# Generated by TestReservedSchemaFile from generators/typescript/reserved.go;\n")
	b.WriteString("# do not edit. Regenerate: go test ./generators/typescript -run TestReservedSchemaFile -update\n")
	b.WriteString("# The collision test: every reserved name as a field must typecheck and round-trip.\n")
	var fields strings.Builder
	opts := make([]string, len(names))
	for i, n := range names {
		fmt.Fprintf(&fields, "      %s: { id: %d, type: u8 }\n", n, i)
		opts[i] = fmt.Sprintf("%s: { id: %d, type: u8 }", n, i)
	}
	k := len(names)
	fmt.Fprintf(&b, `version: 1
$defs:
  struct:
    Inner:
%smessages:
  m:
    payload:
%s      f:     { id: %d, type: fp32 }
      inner: { id: %d, type: struct, fields: { $ref: '#/$defs/struct/Inner' } }
      u:     { id: %d, type: union, oneof: { %s } }
`, fields.String(), fields.String(), k, k+1, k+2, strings.Join(opts, ", "))
	return b.String()
}

// reservedJSON is the harness input for m: every reserved field, nested one and
// the last union option at a non-default value, each under its schema name.
func reservedJSON(names []string) string {
	top := map[string]any{"f": 1.5}
	inner := map[string]any{}
	for i, n := range names {
		top[n] = i + 1
		inner[n] = i + 2
	}
	top["inner"] = inner
	top["u"] = map[string]any{names[len(names)-1]: 9}
	b, _ := json.MarshalIndent(top, "", "  ")
	return string(b) + "\n"
}

// TestReservedSchemaFile keeps the checked-in collision schema and its input in
// step with the list: the conformance suite typechecks and round-trips that file
// (tests/conformance/typescript/run.sh), so a name added to reserved.go is
// covered the moment the file is regenerated -- and this test fails until it is.
func TestReservedSchemaFile(t *testing.T) {
	names := reservedNames()
	for path, want := range map[string]string{
		"../../tests/conformance/typescript/reserved.yaml": reservedYAML(names),
		"../../tests/conformance/typescript/reserved.json": reservedJSON(names),
	} {
		if *update {
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s is out of step with the reserved-name list; regenerate with -update", path)
		}
	}
}

// TestReservedNamesAreMangled: every name on the list comes out with a trailing
// underscore as a class member -- except the members only a union has, which a
// struct member keeps -- and the JSON key keeps the schema name.
func TestReservedNamesAreMangled(t *testing.T) {
	names := reservedNames()
	out := genTSWith(t, reservedYAML(names), map[string]any{})
	for _, n := range names {
		want := n + "_"
		if unionReserved[n] {
			want = n
		}
		if !regexp.MustCompile(`(?m)^  ` + regexp.QuoteMeta(want) + `: number = 0;$`).MatchString(out) {
			t.Errorf("field %q is not the member %s", n, want)
		}
		if !strings.Contains(out, fmt.Sprintf("%q: ", n)) {
			t.Errorf("JSON key %q is gone", n)
		}
	}
}

// TestFieldNameCollision: two fields that derive one member -- a mangled name
// landing on a field that already has it, or an fp32 field's raw-bytes companion
// landing on another field -- are a generation error naming both.
func TestFieldNameCollision(t *testing.T) {
	for _, c := range []struct{ a, b string }{
		{"encode: { id: 0, type: u8 }", "encode_: { id: 1, type: u8 }"},
		{"f: { id: 0, type: fp32 }", "fFp32Raw: { id: 1, type: u8 }"},
	} {
		src := fmt.Sprintf("version: 1\nmessages:\n  m:\n    payload:\n      %s\n      %s\n", c.a, c.b)
		_, err := (&Backend{}).Generate(schema(t, src), map[string]any{})
		if err == nil || !strings.Contains(err.Error(), "both generate the member") {
			t.Errorf("%s / %s: want a collision error, got %v", c.a, c.b, err)
		}
	}
}
