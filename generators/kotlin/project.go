// benchSinkField names one cheap integer scalar of m, folded into the bench loop
// so the decode cannot be elided. It runs inside the measured loop, so it must
// stay cheap -- rendering JSON there would be counted as decode cost.
func benchSinkField(m *ir.Message) *ir.Field {
	for _, f := range m.Fields {
		switch f.Kind {
		case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64,
			ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64:
			return f
		}
	}
	return nil
}

// emitBench emits the `bench <workload> <reps>` entry point (tests/bench,
// ARCHITECTURE §15).
//
// The JVM JIT-compiles the hot path at runtime, so there is no native symbol to
// --toggle-collect on. This is the `subtract` method: tests/bench runs the same
// workload at two rep counts and subtracts the totals,
//
//	Ir/op = ( Ir(R2) - Ir(R1) ) / ( R2 - R1 )
//
// which cancels JVM startup, class loading, JIT compilation and setup exactly.
//
// That only holds if the two runs differ in NOTHING but the rep count, which
// needs both halves of the contract:
//   - here: a FIXED warmup, independent of reps, so the hot methods reach their
//     final tier BEFORE the measured loop and every measured op runs at steady
//     cost;
//   - in tests/bench/lang/kotlin.sh: -XX:-TieredCompilation (one tier, no mid-run
//     transition), -XX:+UseEpsilonGC with a fixed heap (no GC at all), and
//     -XX:hashCode=2 (identity hashes are otherwise seeded per run).
func (g *gen) emitBench(f *kfile, s *ir.Schema) {
	f.line("// Fixed warmup ops per run, independent of `reps`, so it cancels in the")
	f.line("// subtraction while leaving the measured ops at steady, fully-JITted cost.")
	f.line("private val WARMUP: Int = (System.getProperty(\"sofab.warmup\") ?: \"5000\").toInt()")
	f.line("private var benchSink: Long = 0")
	f.blank()
	for _, m := range s.Messages {
		mt := exported(m.Name)
		low := strings.ToLower(m.Name)
		sink := benchSinkField(m)
		f.line("private fun benchOp%s(enc: Boolean, obj: %s, wire: ByteArray) {", mt, mt)
		f.line("    if (enc) {")
		f.line("        benchSink = benchSink xor obj.encode().size.toLong()")
		f.line("    } else {")
		if sink != nil {
			f.line("        benchSink = benchSink xor %s.decode(wire).%s.toLong()", mt, ktIdent(sink.Name))
		} else {
			f.line("        benchSink = benchSink xor %s.decode(wire).hashCode().toLong()", mt)
		}
		f.line("    }")
		f.line("}")
		f.blank()
		_ = low
	}
	f.line("private fun benchMain(w: String, reps: Int, input: ByteArray): Int {")
	for _, m := range s.Messages {
		mt := exported(m.Name)
		low := strings.ToLower(m.Name)
		f.line("    if (w == \"encode_%s\" || w == \"decode_%s\") {", low, low)
		f.line("        val obj = %s()", mt)
		f.line("        Json.from(JsonValue.parse(input.decodeToString()).obj(), obj)")
		f.line("        val wire = obj.encode()   // setup: the decode input")
		f.line("        val enc = w == \"encode_%s\"", low)
		f.line("        for (i in 0 until WARMUP) benchOp%s(enc, obj, wire)", mt)
		f.line("        for (i in 0 until reps) benchOp%s(enc, obj, wire)", mt)
		f.line("        System.err.println(\"sink=\" + benchSink + \" bytes=\" + wire.size)")
		f.line("        val hx = StringBuilder()")
		f.line("        for (b in wire) hx.append(\"0123456789abcdef\"[(b.toInt() shr 4) and 0xF]).append(\"0123456789abcdef\"[b.toInt() and 0xF])")
		f.line("        System.err.println(\"wire_hex=\" + hx)")
		f.line("        return 0")
		f.line("    }")
	}
	f.line("    System.err.println(\"unknown workload: \" + w)")
	f.line("    return 2")
	f.line("}")
	f.blank()
}

func (g *gen) mainHarness(s *ir.Schema) []byte {
	f := &kfile{}
	g.header(f)
	g.emitBench(f, s)
	f.line("public fun main(args: Array<String>) {")
	f.line("    val mode = if (args.isNotEmpty()) args[0] else \"\"")
	f.line("    val name = if (args.size > 1) args[1] else %s", ktStringLit(defaultMessage(s)))
	f.line("    val input = System.`in`.readBytes()")
	f.line("    // `bench <workload> <reps>` takes a workload, not a message name.")
	f.line("    if (mode == \"bench\") {")
	f.line("        kotlin.system.exitProcess(benchMain(name, if (args.size > 2) args[2].toInt() else 1000, input))")
	f.line("    }")
	f.line("    when (name) {")
	for _, m := range s.Messages {
		mt := exported(m.Name)
		f.line("        %s -> {", ktStringLit(m.Name))
		f.line("            when (mode) {")
		f.line("                \"encode\" -> {")
		f.line("                    val obj = %s()", mt)
		f.line("                    Json.from(JsonValue.parse(input.decodeToString()).obj(), obj)")
		f.line("                    System.out.write(obj.encode())")
		f.line("                }")
		f.line("                \"decode\" -> {")
		f.line("                    val obj = %s.decode(input)", mt)
		f.line("                    val sb = StringBuilder(); Json.to(obj, sb)")
		f.line("                    System.out.write(sb.toString().encodeToByteArray()); System.out.write('\\n'.code)")
		f.line("                }")
		f.line("                \"stream\" -> {")
		f.line("                    // Both streaming halves, against the one-shot pair as the oracle.")
		f.line("                    //")
		f.line("                    // OUT: a ONE-BYTE window with a flush sink. The corelib splits every")
		f.line("                    // atomic unit, so any buffer at or above MIN_OUTPUT_BUFFER must produce")
		f.line("                    // output byte-identical to the one-shot path -- which is the property")
		f.line("                    // that makes a message larger than RAM encodable at all, and the one a")
		f.line("                    // generated serialize can break by holding something back itself.")
		f.line("                    //")
		f.line("                    // IN: those same bytes fed ONE AT A TIME. Decoder state has to survive")
		f.line("                    // a boundary at every single byte offset, so the JSON printed here is")
		f.line("                    // compared against the `decode` mode's by the conformance runner.")
		f.line("                    val obj = %s()", mt)
		f.line("                    Json.from(JsonValue.parse(input.decodeToString()).obj(), obj)")
		f.line("                    val oneShot = obj.encode()")
		f.line("                    val acc = Sbuf.Acc()")
		f.line("                    val os = OStream(ByteArray(1), 0, FlushSink { data, off, len -> acc.write(data, off, len) })")
		f.line("                    obj.encodeTo(os)")
		f.line("                    val streamed = acc.toByteArray()")
		f.line("                    if (!oneShot.contentEquals(streamed)) {")
		f.line("                        System.err.println(\"stream: a 1-byte output buffer changed the bytes\")")
		f.line("                        kotlin.system.exitProcess(2)")
		f.line("                    }")
		f.line("                    val dec = %s.decoder()", mt)
		f.line("                    for (b in streamed) dec.feed(byteArrayOf(b))")
		f.line("                    val back = dec.finish()")
		f.line("                    val sb = StringBuilder(); Json.to(back, sb)")
		f.line("                    System.out.write(sb.toString().encodeToByteArray()); System.out.write('\\n'.code)")
		f.line("                }")
		f.line("                \"trydecode\" -> {")
		f.line("                    val obj = %s()", mt)
		f.line("                    val st = %s.tryDecode(input, obj)", mt)
		f.line("                    System.out.write((st.name + \"\\n\").encodeToByteArray())")
		f.line("                    val sb = StringBuilder(); Json.to(obj, sb)")
		f.line("                    System.out.write(sb.toString().encodeToByteArray()); System.out.write('\\n'.code)")
		f.line("                }")
		f.line("                else -> { System.err.println(\"unknown mode\"); kotlin.system.exitProcess(2) }")
		f.line("            }")
		f.line("        }")
	}
	f.line("        else -> { System.err.println(\"unknown message\"); kotlin.system.exitProcess(2) }")
	f.line("    }")
	f.line("    System.out.flush()")
	f.line("}")
	return f.bytes()
}

