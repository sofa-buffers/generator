// projectFiles scaffolds a Gradle project with a canonical-JSON encode/decode
// harness over corelib-kotlin-mp.
//
// The generated MESSAGE sources are plain `commonMain` Kotlin -- stdlib plus
// `sofab`, no JVM API -- so they drop into a multiplatform source set unchanged.
// The project around them is a JVM one, because a harness needs a `main`, a
// process exit code and a stdin: the scaffolding is where the platform gets
// picked, never the code that encodes.
//
// JSON is parsed by hand rather than with a library so a u64 above 2^53 stays
// exact and the project has no dependency the corelib does not.
func (g *gen) projectFiles(s *ir.Schema, cfg map[string]any, dir string) []generator.File {
	return []generator.File{
		{Path: "settings.gradle.kts", Content: []byte(g.settingsGradle())},
		{Path: "build.gradle.kts", Content: []byte(g.buildGradle())},
		{Path: dir + "Json.kt", Content: g.jsonHelper(s)},
		{Path: dir + "Main.kt", Content: g.mainHarness(s)},
		{Path: "README.md", Content: []byte("# Generated SofaBuffers Kotlin project\n\n" +
			"`@generated by sofabgen`. Build and run the harness:\n\n" +
			"```sh\n./gradlew installDist\nbuild/install/harness/bin/harness encode <message> < in.json\n```\n\n" +
			"The sources under `src/main/kotlin` are plain `commonMain` Kotlin (stdlib +\n" +
			"`sofab` only), so they can be moved into a Kotlin Multiplatform source set\n" +
			"as they are; only this project scaffolding is JVM-specific.\n")},
	}
}

