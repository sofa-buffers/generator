// TestKotlinSupportIsTheCorelibs: no generated package carries a support file
// of its own. Placing an element, growing an array, reassembling a payload and
// validating its UTF-8 all have the same shape for every schema, with the schema
// dependence carried by the arguments, so ARCHITECTURE §8 puts them in
// corelib-kotlin-mp; generated code names them and emits nothing
// (generator#345).
func TestKotlinSupportIsTheCorelibs(t *testing.T) {
	gen := func(t *testing.T, payload string) map[string]string {
		t.Helper()
		return genFromYAML(t, "version: 1\nmessages:\n  M:\n    payload:\n"+payload,
			map[string]any{"package": "m"})
	}

	t.Run("no support file is emitted at all", func(t *testing.T) {
		for _, payload := range []string{
			"      a: { id: 0, type: u32 }\n",
			"      a: { id: 0, type: array, items: { type: u32 } }\n",
			"      a: { id: 0, type: array, items: { type: array, count: 2, items: { type: i32, count: 3 } } }\n",
			"      a: { id: 0, type: string, maxlen: 8 }\n",
		} {
			files := gen(t, payload)
			if _, ok := files["src/main/kotlin/m/Sbuf.kt"]; ok {
				t.Errorf("a support file was emitted for %q", payload)
			}
			for path, body := range files {
				if strings.Contains(body, "Sbuf") {
					t.Errorf("%s still names the retired support object", path)
				}
			}
		}
	})

	t.Run("an unbounded array is sized at the checked count, not grown", func(t *testing.T) {
		m := gen(t, "      a: { id: 0, type: array, items: { type: u32 } }\n")["src/main/kotlin/m/M.kt"]
		if !strings.Contains(m, "Seq.EMPTY_UINTS") {
			t.Error("M.kt missing the corelib's empty-array constant")
		}
		// Growth is the corelib's Seq.ensureCap / Seq.ARRAY_INIT_CAP, and it is no
		// longer reachable from generated code: the count is bounded before the
		// allocation, so the allocation is exact (§9.5, shape A).
		for _, gone := range []string{"Seq.ensureCap", "Seq.ARRAY_INIT_CAP", "acap"} {
			if strings.Contains(m, gone) {
				t.Errorf("M.kt must not still grow through %q", gone)
			}
		}
	})

	t.Run("a matrix row is reserved through Seq.reserveRow", func(t *testing.T) {
		m := gen(t, "      a: { id: 0, type: array, items: { type: array, count: 2, items: { type: i32, count: 3 } } }\n")["src/main/kotlin/m/M.kt"]
		if !strings.Contains(m, "Seq.reserveRowInts(m.a, id,") {
			t.Error("a native row must be reserved through the corelib's per-element member")
		}
	})

	t.Run("a boolean array is materialised by Seq.boolsToBytes", func(t *testing.T) {
		m := gen(t, "      a: { id: 0, type: array, items: { type: boolean } }\n")["src/main/kotlin/m/M.kt"]
		if !strings.Contains(m, "Seq.boolsToBytes(this.a)") {
			t.Error("the one native kind with no OStream overload goes through the corelib")
		}
	})

	t.Run("a payload is reassembled and validated by PayloadAcc", func(t *testing.T) {
		m := gen(t, "      s: { id: 0, type: string, maxlen: 8 }\n      b: { id: 1, type: blob, maxlen: 8 }\n")["src/main/kotlin/m/M.kt"]
		for _, want := range []string{
			"private val acc = PayloadAcc()",
			"val s = acc.string(total, offset, data, chunkOffset, chunkLength, maxlen, MAX_DYN_STRING_LEN) ?: return",
			"val b = acc.blob(total, offset, data, chunkOffset, chunkLength, maxlen, MAX_DYN_BLOB_LEN) ?: return",
		} {
			if !strings.Contains(m, want) {
				t.Errorf("M.kt missing %q", want)
			}
		}
		// The chunk buffer and the UTF-8 check are the corelib's, so neither the
		// accumulator's internals nor a validator of our own is named here.
		for _, unwanted := range []string{"acc.buf", "acc.write(", "Utf8.valid", "private fun utf8("} {
			if strings.Contains(m, unwanted) {
				t.Errorf("M.kt still carries %q", unwanted)
			}
		}
	})
}

// TestKotlinAShapeCheckThenAllocate: the Kotlin half of ARCHITECTURE §9.5's
// shape A (generator#386) -- an array whose size arrives before its payload is
// bounded at the count header and then allocated at exactly that count, once.
// See the Java twin for why the check and the allocation are asserted together.
func TestKotlinAShapeCheckThenAllocate(t *testing.T) {
	const src = `
version: 1
messages:
  M:
    payload:
      dyn: { id: 0, type: array, items: { type: u32 } }
      bnd: { id: 1, type: array, items: { type: u32, count: 8 } }
      fps: { id: 2, type: array, items: { type: fp32 } }
      mat: { id: 3, type: array, items: { type: array, count: 3, items: { type: u32, count: 4 } } }
`
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]

	for _, want := range []string{
		`if (count > MAX_DYN_ARRAY_COUNT)`,
		`m.dyn = UIntArray(count); abulk = m.dyn.asIntArray()`,
		`if (count > 8) throw SofabException(SofabError.INVALID_MSG, "bnd: array count above schema capacity 8")`,
		`m.bnd = UIntArray(count); abulk = m.bnd.asIntArray()`,
		// fp arrays are sized the same way but carry no bulk offer.
		`m.fps = FloatArray(count)`,
		// The row's own element COUNT is still bounded here -- the count header
		// arrives in this callback and the reservation is sized from it, so
		// there is no earlier corelib call to hang it on. The row's INDEX rides
		// the reservation instead, with both of its numbers as arguments.
		`if (count > 4) throw SofabException(SofabError.INVALID_MSG, "mat element: array count above schema capacity 4")`,
		`Seq.reserveRowUInts(m.mat, id, count, 3, MAX_DYN_ARRAY_COUNT)`,
		// Plain indexed stores; no growth, no write-back.
		`m.dyn[ai] = value.toUInt(); ai++`,
		`_arowUInt[ai] = value.toUInt(); ai++`,
	} {
		if !strings.Contains(m, want) {
			t.Errorf("M.kt missing %q:\n%s", want, m)
		}
	}
	for _, gone := range []string{"Seq.ensureCap", "Seq.ARRAY_INIT_CAP", "minOf(count", "acap"} {
		if strings.Contains(m, gone) {
			t.Errorf("M.kt must not still grow into an array (%q):\n%s", gone, m)
		}
	}
}

// TestKotlinWrapperIndexCap: a DYNAMIC wrapper array's element index is bounded
// by the receiver cap, checked before the container grows (ARCHITECTURE §9.5,
// generator#387). See the Java twin for why the INDEX and not the element count:
// gap filling makes the array's length its highest present id, so two delivered
// elements can be an arbitrarily large container.
func TestKotlinWrapperIndexCap(t *testing.T) {
	const src = `
version: 1
messages:
  M:
    payload:
      dstrs: { id: 0, type: array, items: { type: string } }
      dblbs: { id: 1, type: array, items: { type: blob } }
      dobjs: { id: 2, type: array, items: { type: struct, fields: { x: { id: 0, type: u32 } } } }
      dmat:  { id: 3, type: array, items: { type: array, items: { type: u32 } } }
      bstrs: { id: 4, type: array, items: { type: string, count: 4 } }
`
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]

	for _, want := range []string{
		`if (id >= MAX_DYN_ARRAY_COUNT) throw SofabException(SofabError.LIMIT_EXCEEDED, "dstrs element: array index above configured limit 16384"); while (m.dstrs.size <= id)`,
		`"dblbs element: array index above configured limit 16384"); while (m.dblbs.size <= id)`,
		`"dobjs element: array index above configured limit 16384"); while (m.dobjs.size <= id)`,
		// A native matrix ROW takes the index cap too: its id is the outer array's
		// length. It rides the reservation, which is the call that grows the outer
		// list, so the cap arrives as an argument and no guard precedes it. Its own
		// element count is capped separately, beside it (#386).
		`Seq.reserveRowUInts(m.dmat, id, count, -1, MAX_DYN_ARRAY_COUNT)`,
	} {
		if !strings.Contains(m, want) {
			t.Errorf("M.kt missing wrapper index cap %q:\n%s", want, m)
		}
	}
	if strings.Contains(m, `"dmat element: array index above configured limit`) {
		t.Errorf("a row index is bounded once, inside the reservation:\n%s", m)
	}
	// The cap governs only what the schema left unbounded (§9.5): a count:N array
	// keeps its own bound and its own category.
	if !strings.Contains(m, `if (id >= 4) throw SofabException(SofabError.INVALID_MSG, "bstrs element: array index above schema capacity 4")`) {
		t.Errorf("a count:N wrapper array must keep its INVALID schema bound:\n%s", m)
	}
	if strings.Contains(m, `"bstrs element: array index above configured limit`) {
		t.Errorf("a schema-bounded array must not also carry the receiver cap:\n%s", m)
	}
}

// TestKotlinFixlenBeginLatchesTheReceiverCapAtTheLengthWord: the RECEIVER CAP is
// latched at that same length word, and with its own category (CORELIB_PLAN
// §6.2.1 "Enforcement point", ARCHITECTURE §9.5).
//
// The schema-maxlen half above was already latched there. The cap half was not:
// it travelled only as PayloadAcc.string/.blob's `rmaxlen` argument, and those
// fire once a payload byte exists. So `0a a2 06` -- a length word declaring 100
// bytes on a field capped at 8, then end of input -- reached no callback and
// answered INCOMPLETE, which §6.3 makes the wrong category (the refusal is
// terminal) and which invites a streaming caller to feed more of a stream this
// receiver has already refused.
//
// The comparison is still the corelib's -- PayloadAcc.checkStringLength is what
// PayloadAcc.string runs at the top of itself -- so this is one implementation of
// the rule applied at two points, not a second copy in the generated layer.
func TestKotlinFixlenBeginLatchesTheReceiverCapAtTheLengthWord(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      ds: { id: 0, type: string }\n" +
		"      bs: { id: 1, type: string, maxlen: 32 }\n" +
		"      db: { id: 2, type: blob }\n" +
		"      sa: { id: 3, type: array, items: { type: string } }\n"
	m := genFromYAML(t, src, map[string]any{
		"max_dyn_string_len": 8, "max_dyn_blob_len": 8, "max_dyn_array_count": 4,
	})["src/main/kotlin/message/M.kt"]
	fx := m[strings.Index(m, "override fun fixlenBegin("):strings.Index(m, "override fun string(")]
	if fx == "" {
		t.Fatal("M.kt must implement fixlenBegin")
	}
	for _, want := range []string{
		// A schema-unbounded string and blob: the corelib's own check, at the
		// header. -1 is the schema FACT that this field declares no maxlen, the
		// same number the payload call passes -- not "unlimited".
		"0 -> PayloadAcc.checkStringLength(total, -1, MAX_DYN_STRING_LEN)",
		"2 -> PayloadAcc.checkBlobLength(total, -1, MAX_DYN_BLOB_LEN)",
		// A schema-bounded one keeps INVALID_MSG and its own number: §6.2.1 forbids
		// the cap on a field the schema bounds, even a maxlen far above the cap.
		`1 -> if (total > 32) throw SofabException(SofabError.INVALID_MSG, "bs: string length above schema maxlen 32")`,
		// ...all of it behind the §7.3 declared-subtype gate.
		"if (subtype == FixlenType.STRING) {",
		"if (subtype == FixlenType.BLOB) {",
	} {
		if !strings.Contains(fx, want) {
			t.Errorf("fixlenBegin missing %q\ngot:\n%s", want, fx)
		}
	}
	// The cap is never re-implemented here: a bare comparison against the constant
	// would be the second implementation §6.2.1 forbids.
	if strings.Contains(fx, "total > MAX_DYN_STRING_LEN") || strings.Contains(fx, "total > MAX_DYN_BLOB_LEN") {
		t.Error("the cap comparison belongs to the corelib call, not to a guard emitted beside it (§6.2.1)")
	}
	// A message whose every string the schema bounds meets no cap anywhere: the
	// exclusivity rule leaves nothing for the cap to govern.
	bounded := genFromYAML(t, "version: 1\nmessages:\n  B:\n    payload:\n"+
		"      s: { id: 0, type: string, maxlen: 8 }\n"+
		"      b: { id: 1, type: blob, maxlen: 8 }\n",
		map[string]any{"max_dyn_string_len": 8, "max_dyn_blob_len": 8})["src/main/kotlin/message/B.kt"]
	if strings.Contains(bounded, "checkStringLength") || strings.Contains(bounded, "checkBlobLength") {
		t.Error("a schema-bounded field must not meet the receiver cap (§6.2.1)")
	}
}
