// TestKotlinDeclaredWidthIsAValidityBound: a value outside the declared integer
// width is malformed input -- never masked to the width, never kept -- at every
// store the schema declares: message fields, nested members and array elements.
// The 64-bit kinds span the delivery accumulator itself, so no reachable value
// can breach them and no guard is emitted.
func TestKotlinDeclaredWidthIsAValidityBound(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      a: { id: 0, type: u8 }\n" +
		"      b: { id: 1, type: i16 }\n" +
		"      c: { id: 2, type: u64 }\n" +
		"      d: { id: 3, type: array, items: { type: u32, count: 2 } }\n" +
		"      e: { id: 4, type: struct, fields: { n: { id: 0, type: u16 } } }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	for _, want := range []string{
		`if (value < 0L || value > 255L) throw SofabException(SofabError.INVALID_MSG, "a: value outside declared width u8")`,
		`if (value < -32768L || value > 32767L) throw SofabException(SofabError.INVALID_MSG, "b: value outside declared width i16")`,
		`if (value < 0L || value > 4294967295L) throw SofabException(SofabError.INVALID_MSG, "d element: value outside declared width u32")`,
		`if (value < 0L || value > 65535L) throw SofabException(SofabError.INVALID_MSG, "n: value outside declared width u16")`,
	} {
		if !strings.Contains(m, want) {
			t.Errorf("M.kt missing width guard %q", want)
		}
	}
	if strings.Contains(m, `"c: value outside declared width`) {
		t.Error("a u64 destination spans the delivery accumulator: no guard may be emitted")
	}
	// The array guard must sit INSIDE the armed-fill arm, never in front of it:
	// an over-width scalar arriving at an array id with no arrayBegin ahead of it
	// is a skip, and hoisting the guard would turn that skip into a false INVALID.
	fill := strings.Index(m, "if (afill != 0) {")
	guard := strings.Index(m, `"d element: value outside declared width u32"`)
	if fill < 0 || guard < 0 || guard < fill {
		t.Error("the element width guard must live inside the armed-fill arm")
	}
}

// TestKotlinCountIsCapacityNotLength: `count: N` is a capacity. It never reaches
// the wire, so a declared default shorter than N stays that length, a count:N
// array with no default is EMPTY, and the wire count M is the array's length --
// the M elements that arrived are the whole value, with nothing materialised at
// [M, N).
func TestKotlinCountIsCapacityNotLength(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      a: { id: 0, type: array, items: { type: u32, count: 5 }, default: [1, 2] }\n" +
		"      b: { id: 1, type: array, items: { type: u32, count: 5 } }\n" +
		"      c: { id: 2, type: array, items: { type: string, count: 3, maxlen: 8 } }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	if !strings.Contains(m, "public var a: UIntArray = uintArrayOf(1u, 2u)") {
		t.Error("a declared default must stand exactly as written, never tail-padded to count")
	}
	if !strings.Contains(m, "public var b: UIntArray = Sbuf.EMPTY_UINT") {
		t.Error("a count:N array with no declared default is the EMPTY array")
	}
	if !strings.Contains(m, "public var c: MutableList<String> = mutableListOf()") {
		t.Error("a count:N wrapper array starts empty")
	}
	// The whole-field omit compare is against the declared default as written.
	if !strings.Contains(m, "if (!this.a.contentEquals(_arrdef_a)) {") {
		t.Error("the omit compare must read the hoisted default")
	}
	if !strings.Contains(m, "if (this.b.isNotEmpty()) {") {
		t.Error("with no declared default the omit compare degenerates to a length test")
	}
	// Decode sizes from the wire count, capped -- never from N, and never from
	// the untrusted count for an unbounded array.
	if !strings.Contains(m, "m.a = UIntArray(count)") {
		t.Error("a bounded array's destination is sized to the wire count the guard just bounded")
	}
}

// TestKotlinWrapperElementSparsity: inside a wrapper array the child id IS the
// index and the array carries no length field, so the decoded length is *highest
// present id + 1*. Both halves of the rule follow: an interior element equal to
// its element default is omitted (leaving an id gap the decoder restores), and
// the LAST element is always written, whatever its value.
func TestKotlinWrapperElementSparsity(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      s: { id: 0, type: array, items: { type: string, count: 4, maxlen: 8 } }\n" +
		"      b: { id: 1, type: array, items: { type: blob,   count: 4, maxlen: 8 } }\n" +
		"      p: { id: 2, type: array, items: { type: struct, count: 4, fields: { x: { id: 0, type: i32 } } } }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	for _, want := range []string{
		"if (_e0.isNotEmpty() || _i0 == _t0.size - 1) os.writeString(_i0, _e0)",
		"if (_e0.isNotEmpty() || _i0 == _t1.size - 1) os.writeBlob(_i0, _e0)",
		// A sequence-form element obeys the same rule through the CLOSER: dropped
		// in the interior, kept at the last index where its presence is what fixes
		// the length.
		"if (_i0 == _t2.size - 1) os.writeSequenceEndKeep() else os.writeSequenceEnd()",
	} {
		if !strings.Contains(m, want) {
			t.Errorf("M.kt missing element sparsity %q", want)
		}
	}
	// The wrapper FIELD itself takes the dropping closer: an empty array is
	// omitted rather than framed empty.
	if strings.Count(m, "os.writeSequenceEnd()\n") < 3 {
		t.Error("each wrapper FIELD must close with the dropping end")
	}
}

