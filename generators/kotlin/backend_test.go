// TestKotlinNarrowestCorrectType: every integer maps to its exact declared width,
// unsigned included -- a `u8` is a `UByte`, not a widened `Long` the caller has to
// mask, and a `u8[]` is a `UByteArray`. (The C# position; Java widens everything to
// `long` because it has no unsigned type, which is not a constraint here.)
//
// enum and bitfield are the deliberate exceptions, pinned at the width that
// cannot lose a legal value rather than the narrowest that fits the declared
// members: an enum is bounded by the signed 32-bit range, and a bitfield word is
// an unsigned varint over positions 0..63.
func TestKotlinNarrowestCorrectType(t *testing.T) {
	m := exampleFile(t)
	for _, want := range []string{
		"public var someu8: UByte = 7u.toUByte()",
		"public var someu16: UShort = 1000u.toUShort()",
		"public var someu32: UInt = 100000u",
		"public var someu64: ULong = 18446744073709551615uL",
		"public var somei8: Byte = (10).toByte()",
		"public var somei16: Short = (-12345).toShort()",
		"public var somei32: Int = -2000000",
		"public var somei64: Long = Long.MIN_VALUE", // no Kotlin literal spells this
		"public var somefp32: Float = 0.0f",
		"public var somefp64: Double = 3.141592653589793",
		"public var somebool: Boolean = true",
		"public var somestring: String = \"\"",
		"public var someblob: ByteArray = byteArrayOf(72, 101, 108, 108, 111)",
		"public var someenum: Int = 2",
		"public var somebitfield: ULong = 2uL",
		"public var someuintarray: UIntArray = uintArrayOf(0u, 1u, 1000u, 4294967295u)",
		"public var someintarray: IntArray = intArrayOf(10, 20, 300, 4000, 50000)",
		"public var somefloatarray: FloatArray = floatArrayOf(0.0f, -1.5f, 3.25f)",
		"public var someboolarray: BooleanArray = booleanArrayOf(true, true, false)",
		"public var somestringarray: MutableList<String> = mutableListOf()",
	} {
		if !strings.Contains(m, want) {
			t.Errorf("Myfirstmessage.kt missing %q", want)
		}
	}
}

// TestKotlinUnsignedArraysGoToTheWireUnwidened: what makes the exact width free
// rather than merely correct. Kotlin's unsigned arrays are inline classes over
// their signed peers, so `asIntArray()` hands the corelib the very same backing
// array -- no copy, no per-element widening -- and the bulk decode offer hands
// that same view back as the destination, so neither direction pays for it.
func TestKotlinUnsignedArraysGoToTheWireUnwidened(t *testing.T) {
	m := exampleFile(t)
	if !strings.Contains(m, "os.writeArrayUnsigned(15, this.someuintarray.asIntArray())") {
		t.Error("a UIntArray must reach writeArrayUnsigned through asIntArray(), not a widened copy")
	}
	if !strings.Contains(m, "m.someuintarray = UIntArray(count); abulk = m.someuintarray.asIntArray()") {
		t.Error("the bulk destination must be the field's own backing array")
	}
	// A boolean array is the one native kind with no OStream overload, so it is
	// the one that has to be materialised for the write.
	if !strings.Contains(m, "os.writeArrayUnsigned(27, Sbuf.boolBytes(this.someboolarray))") {
		t.Error("a BooleanArray must be materialised as 0/1 bytes for the write")
	}
}

// TestKotlinKeywordFieldsAreEscaped: Kotlin has a real escape (backticks), so a
// field whose name is a hard keyword keeps the schema's spelling. A name that
// would collide with a GENERATED member is a different problem -- an escape
// cannot help against another declaration -- so it is mangled instead.
func TestKotlinKeywordFieldsAreEscaped(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      object: { id: 0, type: u32 }\n" +
		"      class:  { id: 1, type: u32 }\n" +
		"      where:  { id: 2, type: u32 }\n" +
		"      encode: { id: 3, type: u32 }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	for _, want := range []string{
		"public var `object`: UInt = 0u",
		"public var `class`: UInt = 0u",
		"public var where: UInt = 0u", // a SOFT keyword is already a legal identifier
		"public var encode_: UInt = 0u",
	} {
		if !strings.Contains(m, want) {
			t.Errorf("M.kt missing %q", want)
		}
	}
	if !strings.Contains(m, "os.writeUnsigned(0, this.`object`.toLong())") {
		t.Error("the escaped identifier must be used at every use site, not just the declaration")
	}
}

// TestKotlinEnumAndBitfieldConstants: a target that lowers enum/bitfield fields
// to a bare integer has no symbol to hang the schema's per-constant descriptions
// on. Kotlin gets both -- the FIELD stays an integer, so an unknown wire value
// survives a decode, and the declared members are named constants beside it.
func TestKotlinEnumAndBitfieldConstants(t *testing.T) {
	const src = `
version: 1
$defs:
  enum:
    Mode:
      Off: { value: 0, description: "Powered down." }
      On:  { value: 1, description: "Running." }
  bitfield:
    Flags:
      ready: { pos: 0, default: true, description: "Initialized." }
      busy:  { pos: 3, description: "Work in flight." }
messages:
  Telemetry:
    payload:
      mode:   { id: 0, type: enum, enum: { $ref: "#/$defs/enum/Mode" } }
      status: { id: 1, type: bitfield, bits: { $ref: "#/$defs/bitfield/Flags" } }
`
	out := genFromYAML(t, src, map[string]any{})
	mode := out["src/main/kotlin/message/EnumMode.kt"]
	flags := out["src/main/kotlin/message/BitfieldFlags.kt"]
	for _, want := range []string{
		"public object EnumMode {",
		"/** Powered down. */",
		"public const val Off: Int = 0",
		"/** Running. */",
		"public const val On: Int = 1",
	} {
		if !strings.Contains(mode, want) {
			t.Errorf("EnumMode.kt missing %q", want)
		}
	}
	for _, want := range []string{
		"public object BitfieldFlags {",
		"/** Initialized. (default: true) */",
		"public const val ready: ULong = 1uL",
		"/** Work in flight. */",
		"public const val busy: ULong = 8uL",
	} {
		if !strings.Contains(flags, want) {
			t.Errorf("BitfieldFlags.kt missing %q", want)
		}
	}
	// The field itself stays an integer, and the bitfield default is seeded from
	// the flags' `default:`.
	msg := out["src/main/kotlin/message/Telemetry.kt"]
	if !strings.Contains(msg, "public var mode: Int = 0") {
		t.Error("an enum field must lower to Int, not to a closed enum class")
	}
	if !strings.Contains(msg, "public var status: ULong = 1uL") {
		t.Error("a bitfield field must lower to ULong seeded from the flag defaults")
	}
}

