// TestKotlinFixlenBeginLatchesBoundsAtTheLengthWord: every bound a fixlen
// header already decides is latched at that word rather than once payload bytes
// arrive -- otherwise a message truncated right after the word produces no event
// at all and decays to INCOMPLETE, while the same bytes read whole are INVALID.
//
// Each guard sits inside the DECLARED-subtype test: the hook fires for whatever
// subtype arrived, and a contradicting one is a skipped field, not this field's
// length.
func TestKotlinFixlenBeginLatchesBoundsAtTheLengthWord(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      s:  { id: 0, type: string, maxlen: 8 }\n" +
		"      b:  { id: 1, type: blob,   maxlen: 4 }\n" +
		"      es: { id: 2, type: array, items: { type: string, count: 3, maxlen: 6 } }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	if !strings.Contains(m, "override fun fixlenBegin(id: Int, subtype: FixlenType, total: Int) {") {
		t.Fatal("M.kt must implement fixlenBegin")
	}
	for _, want := range []string{
		"if (subtype == FixlenType.STRING) {",
		"if (subtype == FixlenType.BLOB) {",
		`0 -> if (total > 8) throw SofabException(SofabError.INVALID_MSG, "s: string length above schema maxlen 8")`,
		`1 -> if (total > 4) throw SofabException(SofabError.INVALID_MSG, "b: blob length above schema maxlen 4")`,
		// Over-index FIRST: an element that is not this array's element at all
		// must not have its length measured against the element bound.
		`{ if (id >= 3) throw SofabException(SofabError.INVALID_MSG, "es element: array index above schema capacity 3"); if (total > 6) throw SofabException(SofabError.INVALID_MSG, "es element: string length above schema maxlen 6") }`,
	} {
		if !strings.Contains(m, want) {
			t.Errorf("fixlenBegin missing %q", want)
		}
	}
	// A schema with no bounded fixlen field at all has nothing to latch, so the
	// hook is not emitted.
	plain := genFromYAML(t, "version: 1\nmessages:\n  P:\n    payload:\n      a: { id: 0, type: u32 }\n",
		map[string]any{})["src/main/kotlin/message/P.kt"]
	if strings.Contains(plain, "fixlenBegin") {
		t.Error("a bound-free message must not implement fixlenBegin")
	}
}

// TestKotlinArrayAtScalarIdSkipped: an integer or fp array delivered at an id
// whose declared type is a SCALAR is a wire-type contradiction. The corelib
// streams array elements through the very unsigned()/signed()/fp callbacks a lone
// scalar uses, so the id dispatch alone cannot tell them apart: arrayBegin arms a
// discard counter with the announced count and the element callbacks drop exactly
// that many.
func TestKotlinArrayAtScalarIdSkipped(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n" +
		"      u:  { id: 0, type: u8 }\n" +
		"      i:  { id: 1, type: i8 }\n" +
		"      f:  { id: 2, type: fp32 }\n" +
		"      ua: { id: 3, type: array, items: { type: u8, count: 4 } }\n"
	m := genFromYAML(t, src, map[string]any{})["src/main/kotlin/message/M.kt"]
	if !strings.Contains(m, "askip = count") {
		t.Error("arrayBegin must arm the discard counter for every array header")
	}
	if strings.Count(m, "if (askip > 0) { askip--; return }") != 4 {
		t.Error("all four element callbacks (unsigned/signed/fp32/fp64) must carry the discard guard")
	}
	// The one declared array disarms it, and only under its own wire kind.
	if !strings.Contains(m, "3 -> if (kind == ArrayKind.UNSIGNED) {") {
		t.Error("a declared array arm must be keyed on the wire kind its element type maps to")
	}
	if !strings.Contains(m, "askip = 0; afill = count; atgt = 1;") {
		t.Error("a declared array must disarm the discard counter and arm the fill")
	}
}

// TestKotlinMistypedArrayNotResized: the wire-kind test comes FIRST, so a header
