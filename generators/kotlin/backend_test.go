// TestKotlinSourcesArePlatformFree: the message sources are the product, and the
// claim about them is that they are plain `commonMain` Kotlin -- the standard
// library and `sofab`, nothing else -- so one source set compiles for the JVM,
// for Node and the browser, and as a native binary.
//
// The realistic way to break that is to reach for a JVM class the way the Java
// backend legitimately does (`java.io.ByteArrayOutputStream` for the chunk
// accumulator, `new String(bytes, UTF_8)` for the strict decode, a `ThreadLocal`
// scratch buffer). Each has a common-Kotlin answer in the corelib's commonMain
// support layer (`PayloadAcc`, `Utf8.decode`, a per-call buffer), and this is the
// guard that keeps them. The conformance harness proves the sources COMPILE; this
// proves what they compile against, hermetically and for every corpus shape.
//
// Only `emit: sources` is swept: the project scaffolding is deliberately
// JVM-specific (a harness needs a `main`, an exit code and a stdin).
func TestKotlinSourcesArePlatformFree(t *testing.T) {
	defs, _ := filepath.Glob(filepath.Join("..", "..", "tests", "matrix", "corpus", "defs", "*.yaml"))
	defs = append(defs, filepath.Join("..", "..", "examples", "messages", "example.yaml"),
		filepath.Join("..", "..", "examples", "messages", "realworld", "vehicle_telemetry.yaml"))
	if len(defs) < 3 {
		t.Fatal("no corpus defs found")
	}
	// Substrings that only exist on the JVM. `java.`/`javax.` cover the platform
	// classes; `kotlin.jvm` the JVM-only annotations; the rest are the specific
	// names a port of the Java backend would reach for first.
	banned := []string{
		"java.", "javax.", "kotlin.jvm", "ThreadLocal", "System.",
		"StandardCharsets", "ByteArrayOutputStream", "@JvmStatic", "@JvmField",
	}
	for _, def := range defs {
		files := genFromFile(t, def, map[string]any{})
		for path, src := range files {
			if !strings.HasSuffix(path, ".kt") {
				continue
			}
			for _, bad := range banned {
				if strings.Contains(src, bad) {
					t.Errorf("[%s] %s references %q — the message sources must be plain commonMain Kotlin",
						filepath.Base(def), path, bad)
				}
			}
		}
	}
}

// TestKotlinProjectMode: `emit: project` adds the Gradle scaffolding and the
// canonical-JSON harness the conformance runner drives. The MESSAGE sources stay
// platform-free either way -- only the scaffolding is JVM-specific.
func TestKotlinProjectMode(t *testing.T) {
	src := "version: 1\nmessages:\n  M:\n    payload:\n      a: { id: 0, type: u64 }\n"
	out := genFromYAML(t, src, map[string]any{"emit": "project"})
	for _, p := range []string{"settings.gradle.kts", "build.gradle.kts", "README.md",
		"src/main/kotlin/message/Json.kt", "src/main/kotlin/message/Main.kt"} {
		if _, ok := out[p]; !ok {
			t.Errorf("project mode must emit %s", p)
		}
	}
	main := out["src/main/kotlin/message/Main.kt"]
	for _, mode := range []string{`"encode" ->`, `"decode" ->`, `"trydecode" ->`, `"stream" ->`, `if (mode == "bench")`} {
		if !strings.Contains(main, mode) {
			t.Errorf("the harness must expose %s", mode)
		}
	}
	// The `stream` mode is what covers the two paths `encode`/`decode` cannot: a
	// ONE-BYTE output window (the bytes must stay identical to the one-shot
	// path's) and a decoder fed one byte at a time.
	for _, want := range []string{
		"val os = OStream(ByteArray(1), 0, acc)",
		"obj.encodeTo(os)",
		"if (!oneShot.contentEquals(streamed)) {",
		"for (b in streamed) dec.feed(byteArrayOf(b))",
		"val back = dec.finish()",
	} {
		if !strings.Contains(main, want) {
			t.Errorf("the stream mode is missing %q", want)
		}
	}
	// A u64 must survive the JSON round trip exactly, which a double-based
	// parser cannot do -- so the reader keeps the literal text and parses it at
	// the field's declared width.
	if !strings.Contains(out["src/main/kotlin/message/Json.kt"], "o.a = e.uint()") {
		t.Error("a u64 must be parsed at its declared width from the literal text")
	}
	// Sources mode emits none of it.
	plain := genFromYAML(t, src, map[string]any{})
	for _, p := range []string{"settings.gradle.kts", "build.gradle.kts", "src/main/kotlin/message/Main.kt"} {
		if _, ok := plain[p]; ok {
			t.Errorf("sources mode must not emit %s", p)
		}
	}
}

