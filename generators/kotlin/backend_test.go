// genFromYAML generates from an inline definition and returns the emitted files
// keyed by path.
func genFromYAML(t *testing.T, src string, cfg map[string]any) map[string]string {
	t.Helper()
	doc, err := parser.Parse([]byte(src), "dyn.yaml")
	if err != nil {
		t.Fatal(err)
	}
	resolved, _ := doc.Resolve()
	if errs := parser.Validate(resolved); errs != nil {
		t.Fatalf("invalid: %v", errs)
	}
	s, err := model.Build(doc)
	if err != nil {
		t.Fatal(err)
	}
	if err := analysis.Analyze(s); err != nil {
		t.Fatal(err)
	}
	files, err := (&Backend{}).Generate(s, cfg)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = string(f.Content)
	}
	return out
}

// genFromFile generates from a definition ON DISK and returns the emitted files
// keyed by path. It goes through parser.Load rather than parser.Parse because a
// cross-file `$ref` resolves relative to the definition's own directory, which a
// byte slice does not have.
func genFromFile(t *testing.T, path string, cfg map[string]any) map[string]string {
	t.Helper()
	doc, err := parser.Load(path)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	resolved, err := doc.Resolve()
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	if errs := parser.Validate(resolved); errs != nil {
		t.Fatalf("%s invalid: %v", path, errs)
	}
	s, err := model.Build(doc)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	if err := analysis.Analyze(s); err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	files, err := (&Backend{}).Generate(s, cfg)
	if err != nil {
		t.Fatalf("%s generate: %v", path, err)
	}
	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = string(f.Content)
	}
	return out
}

// exampleFiles generates the showcase example and returns its files by path.
func exampleFiles(t *testing.T) map[string]string {
	t.Helper()
	b, err := os.ReadFile("../../examples/messages/example.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return genFromYAML(t, string(b), map[string]any{"package": "messages"})
}

func exampleFile(t *testing.T) string {
	t.Helper()
	return exampleFiles(t)["src/main/kotlin/messages/Myfirstmessage.kt"]
}

