// Package golang is the Go throughput backend (PLAN §6.4): it emits one struct
// per object with Marshal (streaming Encoder) and a pull-parser Unmarshal
// (Decoder.Next/Skip + typed readers) against corelib-go. Generated code is a
// thin, allocation-light wrapper; the corelib owns the wire format.
package golang

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// gofile is the small Builder for a Go source file (PLAN §8.4): intent-level
// line output + managed imports, no ad-hoc cross-file concatenation.
type gofile struct {
	pkg     string
	imports map[string]bool
	body    strings.Builder
}

func newGoFile(pkg string) *gofile {
	return &gofile{pkg: pkg, imports: map[string]bool{}}
}

func (f *gofile) imp(path string) { f.imports[path] = true }

func (f *gofile) line(format string, args ...any) {
	fmt.Fprintf(&f.body, format, args...)
	f.body.WriteByte('\n')
}

func (f *gofile) blank() { f.body.WriteByte('\n') }

// formatSource is go/format.Source; a test swaps it to prove a failure surfaces.
var formatSource = format.Source

// bytes assembles the final file: banner + package + sorted imports + body. A
// non-empty license adds an SPDX line.
//
// The result is always gofmt output. Source go/format cannot parse is a codegen
// bug, and it is returned as an error rather than emitted unformatted: shipping
// it would hand the user a file that fails their own `gofmt -l` (and most likely
// their build) with nothing pointing back at the generator.
func (f *gofile) bytes(banner, license string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by ")
	b.WriteString(banner)
	b.WriteString("; DO NOT EDIT.\n")
	if license != "" {
		b.WriteString("// SPDX-License-Identifier: ")
		b.WriteString(license)
		b.WriteString("\n")
	}
	b.WriteString("\n")
	b.WriteString("package ")
	b.WriteString(f.pkg)
	b.WriteString("\n\n")
	if len(f.imports) > 0 {
		paths := make([]string, 0, len(f.imports))
		for p := range f.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		b.WriteString("import (\n")
		for _, p := range paths {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(f.body.String())
	formatted, err := formatSource([]byte(b.String()))
	if err != nil {
		return nil, err
	}
	return formatted, nil
}
