// Package csharp is the C#/.NET throughput backend (PLAN §6.4): classes with
// Serialize over OStream and a flat-visitor decode (IVisitor) against corelib-cs.
// The corelib's IVisitor is flat (SequenceBegin/End, no child visitors), so
// decode is a (location, id) state machine with a location stack — mirroring the
// Rust backend.
package csharp

import (
	"fmt"
	"strings"

	"github.com/sofa-buffers/generator/internal/generator"
	"github.com/sofa-buffers/generator/internal/ir"
)

func init() { generator.Register(&Backend{}) }

// Backend implements generator.Backend for C#.
type Backend struct{}

func (*Backend) Lang() string { return "csharp" }

func (*Backend) Generate(s *ir.Schema, cfg map[string]any) ([]generator.File, error) {
	g := &gen{schema: s, ns: cfgString(cfg, "namespace", "Message"), banner: cfgString(cfg, "tool_banner", "sofabgen"), license: generator.LicenseID(cfg), limits: resolveLimits(cfg), size: generator.NewSizePolicy(cfg)}
	files := []generator.File{{Path: "Message.cs", Content: g.module(s)}}
	if cfgString(cfg, "emit", "sources") == "project" {
		files = append(files, g.projectFiles(s, cfg)...)
	}
	if g.sizeErr != nil {
		return nil, g.sizeErr
	}
	return files, nil
}

type gen struct {
	schema  *ir.Schema
	ns      string
	banner  string
	license string // SPDX id, "" to omit the header line
	limits  limitSet
	// size is the max_message_size policy; sizeErr carries a violation out of
	// the emit path, which has no error channel of its own.
	size    generator.SizePolicy
	sizeErr error
}

// messageSize resolves a message's worst-case encoded size via the shared walk
// (ir.MaxWireSize), falling back to the configured max_message_size ceiling when
// a field is unbounded. The emit path has no error channel, so a violation of an
// explicitly configured ceiling is recorded here and surfaced by Generate.
func (g *gen) messageSize(name string, fields []*ir.Field) generator.MessageSize {
	ms, err := g.size.Resolve(name, fields)
	if err != nil && g.sizeErr == nil {
		g.sizeErr = err
	}
	return ms
}

// limitSet is the receiver-side decode-limit configuration (generator#102).
// Unlike the corelib-global backends (Go/Python/TypeScript), the C# guards are
// emitted per-field in the generated visitor and only on schema-unbounded
// fields, so each configured cap is used as-is (no raise to the largest schema
// bound): a schema-bounded field never meets a cap and keeps only its
// generator#100 schema-capacity guard. Each cap is always SET — every target
// carries a finite default (§9.5, generator#385) — so the only question left is
// whether it is LIVE: a cap is inert for a message whose reachable fields have
// no unbounded field of that kind (ir.Bounds, checked per visitor), and then no
// constant or guard is emitted.
type limitSet struct {
	arrayCount, stringLen, blobLen int64
	arrayHas, stringHas, blobHas   bool
}

// resolveLimits reads the max_dyn_* config keys over the target's finite
// defaults (see limitSet). Unlike the other backends it does not consult the
// schema here: liveness is decided per message in emitVisitor, because C# emits
// the constants and guards per visitor rather than once per module.
func resolveLimits(cfg map[string]any) limitSet {
	d := generator.ServerDynLimits.Resolve(cfg)
	return limitSet{
		arrayCount: d.ArrayCount, arrayHas: true,
		stringLen: d.StringLen, stringHas: true,
		blobLen: d.BlobLen, blobHas: true,
	}
}

type cfile struct{ b strings.Builder }

func (f *cfile) line(format string, args ...any) {
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}
func (f *cfile) blank()        { f.b.WriteByte('\n') }
func (f *cfile) bytes() []byte { return []byte(f.b.String()) }

func (g *gen) module(s *ir.Schema) []byte {
	f := &cfile{}
	f.line("// Code generated by %s; DO NOT EDIT.", g.banner)
	if g.license != "" {
		f.line("// SPDX-License-Identifier: %s", g.license)
	}
	f.line("using System;")
	f.line("using System.Collections.Generic;")
	f.line("using System.Text;")
	f.line("using sofab;")
	f.blank()
	f.line("namespace %s;", g.ns)
	f.blank()

	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		switch nt.Category {
		case ir.CatEnum:
			g.emitEnum(f, nt)
		case ir.CatBitfield:
			g.emitBitfield(f, nt)
		}
	}
	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		if nt.Category == ir.CatStruct || nt.Category == ir.CatUnion {
			g.emitClass(f, g.typeName(key), nt.Summary, nt.Fields, false)
		}
	}
	for _, m := range s.Messages {
		g.emitClass(f, exported(m.Name), m.Summary, m.Fields, true)
	}
	return f.bytes()
}

func (g *gen) emitEnum(f *cfile, nt *ir.NamedType) {
	f.line("public enum %s : %s {", g.typeName(nt.Key), enumBacking(nt))
	for _, c := range nt.Consts {
		emitDoc(f, "    ", c.Description)
		f.line("    %s = %d,", exported(c.Name), c.Value)
	}
	f.line("}")
	f.blank()
}

func (g *gen) emitBitfield(f *cfile, nt *ir.NamedType) {
	f.line("[Flags]")
	f.line("public enum %s : %s {", g.typeName(nt.Key), bitfieldBacking(nt))
	for _, fl := range nt.Flags {
		emitDoc(f, "    ", flagDoc(fl))
		f.line("    %s = %d,", exported(fl.Name), uint64(1)<<uint(fl.Pos))
	}
	f.line("}")
	f.blank()
}

func (g *gen) emitClass(f *cfile, name, summary string, fields []*ir.Field, isMessage bool) {
	emitDoc(f, "", summary)
	f.line("public sealed class %s {", name)
	for _, fld := range fields {
		emitDoc(f, "    ", fieldDoc(fld, generator.BoundNote(fld, generator.StorageDynamic)))
		if fld.Deprecated {
			f.line("    [Obsolete]")
		}
		f.line("    public %s %s%s;", g.csType(fld), csIdent(fld.Name), g.csInit(fld))
	}
	// Hoist each native array's omit-compare default into a static: Serialize only
	// ever reads it, so one shared instance suffices and encode stops allocating
	// a fresh literal (a `count: N` field's default is N elements long — for a
	// large N that per-call allocation would dominate). The mutable per-object
	// initializer above stays a fresh allocation.
	for _, fld := range fields {
		if def, ok := g.csArrayCompareDefault(fld); ok {
			f.line("    private static readonly %s %s = %s;", g.csType(fld), arrDefName(fld), def)
		}
	}
	f.blank()

	// Serialize. Generated marshal legitimately reads fields marked [Obsolete];
	// silence the CS0618 deprecation warning around that internal access.
	dep := hasDeprecatedDirect(fields)
	f.line("    public void Serialize(OStream os) {")
	if dep {
		f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
	}
	for _, fld := range fields {
		g.emitMarshal(f, fld)
	}
	if dep {
		f.line("#pragma warning restore 618")
	}
	f.line("    }")

	g.emitIsDefault(f, fields, dep)

	if isMessage {
		ms := g.messageSize(name, fields)
		if !ms.Bounded {
			f.line("    // Configured ceiling (max_message_size): an unbounded field means this")
			f.line("    // size is imposed, not derived from the schema.")
			f.line("    public const int MaxSizeLimit = %d;", ms.Size)
			f.line("    public const int MaxSize = MaxSizeLimit;")
		} else {
			f.line("    public const int MaxSize = %d;", ms.Size)
		}
		f.line("    // Per-thread scratch buffer: Encode() serialises into it and returns an")
		f.line("    // exact-size copy, so the worst-case buffer is not re-allocated (and")
		f.line("    // zeroed) on every call. Do not call Encode() reentrantly from a")
		f.line("    // Serialize() override on the same thread.")
		f.line("    [ThreadStatic] private static byte[] _encScratch;")
		f.line("    public byte[] Encode() {")
		f.line("        var buf = _encScratch ??= new byte[MaxSize];")
		f.line("        var os = new OStream(buf);")
		f.line("        Serialize(os);")
		f.line("        var outp = new byte[os.BytesUsed];")
		f.line("        Array.Copy(buf, outp, os.BytesUsed);")
		f.line("        return outp;")
		f.line("    }")
		// Streaming encode. Serialize writes the fields and nothing else, so a
		// nested message can be written into an open frame; this is the entry
		// point for a caller who owns the stream, and it flushes the tail the
		// last write left in the buffer. With a FlushSink on `os` the buffer may
		// be smaller than the message.
		f.line("    /// <summary>")
		f.line("    /// Encode into a stream the caller owns, then flush the tail.")
		f.line("    /// With a <c>FlushSink</c> on <paramref name=\"os\"/> the buffer may be")
		f.line("    /// smaller than the message: it is drained as it fills, so what bounds")
		f.line("    /// memory is the buffer, not the message.")
		f.line("    /// </summary>")
		f.line("    public void EncodeTo(OStream os) {")
		f.line("        Serialize(os);")
		f.line("        os.Flush();")
		f.line("    }")
		// Best-effort decode: kept for back-compat. It discards Feed's
		// DecodeStatus, so a truncated message is indistinguishable from a
		// COMPLETE one — prefer TryDecode when that verdict matters
		// (generator#105).
		f.line("    public static %s Decode(byte[] data) {", name)
		f.line("        var m = new %s();", name)
		f.line("        var v = new %sVisitor(m);", name)
		f.line("        new IStream().Feed(data, 0, data.Length, v);")
		f.line("        return m;")
		f.line("    }")
		// Status-surfacing one-shot decode (MESSAGE_SPEC §7): returns the
		// corelib's terminal DecodeStatus — Complete at a clean field boundary,
		// Incomplete when the bytes end inside a field or an open sequence.
		// Malformed input throws SofabException (Invalid) from Feed. msg always
		// receives the fields decoded so far; on Incomplete the caller owns
		// end-of-input and decides whether truncation is an error.
		f.line("    public static DecodeStatus TryDecode(byte[] data, out %s msg) {", name)
		f.line("        msg = new %s();", name)
		f.line("        return new IStream().Feed(data, 0, data.Length, new %sVisitor(msg));", name)
		f.line("    }")
		// Streaming decode (PLAN §5.6). The corelib's IStream is resumable, so
		// the only thing missing was a public handle on it: Decoder() binds a
		// fresh destination and hands back an object whose Feed takes chunks of
		// any size. Nested, matching the Java backend's Msg.Decoder.
		g.emitDecoder(f, name)
	}
	f.line("}")
	f.blank()

	if isMessage {
		// The flat-visitor decode writes into reachable fields, including any
		// marked [Obsolete] (message-level or nested struct/union); silence the
		// CS0618 deprecation warning around the generated decode.
		depVis := framesHaveDeprecated(g.frames(&ir.Message{Name: name, Fields: fields}))
		if depVis {
			f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
		}
		g.emitVisitor(f, name, fields)
		if depVis {
			f.line("#pragma warning restore 618")
			f.blank()
		}
	}
}

// emitDecoder writes the public incremental decoder: a handle on the corelib's
// resumable IStream plus the destination it fills. The corelib already suspends
// and resumes at any byte boundary, so this type carries no parse state of its
// own -- it exists to make that reachable from outside the assembly, which an
// `internal` IVisitor was not (PLAN §5.6).
//
// Nested and constructed with `new Msg.Decoder()` rather than reached through a
// static Decoder() factory as in Java: C# puts nested types and members in ONE
// declaration space, so a method and a nested class cannot share the name. The
// constructor is the factory.
func (g *gen) emitDecoder(f *cfile, name string) {
	f.line("    /// <summary>")
	f.line("    /// Incremental decoder for <see cref=\"%s\"/>: hold one and feed the", name)
	f.line("    /// message as bytes arrive, instead of buffering it whole first.")
	f.line("    /// </summary>")
	f.line("    /// <remarks>")
	f.line("    /// The wire format has no end marker at the top level -- a message ends")
	f.line("    /// where its bytes end -- so a feed cannot report that the MESSAGE is")
	f.line("    /// complete, only that the bytes handed in ended on a field boundary")
	f.line("    /// (<c>Complete</c>) or mid-field (<c>Incomplete</c>). Neither is a")
	f.line("    /// failure mid-stream; the caller's own framing decides when the input")
	f.line("    /// is over, and <c>Finish</c> then gives the verdict for the message as")
	f.line("    /// a whole.")
	f.line("    /// </remarks>")
	f.line("    public sealed class Decoder {")
	f.line("        private readonly %s _m = new %s();", name, name)
	f.line("        private readonly IStream _is = new IStream();")
	f.line("        private readonly %sVisitor _v;", name)
	f.blank()
	f.line("        public Decoder() { _v = new %sVisitor(_m); }", name)
	f.blank()
	f.line("        /// <summary>")
	f.line("        /// Feed the next chunk, of any size. Returns <c>Complete</c> if it")
	f.line("        /// ended on a field boundary, <c>Incomplete</c> if it ended mid-field")
	f.line("        /// -- neither answers whether the MESSAGE is done.")
	f.line("        /// </summary>")
	f.line("        public DecodeStatus Feed(byte[] chunk) => _is.Feed(chunk, 0, chunk.Length, _v);")
	f.blank()
	f.line("        /// <summary>As <c>Feed</c>, over a slice of <paramref name=\"chunk\"/>.</summary>")
	f.line("        public DecodeStatus Feed(byte[] chunk, int off, int len) => _is.Feed(chunk, off, len, _v);")
	f.blank()
	f.line("        /// <summary>The outcome for everything fed so far.</summary>")
	f.line("        public DecodeStatus Status => _is.Status;")
	f.blank()
	f.line("        /// <summary>The destination, holding whatever has been decoded so far.</summary>")
	f.line("        public %s Message => _m;", name)
	f.blank()
	f.line("        /// <summary>")
	f.line("        /// Take the decoded message once the caller's framing says the input")
	f.line("        /// is over. Rejects a stream that ended mid-field rather than")
	f.line("        /// returning a half-filled value; read <c>Message</c> to get it")
	f.line("        /// anyway.")
	f.line("        /// </summary>")
	f.line("        /// <remarks>")
	f.line("        /// This is an <c>InvalidOperationException</c> and not a")
	f.line("        /// <c>SofabException</c> on purpose: an incomplete message is not a")
	f.line("        /// malformed one. Nothing is wrong with the bytes -- the caller")
	f.line("        /// declared end-of-input at a point they did not agree with.")
	f.line("        /// </remarks>")
	f.line("        public %s Finish() {", name)
	f.line("            if (_is.Status != DecodeStatus.Complete) {")
	f.line("                throw new InvalidOperationException(")
	f.line("                    $\"%s: stream ended mid-field ({_is.Status})\");", name)
	f.line("            }")
	f.line("            return _m;")
	f.line("        }")
	f.line("    }")
}

// emitIsDefault emits the class's all-default predicate. It is the exact negation
// of what Serialize writes: the object is default iff Serialize would emit no child at
// all, evaluated per field and recursively (MESSAGE_SPEC §2). It is the explicit
// form of the predicate lazy framing applies implicitly ("not one child was
// written"), generated from the very same per-field expressions the writer uses so
// the two cannot drift apart: a predicate that disagrees with the writer omits a
// field that is on the wire, or keeps one that is not.
// `dep` carries emitMarshal's CS0618 guard: the predicate reads the very same
// members, including any marked [Obsolete].
func (g *gen) emitIsDefault(f *cfile, fields []*ir.Field, dep bool) {
	f.line("    public bool IsDefault() {")
	if dep {
		f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
	}
	for _, fld := range fields {
		f.line("        if (!(%s)) return false;", g.fieldIsDefaultExpr(fld))
	}
	if dep {
		f.line("#pragma warning restore 618")
	}
	f.line("        return true;")
	f.line("    }")
}

// fieldIsDefaultExpr is the boolean expression "this field equals its default",
// i.e. the negation of emitMarshal's write guard for the same field.
func (g *gen) fieldIsDefaultExpr(fld *ir.Field) string {
	acc := "this." + csIdent(fld.Name)
	switch fld.Kind {
	case ir.KindBlob:
		if g.csDefaultValue(fld) == "Array.Empty<byte>()" {
			return fmt.Sprintf("%s == null || %s.Length == 0", acc, acc)
		}
		return fmt.Sprintf("System.Linq.Enumerable.SequenceEqual(%s ?? Array.Empty<byte>(), %s)", acc, g.csDefaultValue(fld))
	case ir.KindStruct, ir.KindUnion:
		// Lazily framed: the frame survives iff the nested Serialize wrote a child,
		// which is exactly "the nested object is not default".
		return fmt.Sprintf("(%s ?? new %s()).IsDefault()", acc, g.typeName(fld.Ref.Key))
	case ir.KindArray:
		return g.arrayIsDefaultExpr(fld, acc)
	}
	return fmt.Sprintf("%s == %s", acc, g.csDefaultValue(fld))
}

// arrayIsDefaultExpr mirrors emitMarshalArray. An array's declared `count: N` is a
// CAPACITY, never a length (MESSAGE_SPEC §3), so it takes no part in this test: the
// value is compared against the declared default exactly as written, with no
// padding to N on either side, and against the empty collection when none is
// declared. A count:N array is therefore default only when it is EMPTY — an
// all-zero N-element value is a length-N array, which differs from the empty one
// and stays on the wire.
func (g *gen) arrayIsDefaultExpr(fld *ir.Field, acc string) string {
	if nativeArrayElem(fld.Elem) {
		if _, ok := g.csArrayCompareDefault(fld); ok {
			return fmt.Sprintf("System.Linq.Enumerable.SequenceEqual(%s, %s)", acc, arrDefName(fld))
		}
		if primArrayElem(fld.Elem) {
			return fmt.Sprintf("%s == null || %s.Length == 0", acc, acc)
		}
		return fmt.Sprintf("%s.Count == 0", acc)
	}
	// Wrapper array: the writer emits a child for every element it holds, because the
	// LAST element is written whatever its value (§2) — so "no child is written" is
	// exactly "the array is empty", and the two cannot drift apart.
	return fmt.Sprintf("%s.Count == 0", acc)
}

// hasDeprecatedDirect reports whether any direct field of a class is deprecated,
// so its Serialize reads a member marked [Obsolete] and needs the CS0618 guard.
func hasDeprecatedDirect(fields []*ir.Field) bool {
	for _, fld := range fields {
		if fld.Deprecated {
			return true
		}
	}
	return false
}

// framesHaveDeprecated reports whether any object-scope field reachable from a
// message (message-level or a nested struct/union) is deprecated, so the
// generated visitor writes into a member marked [Obsolete].
func framesHaveDeprecated(fs []frame) bool {
	for _, fr := range fs {
		if fr.isArr {
			continue
		}
		for _, fld := range fr.fields {
			if fld.Deprecated {
				return true
			}
		}
	}
	return false
}

func (g *gen) emitMarshal(f *cfile, fld *ir.Field) {
	acc := "this." + csIdent(fld.Name)
	var write string
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		write = fmt.Sprintf("os.WriteUnsigned(%d, (ulong)%s);", fld.ID, acc)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		write = fmt.Sprintf("os.WriteSigned(%d, (long)%s);", fld.ID, acc)
	case ir.KindBool:
		write = fmt.Sprintf("os.WriteBoolean(%d, %s);", fld.ID, acc)
	case ir.KindFP32:
		write = fmt.Sprintf("os.WriteFp32(%d, %s);", fld.ID, acc)
	case ir.KindFP64:
		write = fmt.Sprintf("os.WriteFp64(%d, %s);", fld.ID, acc)
	case ir.KindString:
		write = fmt.Sprintf("os.WriteString(%d, %s ?? \"\");", fld.ID, acc)
	case ir.KindBlob:
		// A blob is a leaf: omit when equal to its default (empty if none). The
		// decoder reconstructs the omitted field from its materialized default.
		// With an empty default the content compare degenerates to a length
		// check, sparing the LINQ SequenceEqual enumeration per call.
		if g.csDefaultValue(fld) == "Array.Empty<byte>()" {
			f.line("        if (%s != null && %s.Length != 0) { os.WriteBlob(%d, %s); }", acc, acc, fld.ID, acc)
			return
		}
		f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s ?? Array.Empty<byte>(), %s)) { os.WriteBlob(%d, %s ?? Array.Empty<byte>()); }", acc, g.csDefaultValue(fld), fld.ID, acc)
		return
	case ir.KindStruct, ir.KindUnion:
		// MESSAGE_SPEC S2: the != default test is per field and a sequence-typed
		// FIELD is no exception, so the frame is opened LAZILY -- the corelib holds
		// the header back until a child field appears. The nested Serialize omits every
		// child that equals its default, so "no child was written" IS "the object
		// equals its declared default", evaluated per field and recursively. The
		// dropping closer therefore makes an all-default nested object vanish instead
		// of reaching the wire as an empty wrapper frame.
		f.line("        os.WriteSequenceBeginLazy(%d); (%s ?? new %s()).Serialize(os); os.WriteSequenceEnd();", fld.ID, acc, g.typeName(fld.Ref.Key))
		return
	case ir.KindArray:
		g.emitMarshalArray(f, fld, acc)
		return
	}
	// Scalar/string/enum/bitfield leaf: always omit when equal to the default;
	// sparse encoding is canonical (MESSAGE_SPEC S2) and the decoder reconstructs
	// the omitted field from its default.
	f.line("        if (%s != %s) { %s }", acc, g.csDefaultValue(fld), write)
}

// arrDefName is the static holding a native array field's omit-compare default.
func arrDefName(fld *ir.Field) string { return "_arrdef_" + fld.Name }

// csArrayCompareDefault is the literal a native array field's value is compared
// against for whole-field omission, and ("", false) when the field has no
// materialized default (a dynamic array with no schema default, or a
// wrapper-sequence array, whose whole-field omission is the corelib's lazy frame
// rather than a compare here). It is exactly the field initializer, so an
// untouched field always compares equal and is omitted.
func (g *gen) csArrayCompareDefault(fld *ir.Field) (string, bool) {
	if fld.Kind != ir.KindArray {
		return "", false
	}
	if primArrayElem(fld.Elem) {
		return g.csPrimArrayLiteral(fld)
	}
	return g.csNativeArrayLiteral(fld)
}

func (g *gen) emitMarshalArray(f *cfile, fld *ir.Field, acc string) {
	// A native scalar array is a leaf field: omit it when equal to its default
	// (materialized in the field initializer), else when empty. A composite/
	// dynamic-element array is a wrapper sequence, opened lazily and closed by the
	// dropping end, so an EMPTY one is omitted rather than framed empty.
	//
	// A declared `count: N` takes no part in either test. `count` is a CAPACITY,
	// never a length (§3): it never reaches the wire, so the value is compared
	// against the declared default exactly as written -- neither side padded to N --
	// and against the empty collection when no default is declared.
	if primArrayElem(fld.Elem) {
		// Primitive array (T[]): written straight to the OStream overload with
		// no List.ToArray temporary.
		if _, ok := g.csArrayCompareDefault(fld); ok {
			f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s, %s)) {", acc, arrDefName(fld))
		} else {
			f.line("        if (%s != null && %s.Length != 0) {", acc, acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, true, "")
		f.line("        }")
		return
	}
	if nativeArrayElem(fld.Elem) {
		if _, ok := g.csArrayCompareDefault(fld); ok {
			f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s, %s)) {", acc, arrDefName(fld))
		} else {
			f.line("        if (%s.Count != 0) {", acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, "")
		f.line("        }")
		return
	}
	// The field-level wrapper frame is dropped when no element is written, and
	// absence then reconstructs the field's default. That is correct because a
	// wrapper array's declared `default` is not materialized today (the generated
	// field initializer is the empty collection), so absent and explicitly-empty
	// denote the same value. If that gap is ever closed, this call needs a guard --
	// `if (value != default) { ... WriteSequenceEndKeep(); }` -- so that a value
	// differing from a non-empty default still reaches the wire as the empty
	// wrapper, the only encoding of "explicitly empty" (MESSAGE_SPEC §2, §3).
	g.marshalArray(f, "        ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, "")
}

// lastElemExpr is the "this element is the array's last" test, at loop position
// iv over an array of nv elements.
//
// It is the whole of the positional half of MESSAGE_SPEC §2's element rule. A
// wrapper array carries no length field: its decoded length is *highest present
// id + 1* (§5.1), so the element at the highest index is the only one whose
// PRESENCE carries the length, and nothing that carries the length may be elided.
// Everything before it may be: an interior element equal to the element default is
// indistinguishable from an absent one, because the decoder restores an absent id
// from that same default. Hence: interior sparse, last always written.
//
// A declared `count: N` changes nothing here. N is a capacity, not a length (§3),
// so it can never restore an elided tail -- the same test applies with or without
// one.
func lastElemExpr(iv, nv string) string {
	return fmt.Sprintf("%s == %s - 1", iv, nv)
}

// emitSeqEnd closes the wrapper sequence opened at ind, choosing between the two
// closers the corelib offers. Every sequence is opened LAZILY (the corelib holds
// the header back until a child is written), so the closer alone decides whether a
// contentless one survives: WriteSequenceEnd drops it, WriteSequenceEndKeep forces
// the empty frame out.
//
// keepIf is the condition under which an empty frame must survive:
//   - "" -- never. A sequence-typed FIELD (a struct/union field, an array wrapper):
//     an all-default one is omitted and absence reconstructs it (§2).
//   - a lastElemExpr -- a sequence-form array ELEMENT, kept only at the array's
//     last index. In the interior it is dropped and leaves an id GAP, which is what
//     makes an all-default element sparse like any other default value. Note this
//     is decided from the position in the VALUE, at run time; the schema cannot
//     answer it.
func emitSeqEnd(f *cfile, ind, keepIf string) {
	if keepIf == "" {
		f.line("%sos.WriteSequenceEnd();", ind)
		return
	}
	f.line("%sif (%s) os.WriteSequenceEndKeep(); else os.WriteSequenceEnd();", ind, keepIf)
}

// marshalArray writes the list `val` as field `idExpr`. Numeric/enum/boolean/
// bitfield elements use the native array wire type (enum -> signed, boolean/
// bitfield -> unsigned, value-converted to the corelib's array element width);
// string/blob/struct/union/array elements lower to a wrapper sequence whose child
// ids are the 0-based index (per MESSAGE_SPEC). Recurses for nested arrays,
// depth-suffixing the loop var to avoid collisions. isPrim marks `val` as a
// primitive T[] field (written directly); inner rows of nested arrays stay
// List<T> and bridge via ToArray.
//
// Every element the value holds is written -- no trailing run is elided, of either
// element kind, because the wire count M IS the array's length (§3) and the highest
// wrapper id IS its last index (§5.1). What the interior may drop is a value that
// is indistinguishable from absence, and only that.
//
// keepIf is the closer this call's own wrapper takes (see emitSeqEnd); the native
// element kinds open no sequence and ignore it.
func (g *gen) marshalArray(f *cfile, ind, idExpr, val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, depth int, isPrim bool, keepIf string) {
	iv := fmt.Sprintf("_i%d", depth)
	// `nv` is declared in the for-statement's own scope, so two array fields in one
	// Serialize never collide and the length is evaluated exactly once per field.
	nv := fmt.Sprintf("_n%d", depth)
	loop := fmt.Sprintf("for (int %s = 0, %s = %s.Count; %s < %s; %s++)", iv, nv, val, iv, nv, iv)
	last := lastElemExpr(iv, nv)
	arr := val + ".ToArray()"
	if isPrim {
		arr = val
	}
	switch elem {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64:
		f.line("%sos.WriteArrayUnsigned(%s, %s);", ind, idExpr, arr)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64:
		f.line("%sos.WriteArraySigned(%s, %s);", ind, idExpr, arr)
	case ir.KindFP32:
		f.line("%sos.WriteArrayFp32(%s, %s);", ind, idExpr, arr)
	case ir.KindFP64:
		f.line("%sos.WriteArrayFp64(%s, %s);", ind, idExpr, arr)
	case ir.KindEnum:
		// enum -> signed array at the enum's backing width (matches Go's typed array).
		f.line("%sos.WriteArraySigned(%s, Array.ConvertAll(%s.ToArray(), _x => (%s)_x));", ind, idExpr, val, enumBacking(ref.Target))
	case ir.KindBitfield:
		f.line("%sos.WriteArrayUnsigned(%s, Array.ConvertAll(%s.ToArray(), _x => (%s)_x));", ind, idExpr, val, bitfieldBacking(ref.Target))
	case ir.KindBool:
		// boolean -> unsigned u8 array of 0/1.
		f.line("%sos.WriteArrayUnsigned(%s, Array.ConvertAll(%s.ToArray(), _x => _x ? (byte)1 : (byte)0));", ind, idExpr, val)
	case ir.KindString:
		// A string element is a leaf: in the array's INTERIOR it is omitted when it
		// equals the element default (empty), leaving an id gap the decoder restores
		// from that same default -- the ordinary sparse-field rule of MESSAGE_SPEC §2,
		// applied to an element. At the LAST index it is written whatever its value:
		// see lastElemExpr.
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s { if ((%s[%s] ?? \"\") != \"\" || %s) os.WriteString(%s, %s[%s] ?? \"\"); }", ind, loop, val, iv, last, iv, val, iv)
		emitSeqEnd(f, ind, keepIf)
	case ir.KindBlob:
		// A blob element is a leaf, exactly like the string element above.
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s { if ((%s[%s] ?? Array.Empty<byte>()).Length != 0 || %s) os.WriteBlob(%s, %s[%s] ?? Array.Empty<byte>()); }", ind, loop, val, iv, last, iv, val, iv)
		emitSeqEnd(f, ind, keepIf)
	case ir.KindStruct, ir.KindUnion:
		// A sequence-form element obeys the SAME rule as the leaf elements above --
		// one rule for both kinds -- and the lazily-held frame is where it is applied.
		// The nested Serialize writes no child exactly when the element equals its
		// declared default, so the CLOSER alone decides: the dropping one in the
		// interior, where an all-default element vanishes into an id gap; the keeping
		// one at the last index, where it survives as an empty frame because that
		// presence is what fixes the array's length.
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s {", ind, loop)
		f.line("%s    os.WriteSequenceBeginLazy(%s); (%s[%s] ?? new %s()).Serialize(os);", ind, iv, val, iv, g.typeName(ref.Key))
		emitSeqEnd(f, ind+"    ", last)
		f.line("%s}", ind)
		emitSeqEnd(f, ind, keepIf)
	case ir.KindArray:
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s {", ind, loop)
		if nativeArrayElem(items.Elem) {
			// A native row is a single count-prefixed value with no frame of its own,
			// so the rule lands on the WRITE rather than on a closer: an interior row
			// equal to the element default (the empty row) is not written at all, and
			// the last row always is.
			f.line("%s    if (%s[%s].Count != 0 || %s) {", ind, val, iv, last)
			g.marshalArray(f, ind+"        ", iv, fmt.Sprintf("%s[%s]", val, iv), items.Elem, items.ElemRef, items.ElemItems, depth+1, false, "")
			f.line("%s    }", ind)
		} else {
			// A wrapper row has its own frame, so it takes the closer instead -- the
			// same interior/last choice, expressed the same way as for a struct element
			// above.
			g.marshalArray(f, ind+"    ", iv, fmt.Sprintf("%s[%s]", val, iv), items.Elem, items.ElemRef, items.ElemItems, depth+1, false, last)
		}
		f.line("%s}", ind)
		emitSeqEnd(f, ind, keepIf)
	}
}
