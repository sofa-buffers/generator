// Package csharp is the C#/.NET throughput backend (PLAN §6.4): classes with
// Marshal over OStream and a flat-visitor decode (IVisitor) against corelib-cs.
// The corelib's IVisitor is flat (SequenceBegin/End, no child visitors), so
// decode is a (location, id) state machine with a location stack — mirroring the
// Rust backend.
package csharp

import (
	"fmt"
	"strings"

	"github.com/sofa-buffers/generator/internal/generator"
	"github.com/sofa-buffers/generator/internal/ir"
)

func init() { generator.Register(&Backend{}) }

// Backend implements generator.Backend for C#.
type Backend struct{}

func (*Backend) Lang() string { return "csharp" }

func (*Backend) Generate(s *ir.Schema, cfg map[string]any) ([]generator.File, error) {
	g := &gen{schema: s, ns: cfgString(cfg, "namespace", "Message"), banner: cfgString(cfg, "tool_banner", "sofabgen"), license: generator.LicenseID(cfg), limits: resolveLimits(cfg), size: generator.NewSizePolicy(cfg)}
	files := []generator.File{{Path: "Message.cs", Content: g.module(s)}}
	if cfgString(cfg, "emit", "sources") == "project" {
		files = append(files, g.projectFiles(s, cfg)...)
	}
	if g.sizeErr != nil {
		return nil, g.sizeErr
	}
	return files, nil
}

type gen struct {
	schema  *ir.Schema
	ns      string
	banner  string
	license string // SPDX id, "" to omit the header line
	limits  limitSet
	// trimElems is the set of named struct/union keys used as the element type of
	// a `count: N` wrapper array anywhere in the schema, i.e. exactly the types
	// that need the static TrimTail helper finding M for that array
	// (MESSAGE_SPEC §3/§5.1 — generator#248).
	trimElems map[string]bool
	// size is the max_message_size policy; sizeErr carries a violation out of
	// the emit path, which has no error channel of its own.
	size    generator.SizePolicy
	sizeErr error
}

// messageSize resolves a message's worst-case encoded size via the shared walk
// (ir.MaxWireSize), falling back to the configured max_message_size ceiling when
// a field is unbounded. The emit path has no error channel, so a violation of an
// explicitly configured ceiling is recorded here and surfaced by Generate.
func (g *gen) messageSize(name string, fields []*ir.Field) generator.MessageSize {
	ms, err := g.size.Resolve(name, fields)
	if err != nil && g.sizeErr == nil {
		g.sizeErr = err
	}
	return ms
}

// limitSet is the receiver-side decode-limit configuration (generator#102).
// Unlike the corelib-global backends (Go/Python/TypeScript), the C# guards are
// emitted per-field in the generated visitor and only on schema-unbounded
// fields, so each configured cap is used as-is (no raise to the largest schema
// bound): a schema-bounded field never meets a cap and keeps only its
// generator#100 schema-capacity guard. A configured key is still inert for a
// message whose reachable fields have no unbounded field of that kind
// (ir.Bounds, checked per visitor) — then no constant or guard is emitted.
type limitSet struct {
	arrayCount, stringLen, blobLen int64
	arrayHas, stringHas, blobHas   bool
}

// resolveLimits reads the max_dyn_* config keys (see limitSet).
func resolveLimits(cfg map[string]any) limitSet {
	var l limitSet
	l.arrayCount, l.arrayHas = cfgLimit(cfg, "max_dyn_array_count")
	l.stringLen, l.stringHas = cfgLimit(cfg, "max_dyn_string_len")
	l.blobLen, l.blobHas = cfgLimit(cfg, "max_dyn_blob_len")
	return l
}

type cfile struct{ b strings.Builder }

func (f *cfile) line(format string, args ...any) {
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}
func (f *cfile) blank()        { f.b.WriteByte('\n') }
func (f *cfile) bytes() []byte { return []byte(f.b.String()) }

func (g *gen) module(s *ir.Schema) []byte {
	g.trimElems = trimElemTypes(s)
	f := &cfile{}
	f.line("// Code generated by %s; DO NOT EDIT.", g.banner)
	if g.license != "" {
		f.line("// SPDX-License-Identifier: %s", g.license)
	}
	f.line("using System;")
	f.line("using System.Collections.Generic;")
	f.line("using System.Text;")
	f.line("using sofab;")
	f.blank()
	f.line("namespace %s;", g.ns)
	f.blank()

	g.emitFixedHelpers(f, s)

	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		switch nt.Category {
		case ir.CatEnum:
			g.emitEnum(f, nt)
		case ir.CatBitfield:
			g.emitBitfield(f, nt)
		}
	}
	for _, key := range s.NamedOrder {
		nt := s.Named[key]
		if nt.Category == ir.CatStruct || nt.Category == ir.CatUnion {
			g.emitClass(f, key, g.typeName(key), nt.Summary, nt.Fields, false)
		}
	}
	for _, m := range s.Messages {
		g.emitClass(f, "", exported(m.Name), m.Summary, m.Fields, true)
	}
	return f.bytes()
}

// fixedTrimKinds reports which trailing-default-run trim helpers the schema
// actually needs: the generic one (integer/enum/bitfield/boolean elements, whose
// wire image is an integer array) and the two float ones. Only a top-level
// `count: N` field with a NATIVE element is fixed-length; nested array-of-array
// rows and wrapper-sequence elements never trim (MESSAGE_SPEC §3).
func fixedTrimKinds(s *ir.Schema) (gen32, f32, f64 bool) {
	eachFieldList(s, func(fields []*ir.Field) {
		for _, fld := range fields {
			if fld.Kind != ir.KindArray || !fld.HasCount || !nativeArrayElem(fld.Elem) {
				continue
			}
			switch fld.Elem {
			case ir.KindFP32:
				f32 = true
			case ir.KindFP64:
				f64 = true
			default:
				gen32 = true
			}
		}
	})
	return
}

// eachFieldList calls fn with the field list of every generated class: the named
// struct/union types first, then the messages — the same order module() emits.
func eachFieldList(s *ir.Schema, fn func([]*ir.Field)) {
	for _, key := range s.NamedOrder {
		if nt := s.Named[key]; nt.Category == ir.CatStruct || nt.Category == ir.CatUnion {
			fn(nt.Fields)
		}
	}
	for _, m := range s.Messages {
		fn(m.Fields)
	}
}

// seqTrimKinds reports which WRAPPER-array trim helpers the schema needs
// (generator#248): the string, blob and nested-row narrowings that find M, one
// past a wrapper array's last non-default element. Struct/union elements are not
// here — each such element type carries its own TrimTail (see emitTrimTail),
// since the predicate is that class's own IsDefault. Only a top-level field is
// narrowed, so nested rows are scanned as fields, never as elements: a `count: N`
// on the FIELD is what makes the trailing run reconstructible (MESSAGE_SPEC §3).
func seqTrimKinds(s *ir.Schema) (str, blob, rows bool) {
	// mark walks one element position. `fixed` is the `count: N` of the enclosing
	// FIELD and so is true at most at the top level: a nested row is an element,
	// never a field, so it is never narrowed AS a row (its own leaf elements still
	// are — marshalArray recurses into them at any depth).
	var mark func(elem ir.Kind, items *ir.ArrayElem, fixed bool)
	mark = func(elem ir.Kind, items *ir.ArrayElem, fixed bool) {
		switch elem {
		case ir.KindString:
			str = true
		case ir.KindBlob:
			blob = true
		case ir.KindArray:
			if fixed {
				rows = true
			}
			if items != nil {
				mark(items.Elem, items.ElemItems, false)
			}
		}
	}
	eachFieldList(s, func(fields []*ir.Field) {
		for _, fld := range fields {
			if fld.Kind == ir.KindArray {
				mark(fld.Elem, fld.ElemItems, fld.HasCount)
			}
		}
	})
	return
}

// trimElemTypes is the set of named struct/union keys used as the element type of
// a `count: N` wrapper array, i.e. exactly the classes whose TrimTail helper is
// reachable. A nested row is never narrowed (MESSAGE_SPEC §3 scopes the
// trailing-default-run rule to fields), so only top-level fields are scanned.
func trimElemTypes(s *ir.Schema) map[string]bool {
	out := map[string]bool{}
	eachFieldList(s, func(fields []*ir.Field) {
		for _, fld := range fields {
			if fld.Kind == ir.KindArray && fld.HasCount &&
				(fld.Elem == ir.KindStruct || fld.Elem == ir.KindUnion) {
				out[fld.ElemRef.Key] = true
			}
		}
	})
	return out
}

// hasFixedSeqField reports whether the schema has a `count: N` WRAPPER array
// field, i.e. whether any field initializer needs SofabFixedArray.Filled to
// materialize the array to N element defaults at construction.
func hasFixedSeqField(s *ir.Schema) bool {
	found := false
	eachFieldList(s, func(fields []*ir.Field) {
		for _, fld := range fields {
			if fld.Kind == ir.KindArray && fld.HasCount && seqArrayElem(fld.Elem) {
				found = true
			}
		}
	})
	return found
}

// emitFixedHelpers emits the trailing-default-run trim helpers a fixed-count
// (`count: N`) native array's canonical encoding needs (MESSAGE_SPEC §3): the
// wire carries only elements [0, M'), where M' is one past the last element that
// differs from the element default, and the decoder rebuilds [M', N) from the
// schema count. Elements compare by BIT PATTERN, not by ==, so a trailing -0.0
// (which == 0.0 in C#) survives the round-trip instead of being trimmed to +0.0,
// and a NaN is never mistaken for the default. Nothing is emitted for a schema
// with no fixed-count native array.
func (g *gen) emitFixedHelpers(f *cfile, s *ir.Schema) {
	genT, f32, f64 := fixedTrimKinds(s)
	str, blob, rows := seqTrimKinds(s)
	fill := hasFixedSeqField(s)
	if !genT && !f32 && !f64 && !str && !blob && !rows && !fill {
		return
	}
	f.line("// Trailing-default-run trim for fixed-count (`count: N`) arrays, native and")
	f.line("// sequence-form alike: the canonical wire carries only elements [0, M'),")
	f.line("// where M' is one past the last non-default element; the decoder rebuilds")
	f.line("// [M', N) from the schema count. Dynamic (count-less) arrays never trim.")
	f.line("internal static class SofabFixedArray {")
	if genT {
		// Integer/enum/bitfield/boolean elements reach here as their integer wire
		// image, where EqualityComparer<T> is exact bit-pattern equality.
		f.line("    internal static T[] TrimTail<T>(T[] a) where T : struct {")
		f.line("        int n = a.Length;")
		f.line("        var zero = default(T);")
		f.line("        var eq = EqualityComparer<T>.Default;")
		f.line("        while (n > 0 && eq.Equals(a[n - 1], zero)) n--;")
		f.line("        if (n == a.Length) return a;")
		f.line("        var outp = new T[n];")
		f.line("        Array.Copy(a, outp, n);")
		f.line("        return outp;")
		f.line("    }")
	}
	if f32 {
		f.line("    internal static float[] TrimTailF32(float[] a) {")
		f.line("        int n = a.Length;")
		f.line("        while (n > 0 && BitConverter.SingleToInt32Bits(a[n - 1]) == 0) n--;")
		f.line("        if (n == a.Length) return a;")
		f.line("        var outp = new float[n];")
		f.line("        Array.Copy(a, outp, n);")
		f.line("        return outp;")
		f.line("    }")
	}
	if f64 {
		f.line("    internal static double[] TrimTailF64(double[] a) {")
		f.line("        int n = a.Length;")
		f.line("        while (n > 0 && BitConverter.DoubleToInt64Bits(a[n - 1]) == 0) n--;")
		f.line("        if (n == a.Length) return a;")
		f.line("        var outp = new double[n];")
		f.line("        Array.Copy(a, outp, n);")
		f.line("        return outp;")
		f.line("    }")
	}
	// Wrapper-array narrowing (generator#248). These return M — one past the last
	// element differing from the element default — which is what a `count: N`
	// wrapper array's canonical wire carries, "even for sequence-form elements"
	// (MESSAGE_SPEC §3/§5.1). Marshal loops to M, so the trailing all-default run
	// is never framed; M == 0 writes no child at all, leaving the lazily-opened
	// wrapper to be dropped and the whole field omitted (§2). An INTERIOR
	// all-default element still gets its frame: element presence is what carries
	// the array's length. A string/blob element is a leaf the writer already omits
	// individually, so narrowing its run cannot change the bytes — it exists so
	// the writer and the all-default predicate are computed from ONE expression
	// (elemTrimExpr) and cannot drift apart.
	if str {
		f.line("    internal static int TrimStrs(List<string> a) {")
		f.line("        int n = a.Count;")
		f.line("        while (n > 0 && string.IsNullOrEmpty(a[n - 1])) n--;")
		f.line("        return n;")
		f.line("    }")
	}
	if blob {
		f.line("    internal static int TrimBlobs(List<byte[]> a) {")
		f.line("        int n = a.Count;")
		f.line("        while (n > 0 && (a[n - 1] == null || a[n - 1].Length == 0)) n--;")
		f.line("        return n;")
		f.line("    }")
	}
	if rows {
		f.line("    internal static int TrimRows<T>(List<List<T>> a) {")
		f.line("        int n = a.Count;")
		f.line("        while (n > 0 && (a[n - 1] == null || a[n - 1].Count == 0)) n--;")
		f.line("        return n;")
		f.line("    }")
	}
	if fill {
		// Construction-time materialization for a `count: N` WRAPPER array — the
		// counterpart of the zero-filled `new T[N]` a fixed-count NATIVE array gets
		// in its own initializer. `mk` is called per element rather than one value
		// being repeated: a struct/union or nested-row element is mutable, so N
		// copies of one reference would alias.
		f.line("    internal static List<T> Filled<T>(int n, Func<T> mk) {")
		f.line("        var l = new List<T>(n);")
		f.line("        for (int i = 0; i < n; i++) l.Add(mk());")
		f.line("        return l;")
		f.line("    }")
	}
	f.line("}")
	f.blank()
}

func (g *gen) emitEnum(f *cfile, nt *ir.NamedType) {
	f.line("public enum %s : %s {", g.typeName(nt.Key), enumBacking(nt))
	for _, c := range nt.Consts {
		emitDoc(f, "    ", c.Description)
		f.line("    %s = %d,", exported(c.Name), c.Value)
	}
	f.line("}")
	f.blank()
}

func (g *gen) emitBitfield(f *cfile, nt *ir.NamedType) {
	f.line("[Flags]")
	f.line("public enum %s : %s {", g.typeName(nt.Key), bitfieldBacking(nt))
	for _, fl := range nt.Flags {
		emitDoc(f, "    ", flagDoc(fl))
		f.line("    %s = %d,", exported(fl.Name), uint64(1)<<uint(fl.Pos))
	}
	f.line("}")
	f.blank()
}

func (g *gen) emitClass(f *cfile, key, name, summary string, fields []*ir.Field, isMessage bool) {
	emitDoc(f, "", summary)
	f.line("public sealed class %s {", name)
	for _, fld := range fields {
		emitDoc(f, "    ", fieldDoc(fld))
		if fld.Deprecated {
			f.line("    [Obsolete]")
		}
		f.line("    public %s %s%s;", g.csType(fld), csIdent(fld.Name), g.csInit(fld))
	}
	// Hoist each native array's omit-compare default into a static: Marshal only
	// ever reads it, so one shared instance suffices and encode stops allocating
	// a fresh literal (a `count: N` field's default is N elements long — for a
	// large N that per-call allocation would dominate). The mutable per-object
	// initializer above stays a fresh allocation.
	for _, fld := range fields {
		if def, ok := g.csArrayCompareDefault(fld); ok {
			f.line("    private static readonly %s %s = %s;", g.csType(fld), arrDefName(fld), def)
		}
	}
	f.blank()

	// Marshal. Generated marshal legitimately reads fields marked [Obsolete];
	// silence the CS0618 deprecation warning around that internal access.
	dep := hasDeprecatedDirect(fields)
	f.line("    public void Marshal(OStream os) {")
	if dep {
		f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
	}
	for _, fld := range fields {
		g.emitMarshal(f, fld)
	}
	if dep {
		f.line("#pragma warning restore 618")
	}
	f.line("    }")

	g.emitIsDefault(f, fields, dep)
	if !isMessage && g.trimElems[key] {
		g.emitTrimTail(f, name)
	}

	if isMessage {
		ms := g.messageSize(name, fields)
		if !ms.Bounded {
			f.line("    // Configured ceiling (max_message_size): an unbounded field means this")
			f.line("    // size is imposed, not derived from the schema.")
			f.line("    public const int MaxSizeLimit = %d;", ms.Size)
			f.line("    public const int MaxSize = MaxSizeLimit;")
		} else {
			f.line("    public const int MaxSize = %d;", ms.Size)
		}
		f.line("    // Per-thread scratch buffer: Encode() marshals into it and returns an")
		f.line("    // exact-size copy, so the worst-case buffer is not re-allocated (and")
		f.line("    // zeroed) on every call. Do not call Encode() reentrantly from a")
		f.line("    // Marshal() override on the same thread.")
		f.line("    [ThreadStatic] private static byte[] _encScratch;")
		f.line("    public byte[] Encode() {")
		f.line("        var buf = _encScratch ??= new byte[MaxSize];")
		f.line("        var os = new OStream(buf);")
		f.line("        Marshal(os);")
		f.line("        var outp = new byte[os.BytesUsed];")
		f.line("        Array.Copy(buf, outp, os.BytesUsed);")
		f.line("        return outp;")
		f.line("    }")
		// Best-effort decode: kept for back-compat. It discards Feed's
		// DecodeStatus, so a truncated message is indistinguishable from a
		// COMPLETE one — prefer TryDecode when that verdict matters
		// (generator#105).
		f.line("    public static %s Decode(byte[] data) {", name)
		f.line("        var m = new %s();", name)
		f.line("        var v = new %sVisitor(m);", name)
		f.line("        new IStream().Feed(data, 0, data.Length, v);")
		f.line("        return m;")
		f.line("    }")
		// Status-surfacing one-shot decode (MESSAGE_SPEC §7): returns the
		// corelib's terminal DecodeStatus — Complete at a clean field boundary,
		// Incomplete when the bytes end inside a field or an open sequence.
		// Malformed input throws SofabException (Invalid) from Feed. msg always
		// receives the fields decoded so far; on Incomplete the caller owns
		// end-of-input and decides whether truncation is an error.
		f.line("    public static DecodeStatus TryDecode(byte[] data, out %s msg) {", name)
		f.line("        msg = new %s();", name)
		f.line("        return new IStream().Feed(data, 0, data.Length, new %sVisitor(msg));", name)
		f.line("    }")
	}
	f.line("}")
	f.blank()

	if isMessage {
		// The flat-visitor decode writes into reachable fields, including any
		// marked [Obsolete] (message-level or nested struct/union); silence the
		// CS0618 deprecation warning around the generated decode.
		depVis := framesHaveDeprecated(g.frames(&ir.Message{Name: name, Fields: fields}))
		if depVis {
			f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
		}
		g.emitVisitor(f, name, fields)
		if depVis {
			f.line("#pragma warning restore 618")
			f.blank()
		}
	}
}

// emitIsDefault emits the class's all-default predicate. It is the exact negation
// of what Marshal writes: the object is default iff Marshal would emit no child at
// all, evaluated per field and recursively (MESSAGE_SPEC §2). Every generated class
// carries it so that a `count: N` wrapper array can find M — one past its last
// non-default element — BEFORE opening the element loop (§3/§5.1), which the
// implicit "no child was written" test the lazy framing performs cannot answer in
// time. Keep this in lockstep with emitMarshal: a predicate that disagrees with the
// writer either drops an element that is on the wire or keeps one that is not.
// `dep` carries emitMarshal's CS0618 guard: the predicate reads the very same
// members, including any marked [Obsolete].
func (g *gen) emitIsDefault(f *cfile, fields []*ir.Field, dep bool) {
	f.line("    public bool IsDefault() {")
	if dep {
		f.line("#pragma warning disable 618 // internal access to a member marked [Obsolete]")
	}
	for _, fld := range fields {
		f.line("        if (!(%s)) return false;", g.fieldIsDefaultExpr(fld))
	}
	if dep {
		f.line("#pragma warning restore 618")
	}
	f.line("        return true;")
	f.line("    }")
}

// emitTrimTail emits the static narrowing helper for a class used as the element
// of a `count: N` wrapper array: M, one past the last element differing from the
// element default (MESSAGE_SPEC §3/§5.1). A null element is the element default —
// Marshal materializes it as `new T()` — so it trims like an all-default one.
func (g *gen) emitTrimTail(f *cfile, name string) {
	f.line("    // The number of elements a `count: N` array of this type puts on the")
	f.line("    // wire: one past its last element differing from the element default.")
	f.line("    internal static int TrimTail(List<%s> a) {", name)
	f.line("        int n = a.Count;")
	f.line("        while (n > 0 && (a[n - 1] == null || a[n - 1].IsDefault())) n--;")
	f.line("        return n;")
	f.line("    }")
}

// fieldIsDefaultExpr is the boolean expression "this field equals its default",
// i.e. the negation of emitMarshal's write guard for the same field.
func (g *gen) fieldIsDefaultExpr(fld *ir.Field) string {
	acc := "this." + csIdent(fld.Name)
	switch fld.Kind {
	case ir.KindBlob:
		if g.csDefaultValue(fld) == "Array.Empty<byte>()" {
			return fmt.Sprintf("%s == null || %s.Length == 0", acc, acc)
		}
		return fmt.Sprintf("System.Linq.Enumerable.SequenceEqual(%s ?? Array.Empty<byte>(), %s)", acc, g.csDefaultValue(fld))
	case ir.KindStruct, ir.KindUnion:
		// Lazily framed: the frame survives iff the nested Marshal wrote a child,
		// which is exactly "the nested object is not default".
		return fmt.Sprintf("(%s ?? new %s()).IsDefault()", acc, g.typeName(fld.Ref.Key))
	case ir.KindArray:
		return g.arrayIsDefaultExpr(fld, acc)
	}
	return fmt.Sprintf("%s == %s", acc, g.csDefaultValue(fld))
}

// arrayIsDefaultExpr mirrors emitMarshalArray: a native array compares against the
// materialized default its omit-guard uses, a wrapper array is default iff it would
// write no child — i.e. iff its narrowed length M is 0.
func (g *gen) arrayIsDefaultExpr(fld *ir.Field, acc string) string {
	if nativeArrayElem(fld.Elem) {
		if _, ok := g.csArrayCompareDefault(fld); ok {
			return fmt.Sprintf("System.Linq.Enumerable.SequenceEqual(%s, %s)", acc, arrDefName(fld))
		}
		if primArrayElem(fld.Elem) {
			return fmt.Sprintf("%s == null || %s.Length == 0", acc, acc)
		}
		return fmt.Sprintf("%s.Count == 0", acc)
	}
	// Wrapper array: no child is written iff every element is the element default.
	// fld.HasCount must be threaded through unchanged — narrowing here but not in
	// the marshal loop (or the reverse) is exactly the drift this shared helper
	// exists to prevent: it would call a dynamic [ {} ] "default" while the writer
	// still frames its one empty element, omitting a field that is on the wire.
	return g.elemTrimExpr(acc, fld.Elem, fld.ElemRef, fld.ElemItems, fld.HasCount) + " == 0"
}

// hasDeprecatedDirect reports whether any direct field of a class is deprecated,
// so its Marshal reads a member marked [Obsolete] and needs the CS0618 guard.
func hasDeprecatedDirect(fields []*ir.Field) bool {
	for _, fld := range fields {
		if fld.Deprecated {
			return true
		}
	}
	return false
}

// framesHaveDeprecated reports whether any object-scope field reachable from a
// message (message-level or a nested struct/union) is deprecated, so the
// generated visitor writes into a member marked [Obsolete].
func framesHaveDeprecated(fs []frame) bool {
	for _, fr := range fs {
		if fr.isArr {
			continue
		}
		for _, fld := range fr.fields {
			if fld.Deprecated {
				return true
			}
		}
	}
	return false
}

func (g *gen) emitMarshal(f *cfile, fld *ir.Field) {
	acc := "this." + csIdent(fld.Name)
	var write string
	switch fld.Kind {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64, ir.KindBitfield:
		write = fmt.Sprintf("os.WriteUnsigned(%d, (ulong)%s);", fld.ID, acc)
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64, ir.KindEnum:
		write = fmt.Sprintf("os.WriteSigned(%d, (long)%s);", fld.ID, acc)
	case ir.KindBool:
		write = fmt.Sprintf("os.WriteBoolean(%d, %s);", fld.ID, acc)
	case ir.KindFP32:
		write = fmt.Sprintf("os.WriteFp32(%d, %s);", fld.ID, acc)
	case ir.KindFP64:
		write = fmt.Sprintf("os.WriteFp64(%d, %s);", fld.ID, acc)
	case ir.KindString:
		write = fmt.Sprintf("os.WriteString(%d, %s ?? \"\");", fld.ID, acc)
	case ir.KindBlob:
		// A blob is a leaf: omit when equal to its default (empty if none). The
		// decoder reconstructs the omitted field from its materialized default.
		// With an empty default the content compare degenerates to a length
		// check, sparing the LINQ SequenceEqual enumeration per call.
		if g.csDefaultValue(fld) == "Array.Empty<byte>()" {
			f.line("        if (%s != null && %s.Length != 0) { os.WriteBlob(%d, %s); }", acc, acc, fld.ID, acc)
			return
		}
		f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s ?? Array.Empty<byte>(), %s)) { os.WriteBlob(%d, %s ?? Array.Empty<byte>()); }", acc, g.csDefaultValue(fld), fld.ID, acc)
		return
	case ir.KindStruct, ir.KindUnion:
		// MESSAGE_SPEC S2: the != default test is per field and a sequence-typed
		// FIELD is no exception, so the frame is opened LAZILY -- the corelib holds
		// the header back until a child field appears. The nested Marshal omits every
		// child that equals its default, so "no child was written" IS "the object
		// equals its declared default", evaluated per field and recursively. The
		// dropping closer therefore makes an all-default nested object vanish instead
		// of reaching the wire as an empty wrapper frame.
		f.line("        os.WriteSequenceBeginLazy(%d); (%s ?? new %s()).Marshal(os); os.WriteSequenceEnd();", fld.ID, acc, g.typeName(fld.Ref.Key))
		return
	case ir.KindArray:
		g.emitMarshalArray(f, fld, acc)
		return
	}
	// Scalar/string/enum/bitfield leaf: always omit when equal to the default;
	// sparse encoding is canonical (MESSAGE_SPEC S2) and the decoder reconstructs
	// the omitted field from its default.
	f.line("        if (%s != %s) { %s }", acc, g.csDefaultValue(fld), write)
}

// arrDefName is the static holding a native array field's omit-compare default.
func arrDefName(fld *ir.Field) string { return "_arrdef_" + fld.Name }

// csArrayCompareDefault is the literal a native array field's value is compared
// against for whole-field omission, and ("", false) when the field has no
// materialized default (a dynamic array with no schema default, or a
// wrapper-sequence array, whose whole-field omission is the corelib's lazy frame
// rather than a compare here). It is exactly the field initializer, so an
// untouched field always compares equal and is omitted.
func (g *gen) csArrayCompareDefault(fld *ir.Field) (string, bool) {
	if fld.Kind != ir.KindArray {
		return "", false
	}
	if primArrayElem(fld.Elem) {
		return g.csPrimArrayLiteral(fld)
	}
	return g.csNativeArrayLiteral(fld)
}

func (g *gen) emitMarshalArray(f *cfile, fld *ir.Field, acc string) {
	// A native scalar array is a leaf field: omit it when equal to its default
	// (materialized in the field initializer), else when empty. A composite/
	// dynamic-element array is a wrapper sequence, opened lazily and closed by the
	// dropping end, so it disappears when no element reaches the wire.
	if primArrayElem(fld.Elem) {
		// Primitive array (T[]): written straight to the OStream overload with
		// no List.ToArray temporary.
		if _, ok := g.csArrayCompareDefault(fld); ok {
			f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s, %s)) {", acc, arrDefName(fld))
		} else {
			f.line("        if (%s != null && %s.Length != 0) {", acc, acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, true, fld.HasCount)
		f.line("        }")
		return
	}
	if nativeArrayElem(fld.Elem) {
		if _, ok := g.csArrayCompareDefault(fld); ok {
			f.line("        if (!System.Linq.Enumerable.SequenceEqual(%s, %s)) {", acc, arrDefName(fld))
		} else {
			f.line("        if (%s.Count != 0) {", acc)
		}
		g.marshalArray(f, "            ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, fld.HasCount)
		f.line("        }")
		return
	}
	// The field-level wrapper frame is dropped when no element is written, and
	// absence then reconstructs the field's default. That is correct because a
	// wrapper array's declared `default` is not materialized today (the generated
	// field initializer is the empty collection), so absent and explicitly-empty
	// denote the same value. If that gap is ever closed, this call needs a guard --
	// `if (value != default) { ... WriteSequenceEndKeep(); }` -- so that a value
	// differing from a non-empty default still reaches the wire as the empty
	// wrapper, the only encoding of "explicitly empty" (MESSAGE_SPEC S2, S3).
	g.marshalArray(f, "        ", fmt.Sprintf("%d", fld.ID), acc, fld.Elem, fld.ElemRef, fld.ElemItems, 0, false, fld.HasCount)
}

// trimExpr wraps a native array expression in the trailing-default-run trim a
// fixed-count array's canonical encoding requires (MESSAGE_SPEC §3). Only a
// declared `count: N` array is fixed-length; a dynamic (count-less) array has no
// N to refill from, so a trailing default element is significant and stays.
// `elem` is the kind of the expression's ELEMENTS as already lowered to the wire
// image (bool/enum/bitfield arrive here as their integer conversion).
func trimExpr(val string, elem ir.Kind, fixed bool) string {
	if !fixed {
		return val
	}
	switch elem {
	case ir.KindFP32:
		return fmt.Sprintf("SofabFixedArray.TrimTailF32(%s)", val)
	case ir.KindFP64:
		return fmt.Sprintf("SofabFixedArray.TrimTailF64(%s)", val)
	default:
		return fmt.Sprintf("SofabFixedArray.TrimTail(%s)", val)
	}
}

// elemTrimExpr is the number of elements a wrapper array actually writes: M, one
// past the last element differing from the element default, which is what its
// canonical wire carries (MESSAGE_SPEC §3/§5.1, "even for sequence-form
// elements"). Only a declared `count: N` array is fixed-length and may be
// narrowed — a DYNAMIC array has no N to refill from, so a trailing default
// ELEMENT is significant and must stay framed. Interior all-default elements are
// never dropped by this: element presence carries the length, so only the trailing
// run goes. Both the marshal loop and IsDefault run off this one expression, so
// the writer and the predicate cannot disagree.
func (g *gen) elemTrimExpr(val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, fixed bool) string {
	switch elem {
	case ir.KindString:
		return fmt.Sprintf("SofabFixedArray.TrimStrs(%s)", val)
	case ir.KindBlob:
		return fmt.Sprintf("SofabFixedArray.TrimBlobs(%s)", val)
	case ir.KindStruct, ir.KindUnion:
		if !fixed {
			return val + ".Count"
		}
		return fmt.Sprintf("%s.TrimTail(%s)", g.typeName(ref.Key), val)
	case ir.KindArray:
		if !fixed {
			return val + ".Count"
		}
		return fmt.Sprintf("SofabFixedArray.TrimRows(%s)", val)
	}
	return val + ".Count"
}

// marshalArray writes the list `val` as field `idExpr`. Numeric/enum/boolean/
// bitfield elements use the native array wire type (enum -> signed, boolean/
// bitfield -> unsigned, value-converted to the corelib's array element width);
// string/blob/struct/union/array elements lower to a wrapper sequence whose child
// ids are the 0-based index (per MESSAGE_SPEC). Recurses for nested arrays,
// depth-suffixing the loop var to avoid collisions. isPrim marks `val` as a
// primitive T[] field (written directly); inner rows of nested arrays stay
// List<T> and bridge via ToArray. `fixed` marks `val` as a top-level `count: N`
// field, whose trailing default run is trimmed off (MESSAGE_SPEC §3); nested
// recursion passes false — an inner row of an array-of-array is not fixed.
func (g *gen) marshalArray(f *cfile, ind, idExpr, val string, elem ir.Kind, ref *ir.TypeRef, items *ir.ArrayElem, depth int, isPrim, fixed bool) {
	iv := fmt.Sprintf("_i%d", depth)
	// The element loop runs to M, not to Count (generator#248): `nv` is declared in
	// the for-statement's own scope, so two array fields in one Marshal never
	// collide and the narrowing is evaluated exactly once per field.
	nv := fmt.Sprintf("_n%d", depth)
	loop := func(vals string) string {
		return fmt.Sprintf("for (int %s = 0, %s = %s; %s < %s; %s++)", iv, nv, vals, iv, nv, iv)
	}
	arr := val + ".ToArray()"
	if isPrim {
		arr = val
	}
	// MESSAGE_SPEC S2: every sequence is opened lazily; the CLOSER decides whether a
	// contentless one survives, and it is chosen statically from the position in the
	// schema. A wrapper array at depth 0 is a sequence-typed FIELD, so it closes with
	// the dropping end -- an all-default array is omitted and absence reconstructs
	// it. A nested row (depth > 0) is an array ELEMENT, and element presence is what
	// carries a dynamic array's length (S5.1), so it closes with the keeping end:
	// dropping it would change the decoded length, not merely the bytes.
	seqEnd := "WriteSequenceEnd"
	if depth > 0 {
		seqEnd = "WriteSequenceEndKeep"
	}
	switch elem {
	case ir.KindU8, ir.KindU16, ir.KindU32, ir.KindU64:
		f.line("%sos.WriteArrayUnsigned(%s, %s);", ind, idExpr, trimExpr(arr, elem, fixed))
	case ir.KindI8, ir.KindI16, ir.KindI32, ir.KindI64:
		f.line("%sos.WriteArraySigned(%s, %s);", ind, idExpr, trimExpr(arr, elem, fixed))
	case ir.KindFP32:
		f.line("%sos.WriteArrayFp32(%s, %s);", ind, idExpr, trimExpr(arr, elem, fixed))
	case ir.KindFP64:
		f.line("%sos.WriteArrayFp64(%s, %s);", ind, idExpr, trimExpr(arr, elem, fixed))
	case ir.KindEnum:
		// enum -> signed array at the enum's backing width (matches Go's typed array).
		// Trimming the converted integer image is equivalent to trimming the enums
		// (the element default is the 0 constant <-> integer 0).
		conv := fmt.Sprintf("Array.ConvertAll(%s.ToArray(), _x => (%s)_x)", val, enumBacking(ref.Target))
		f.line("%sos.WriteArraySigned(%s, %s);", ind, idExpr, trimExpr(conv, ir.KindI64, fixed))
	case ir.KindBitfield:
		conv := fmt.Sprintf("Array.ConvertAll(%s.ToArray(), _x => (%s)_x)", val, bitfieldBacking(ref.Target))
		f.line("%sos.WriteArrayUnsigned(%s, %s);", ind, idExpr, trimExpr(conv, ir.KindU64, fixed))
	case ir.KindBool:
		// boolean -> unsigned u8 array of 0/1. Trimming the 0/1 image is equivalent
		// to trimming the bools (false <-> 0).
		conv := fmt.Sprintf("Array.ConvertAll(%s.ToArray(), _x => _x ? (byte)1 : (byte)0)", val)
		f.line("%sos.WriteArrayUnsigned(%s, %s);", ind, idExpr, trimExpr(conv, ir.KindU8, fixed))
	case ir.KindString:
		// A string element is a leaf: omit it when equal to the element default
		// (empty), leaving an id gap the decoder restores (MESSAGE_SPEC S2).
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s { if ((%s[%s] ?? \"\") != \"\") os.WriteString(%s, %s[%s] ?? \"\"); }", ind, loop(g.elemTrimExpr(val, elem, ref, items, fixed)), val, iv, iv, val, iv)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindBlob:
		// A blob element is a leaf: omit it when equal to the element default
		// (empty), leaving an id gap the decoder restores (MESSAGE_SPEC S2).
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s { if ((%s[%s] ?? Array.Empty<byte>()).Length != 0) os.WriteBlob(%s, %s[%s] ?? Array.Empty<byte>()); }", ind, loop(g.elemTrimExpr(val, elem, ref, items, fixed)), val, iv, iv, val, iv)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindStruct, ir.KindUnion:
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s {", ind, loop(g.elemTrimExpr(val, elem, ref, items, fixed)))
		// An INTERIOR element is framed unconditionally: dropping it would leave an
		// id gap and change the decoded length, not just the bytes (S5.1). The
		// TRAILING all-default run is already gone -- the loop runs to M, not to
		// Count (S3/S5.1) -- and M == 0 writes no child at all, so the lazily-opened
		// wrapper is dropped and the whole field is omitted (S2).
		f.line("%s    os.WriteSequenceBeginLazy(%s); (%s[%s] ?? new %s()).Marshal(os); os.WriteSequenceEndKeep();", ind, iv, val, iv, g.typeName(ref.Key))
		f.line("%s}", ind)
		f.line("%sos.%s();", ind, seqEnd)
	case ir.KindArray:
		f.line("%sos.WriteSequenceBeginLazy(%s);", ind, idExpr)
		f.line("%s%s {", ind, loop(g.elemTrimExpr(val, elem, ref, items, fixed)))
		g.marshalArray(f, ind+"    ", iv, fmt.Sprintf("%s[%s]", val, iv), items.Elem, items.ElemRef, items.ElemItems, depth+1, false, false)
		f.line("%s}", ind)
		f.line("%sos.%s();", ind, seqEnd)
	}
}
