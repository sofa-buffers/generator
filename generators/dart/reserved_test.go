var update = flag.Bool("update", false, "rewrite tests/conformance/dart/reserved.{yaml,json} from the reserved-name list")

// reservedNames is every name on the Dart list, sorted.
func reservedNames() []string {
	var names []string
	for _, set := range []map[string]bool{dartKeywords, dartMembers, dartObjectMembers, dartOuterNames, unionFixed} {
		for n := range set {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	return names
}

// reservedYAML is a schema that uses every reserved name as a field of a message,
// of a nested struct, and as an option of a union. Names are quoted: `true`,
// `false` and `null` are YAML scalars.
func reservedYAML(names []string) string {
	var b strings.Builder
	b.WriteString("# Generated by TestReservedSchemaFile from generators/dart/reserved.go;\n")
	b.WriteString("# do not edit. Regenerate: go test ./generators/dart -run TestReservedSchemaFile -update\n")
	b.WriteString("# The collision test: every reserved name as a field must analyze clean and round-trip.\n")
	// A union option is left out where its has<Option> accessor repeats an
	// earlier one's (`Enum` and `enum` are both hasEnum): a generation error by
	// design.
	var fields strings.Builder
	var opts []string
	bases := map[string]bool{}
	for i, n := range names {
		fmt.Fprintf(&fields, "      %q: { id: %d, type: u8 }\n", n, i)
		if b := strings.ToUpper(n[:1]) + n[1:]; !bases[b] {
			bases[b] = true
			opts = append(opts, fmt.Sprintf("%q: { id: %d, type: u8 }", n, i))
		}
	}
	k := len(names)
	fmt.Fprintf(&b, `version: 1
$defs:
  struct:
    Inner:
%smessages:
  m:
    payload:
%s      inner: { id: %d, type: struct, fields: { $ref: '#/$defs/struct/Inner' } }
      u:     { id: %d, type: union, oneof: { %s } }
`, fields.String(), fields.String(), k, k+1, strings.Join(opts, ", "))
	return b.String()
}

// reservedJSON is the harness input for m: every reserved field, nested one and
// the last union option at a non-default value, each under its schema name.
func reservedJSON(names []string) string {
	top := map[string]any{}
	inner := map[string]any{}
	for i, n := range names {
		top[n] = i + 1
		inner[n] = i + 2
	}
	top["inner"] = inner
	top["u"] = map[string]any{"yield": 9} // an option the schema keeps (not a has<X> repeat)
	b, _ := json.MarshalIndent(top, "", "  ")
	return string(b) + "\n"
}

// TestReservedSchemaFile keeps the checked-in collision schema and its input in
// step with the list: the conformance suite analyzes that file with
// --fatal-infos, compiles and round-trips it (tests/conformance/dart/run.sh), so
// a name added to reserved.go is covered once the file is regenerated -- and
// this test fails until it is.
func TestReservedSchemaFile(t *testing.T) {
	names := reservedNames()
	for path, want := range map[string]string{
		"../../tests/conformance/dart/reserved.yaml": reservedYAML(names),
		"../../tests/conformance/dart/reserved.json": reservedJSON(names),
	} {
		if *update {
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s is out of step with the reserved-name list; regenerate with -update", path)
		}
	}
}

// loadSchema runs load->resolve->IR over a definition file (Load, so a
// cross-file $ref resolves), stopping short of generation.
func loadSchema(t *testing.T, def string) *ir.Schema {
	t.Helper()
	doc, err := parser.Load(def)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := doc.Resolve(); err != nil {
		t.Fatal(err)
	}
	s, err := model.Build(doc)
	if err != nil {
		t.Fatal(err)
	}
	if err := analysis.Analyze(s); err != nil {
		t.Fatal(err)
	}
	return s
}

// TestReservedNamesAreMangled: every name on the list is a member with a
// trailing underscore -- except the members only a union has -- in the message
// and in the nested struct.
func TestReservedNamesAreMangled(t *testing.T) {
	names := reservedNames()
	out := genFor(t, writeDef(t, reservedYAML(names)), map[string]any{})
	for _, n := range names {
		want := n + "_"
		if unionFixed[n] {
			want = n
		}
		if got := len(regexp.MustCompile(`(?m)^  int `+regexp.QuoteMeta(want)+` = 0;$`).FindAllString(out, -1)); got != 2 {
			t.Errorf("field %q is the member %s in %d of the 2 classes", n, want, got)
		}
	}
}

// TestFieldNameCollision: two fields that give one member (`encode` is mangled to
// `encode_`; `f`'s bits companion is fFp32Bits) and a field spelled like a
// generated class are a generation error, not a class that fails to analyze.
func TestFieldNameCollision(t *testing.T) {
	for _, src := range []string{
		"version: 1\nmessages:\n  m:\n    payload:\n      encode: { id: 0, type: u8 }\n      encode_: { id: 1, type: u8 }\n",
		"version: 1\nmessages:\n  m:\n    payload:\n      f: { id: 0, type: fp32 }\n      fFp32Bits: { id: 1, type: u8 }\n",
		"version: 1\nmessages:\n  m:\n    payload:\n      M: { id: 0, type: u8 }\n",
		"version: 1\nmessages:\n  m:\n    payload:\n      MDecoder: { id: 0, type: u8 }\n",
		"version: 1\n$defs:\n  struct:\n    P: { x: { id: 0, type: u8 } }\nmessages:\n  m:\n    payload:\n      StructP: { id: 0, type: struct, fields: { $ref: '#/$defs/struct/P' } }\n",
		// a union option spelled like a generated class
		"version: 1\n$defs:\n  struct:\n    P: { x: { id: 0, type: u8 } }\nmessages:\n  m:\n    payload:\n      u: { id: 0, type: union, oneof: { p: { id: 0, type: struct, fields: { $ref: '#/$defs/struct/P' } }, StructP: { id: 1, type: u8 } } }\n",
		// enum constants: a mangled keyword on a literal, and the class's own name
		"version: 1\n$defs:\n  enum:\n    E: { class: 0, class_: 1 }\nmessages:\n  m:\n    payload:\n      e: { id: 0, type: enum, enum: { $ref: '#/$defs/enum/E' } }\n",
		"version: 1\n$defs:\n  enum:\n    E: { EnumE: 0 }\nmessages:\n  m:\n    payload:\n      e: { id: 0, type: enum, enum: { $ref: '#/$defs/enum/E' } }\n",
	} {
		_, err := (&Backend{}).Generate(loadSchema(t, writeDef(t, src)), map[string]any{})
		if err == nil || !(strings.Contains(err.Error(), "both generate") || strings.Contains(err.Error(), "which is also") || strings.Contains(err.Error(), "its own class")) {
			t.Errorf("want a collision error for:\n%s\ngot %v", src, err)
		}
	}
}

var (
	dartBlank  = regexp.MustCompile(`(?s)/\*.*?\*/|//[^\n]*|'''.*?'''|'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"`)
	dartClass  = regexp.MustCompile(`(?m)^class ([A-Z]\w*)[^{\n]*\{`)
	dartMember = regexp.MustCompile(`^\s*(?:@\w+\s+)*(?:(?:static|final|const|late|external|factory|covariant)\s+)*(?:[\w<>?,\[\] ]+?\s+)?(?:get\s+|set\s+)?(\w+)\s*(?:\(|=>|=|;|\{)`)
	dartTok    = regexp.MustCompile(`(?:^|[^\w.$])([A-Za-z_]\w*)`)
	dartDerive = regexp.MustCompile(`^(has|mutable)[A-Z]|Id$`)
	dartConst  = regexp.MustCompile(`(?m)^const \w+ (\w+)`)
)

// TestDartNamesInScope is the drift guard: over the corpus, realworld set and
// example, every member a public generated class declares beyond the schema's
// fields must be on dartMembers (or be a union's own/derived member, or `_`),
// and every OUTER name its body uses -- an upper-case name, the `sofab` prefix,
// a top-level constant -- must be on the list or be a generated class (which
// checkFieldNames guards). A class body that starts to use `Int32List` or a new
// top-level constant fails here until the name is reserved.
func TestDartNamesInScope(t *testing.T) {
	defs, _ := filepath.Glob("../../tests/matrix/corpus/defs/*.yaml")
	rw, _ := filepath.Glob("../../examples/messages/realworld/*.yaml")
	defs = append(append(defs, rw...), "../../examples/messages/example.yaml")
	for _, def := range defs {
		s := loadSchema(t, def)
		g := &gen{schema: s}
		types := g.dartTypeNames(s)
		fields := map[string]bool{}
		for _, m := range s.Messages {
			for _, f := range m.Fields {
				fields[dartIdent(f.Name)] = true
				fields[fp32BitsField(f.Name)] = true
			}
		}
		for key, nt := range s.Named {
			for _, f := range nt.Fields {
				fields[dartIdent(f.Name)] = true
				fields[fp32BitsField(f.Name)] = true
				if nt.Category == ir.CatUnion {
					fields[unionOptProp(f.Name, g.typeName(key))] = true
				}
			}
		}
		files, err := (&Backend{}).Generate(s, map[string]any{})
		if err != nil {
			t.Fatalf("%s: %v", def, err)
		}
		src := dartBlank.ReplaceAllString(string(files[0].Content), `''`)
		consts := map[string]bool{}
		for _, m := range dartConst.FindAllStringSubmatch(src, -1) {
			consts[m[1]] = true
		}
		for _, loc := range dartClass.FindAllStringSubmatchIndex(src, -1) {
			// A message's Decoder class keeps its own state; no schema field is
			// in scope there.
			if strings.HasPrefix(types[src[loc[2]:loc[3]]], "the decoder class") {
				continue
			}
			depth := 1
			var body strings.Builder
			for _, line := range strings.Split(src[loc[1]:], "\n") {
				if depth == 0 {
					break
				}
				if depth == 1 {
					if m := dartMember.FindStringSubmatch(line); m != nil {
						n := m[1]
						if !(fields[n] || types[n] != "" || strings.HasPrefix(n, "_") || dartDerive.MatchString(n) || dartMembers[n] || dartObjectMembers[n] || unionFixed[n] || dartKeywords[n]) {
							t.Errorf("%s: member %s is not on dartMembers", filepath.Base(def), n)
						}
					}
				}
				depth += strings.Count(line, "{") - strings.Count(line, "}")
				body.WriteString(line + "\n")
			}
			for _, m := range dartTok.FindAllStringSubmatch(body.String(), -1) {
				n := m[1]
				outer := n[0] >= 'A' && n[0] <= 'Z' || n == "sofab" || consts[n]
				if outer && !(dartKeywords[n] || dartOuterNames[n] || types[n] != "") {
					t.Errorf("%s: outer name %s is not on the list", filepath.Base(def), n)
				}
			}
		}
	}
}
